<h3>Myth 4: Tilting the head back for a nosebleed</h3>

<p><strong>Why it's harmful:</strong> Tilting the head back doesn't stop the bleeding. It sends blood down the throat, where it can cause vomiting, and in a child or a drowsy person it can be breathed into the lungs.</p>

<p><strong>Do this instead:</strong> Sit the person down and lean them slightly forward. Pinch the soft part of the nose, just below the bony bridge, firmly for 10 to 15 minutes without letting go, while they breathe through the mouth and spit out any blood. Get medical help if it is still bleeding after 15 to 20 minutes of firm pressure, the bleeding is heavy, it followed a blow to the head, or the person takes blood-thinning medicine.</p>

<h2>Myths about seizures and unconsciousness</h2>

<h3>Myth 5: A shoe, onion or keys, or something in the mouth during a seizure</h3>

<p><strong>Why it's harmful:</strong> Smelling a shoe or an onion, or holding keys or an iron object in the hand, does nothing to stop a seizure; it only crowds the person. Forcing a spoon, cloth or fingers into the mouth can break teeth, block the airway and get your fingers badly bitten. A person cannot swallow their tongue during a fit.</p>

<p><strong>Do this instead:</strong> Note the time. Move hard or sharp objects away, cushion the head with something soft and loosen tight clothing. Don't hold them down. When the jerking stops, roll them onto their side. Call an ambulance if the seizure lasts more than 5 minutes, another one follows, it is their first seizure, they are injured, or they don't wake up normally. Our <a href="<?= post_url('seizure-first-aid') ?>">seizure first-aid guide</a> covers every step.</p>

<h3>Myth 6: A cold bath for a child's febrile seizure</h3>

<p><strong>Why it's harmful:</strong> Cold water does not stop the seizure. It can cause choking and distress, and a child should never be put in a bath or bucket during a fit.</p>

<p><strong>Do this instead:</strong> Lay the child on their side on a soft surface, away from hard edges, and remove extra clothing and blankets. Put nothing in the mouth, and time the seizure. Call an ambulance if it lasts more than 5 minutes, it is the child's first fit, or they have trouble breathing afterwards. Once they are fully awake, give fever medicine only as your doctor advises.</p>

<h3>Myth 7: Splashing water on, or giving water to, an unconscious person</h3>

<p><strong>Why it's harmful:</strong> Someone who is truly unconscious won't wake up from a splash of cold water, so it wastes time. Pouring water, juice or sugar water into their mouth is far more dangerous: they can't swallow properly, so it can go into the lungs and choke them.</p>

<p><strong>Do this instead:</strong> Shout and tap their shoulders. If they don't respond, call an ambulance and check their breathing. If they are breathing normally, turn them onto their side in the recovery position; if they aren't, start CPR. Give nothing by mouth until they are fully awake. Read <a href="<?= post_url('unconscious-person-first-aid') ?>">what to do when someone is unconscious</a>.</p>

<h2>Myths about accidents, drowning and poisoning</h2>

<h3>Myth 8: Lifting accident victims by the arms and legs into a car</h3>

<p><strong>Why it's harmful:</strong> Kind bystanders often bundle accident victims into an auto or car by the arms and legs. If the neck or back is injured, this bending and twisting can damage the spinal cord and cause permanent paralysis.</p>

<p><strong>Do this instead:</strong> Call 112 or an ambulance. Unless the person is in immediate danger, such as from fire or traffic, leave them where they are and keep the head and neck still. Press on any heavy bleeding. If they must be moved, several people should support the head, neck and body in a straight line. See our <a href="<?= post_url('road-accident-first-aid') ?>">road accident first-aid guide</a>.</p>

<h3>Myth 9: Pressing the stomach or hanging someone upside down after drowning</h3>

<p><strong>Why it's harmful:</strong> The danger in drowning is lack of oxygen, not water in the stomach. Pressing the belly, turning the person upside down or spinning them wastes vital time and can make them vomit into their lungs.</p>

<p><strong>Do this instead:</strong> Get the person out of the water without putting yourself at risk: reach with a pole or throw a rope or float rather than jumping in. If they aren't breathing normally, call for help and start CPR straight away. Rescue breaths matter especially in drowning, so give them if you've been trained; if not, chest compressions alone are far better than nothing. Everyone rescued from drowning needs a hospital check. Read our <a href="<?= post_url('drowning-first-aid') ?>">drowning first-aid guide</a>.</p>

<h3>Myth 10: Making someone vomit after poisoning</h3>

<p><strong>Why it's harmful:</strong> Salt water, soapy water or fingers down the throat can do more harm than the poison. Corrosives such as toilet cleaner or acid burn the food pipe a second time on the way up. Kerosene, petrol and other oily liquids can be breathed into the lungs while vomiting, causing serious lung damage.</p>

<p><strong>Do this instead:</strong> Call an ambulance and keep the bottle, label, tablet strip or plant to show the doctors. If the poison is on the skin or in the eyes, rinse with plenty of running water. Don't give anything to eat or drink unless a doctor or poison information centre tells you to. If they are drowsy, put them in the recovery position. Our <a href="<?= post_url('poisoning-first-aid') ?>">poisoning first-aid guide</a> explains more.</p>

<h2>Myths about heart attacks and strokes</h2>

<h3>Myth 11: Eno or an antacid for chest pain, then wait</h3>

<p><strong>Why it's harmful:</strong> A heart attack can feel exactly like acidity or gas: burning or heaviness in the chest or upper stomach, sometimes with burping or nausea. Taking an antacid and waiting for it to settle is a common reason heart attack patients reach hospital late, after more heart muscle has died.</p>

<p><strong>Do this instead:</strong> Treat sudden chest pain as a heart attack until a doctor says otherwise. Call an ambulance, sit the person down and keep them still. If they are an adult and not allergic, give one regular-strength aspirin to chew, after checking with the dispatcher. Ask for a <a href="<?= link_to('cardiac') ?>">cardiac ambulance with a defibrillator</a>, and read how to tell <a href="<?= post_url('chest-pain-heart-attack-or-gas') ?>">heart attack pain from gas or acidity</a>.</p>

<h3>Myth 12: Giving water, food or medicine to someone having a stroke</h3>

<p><strong>Why it's harmful:</strong> A stroke often weakens the muscles used for swallowing, so water, tea, food or tablets can go into the lungs and cause choking or pneumonia. Aspirin can be dangerous too, because some strokes are caused by bleeding in the brain.</p>

<p><strong>Do this instead:</strong> Learn BE FAST: Balance, Eyes, Face drooping, Arm weakness, Speech difficulty, Time to call. Note when symptoms started, give nothing by mouth, and call an ambulance so the patient reaches a hospital with a CT scanner quickly. Read our <a href="<?= post_url('stroke-first-aid-be-fast') ?>">BE FAST stroke first-aid guide</a>.</p>

<h2>What to do instead in any emergency: step by step</h2>

<h3>Step 1: Make sure it's safe</h3>

<p>Check for traffic, fire, live wires, gas or deep water before you go close. A second casualty helps no one.</p>

<h3>Step 2: Call for help first</h3>

<p>Dial 112 or an ambulance helpline, put the phone on speaker and follow the dispatcher's instructions.</p>

<h3>Step 3: Check response and breathing</h3>

<p>Tap their shoulders and speak loudly. Look for normal breathing for up to 10 seconds.</p>

<h3>Step 4: Give simple, proven first aid</h3>

<p>Cool water for burns, firm pressure for bleeding, the side position for an unconscious person who is breathing, and stillness for injuries and snakebites.</p>

<h3>Step 5: Politely stop the remedies</h3>

<p>Ask well-meaning relatives and onlookers to step back, give nothing by mouth, and keep the space clear for the crew.</p>

