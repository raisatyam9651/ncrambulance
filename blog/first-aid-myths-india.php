<h2>If the person gets worse: CPR and the recovery position</h2>

<p>If the person stops responding and isn't breathing normally, or is only gasping, start CPR immediately. Put the heel of your hand in the centre of the chest, your other hand on top, and push hard and fast, 100 to 120 times a minute, until the ambulance crew takes over. Without CPR, a person whose heart has stopped will not survive, so trying is always better than doing nothing.</p>

<p>If they are unconscious but breathing normally, and you don't suspect a neck or back injury, roll them onto their side, tilt the head back slightly to keep the airway open, and keep checking their breathing until help arrives.</p>

