<p>Toothpaste on a burn. An onion or a shoe held under the nose during a fit. A glass of water for someone who has fainted. These remedies are passed down with love in Indian homes, usually by the person who stays calmest in a crisis. The trouble is that some of them waste precious minutes, and a few cause real harm.</p>

<p>This guide goes through 12 of the most common first-aid myths in India: why each one is harmful, what to do instead, and where to find the full guide. Whatever the emergency, the first step never changes: call 112 or an <a href="<?= link_to('emergency') ?>">emergency ambulance service</a>, then give the right first aid while you wait.</p>

<h2>Myths about burns, bites and nosebleeds</h2>

<h3>Myth 1: Toothpaste, ghee or ice on a burn</h3>

<p><strong>Why it's harmful:</strong> Toothpaste, ghee, butter and oil hold heat in the skin, contaminate the wound and have to be scrubbed off painfully in hospital. Ice is too cold and can damage burnt skin further.</p>

<p><strong>Do this instead:</strong> Cool the burn under cool running tap water for 20 minutes. Remove rings, watches and tight clothing near the burn unless they are stuck to it, then cover it loosely with cling film or a clean, non-fluffy cloth. Get medical help for large or deep burns, burns on the face, hands, feet or genitals, and burns in children. Read our <a href="<?= post_url('burns-first-aid') ?>">complete guide to burns first aid</a>.</p>

<h3>Myth 2: Chilli, turmeric or lime on a dog bite</h3>

<p><strong>Why it's harmful:</strong> Chilli powder, turmeric, lime, oil or mud irritate the wound, add dirt and germs, and do nothing against rabies. Worse, they give families false comfort, so the vaccine gets delayed.</p>

<p><strong>Do this instead:</strong> Wash the wound straight away with soap and plenty of running water for about 15 minutes, then apply an antiseptic. Go to a hospital the same day for the anti-rabies vaccine and any other injections the doctor advises, even for a scratch from a pet dog. Rabies is almost always fatal once symptoms start, but timely treatment prevents it. See our <a href="<?= post_url('dog-bite-first-aid') ?>">dog bite first-aid guide</a>.</p>

<h3>Myth 3: Cutting, sucking, a tight tourniquet or a tantrik for snakebite</h3>

<p><strong>Why it's harmful:</strong> Cutting the bite causes bleeding and infection. Sucking doesn't remove venom. A tight rope or cloth tied around the limb can cut off its blood supply and cost the person their limb. And time spent with a tantrik, ojha or herbal remedy is time the venom keeps working.</p>

<p><strong>Do this instead:</strong> Keep the person calm and still, remove rings, bangles and watches, and immobilise the bitten limb with a splint or sling, as you would a fracture. Carry them rather than letting them walk, and go straight to a hospital that has anti-snake venom (ASV). India's national snakebite protocol sums it up as "Do it R.I.G.H.T.": Reassure, Immobilise, Get to Hospital, Tell the doctor about any symptoms. Read our <a href="<?= post_url('snake-bite-first-aid') ?>">snakebite first-aid guide</a>.</p>

