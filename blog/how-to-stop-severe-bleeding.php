<h2>When and how to use a tourniquet</h2>

<p>A tourniquet is a tight band around an arm or leg that stops blood reaching the wound. Use one only for <strong>life-threatening bleeding from a limb</strong> that firm direct pressure hasn't controlled, or when you can't keep pressure on, for example with a cut-off limb or several injured people and only you to help. A tourniquet can't be used on the neck, chest, stomach, armpit or groin.</p>

<p>If your first-aid kit has a ready-made tourniquet, use it according to its instructions. Otherwise, improvise one:</p>

<ol>
  <li><strong>Place it 5 to 7 cm above the wound</strong>, between the wound and the heart. Don't put it over the elbow or knee. If the wound is just below a joint, place it above the joint.</li>
  <li><strong>Use a wide band</strong>: a folded dupatta, a triangular bandage, a tie or a strip of cotton cloth, ideally about 4 to 5 cm wide. Wrap it round the limb twice and tie a half knot.</li>
  <li><strong>Add a windlass</strong>: lay a short, strong stick, a steel spoon handle or a spanner on the knot and tie a full knot over it. Twist the stick to tighten the band.</li>
  <li><strong>Tighten until the bleeding stops.</strong> This will hurt a lot. That is expected, and it means the tourniquet is working.</li>
  <li><strong>Lock the stick in place</strong> by tying its ends to the limb with another strip of cloth so it can't unwind.</li>
  <li><strong>Note the time</strong> you tied it. Write it on the person's skin with a pen if you can, and tell the ambulance crew.</li>
</ol>

<div class="callout callout-danger">
  <strong>Never loosen a tourniquet</strong>
  <p>Once a tourniquet is on, leave it tight until hospital staff take over, however much the person begs you to remove it. Loosening it to "let the blood flow" can restart heavy bleeding. Never use thin wire, string, rope, a rubber band or an electric cable: they cut into the skin and don't press evenly enough to stop the bleeding.</p>
</div>

<h2>Deep wounds in the groin or armpit: pack and press</h2>

<p>A tourniquet can't be used where the limbs join the body. For a deep, gaping wound in the groin or armpit that keeps bleeding, <strong>pack the wound</strong>. Push clean gauze or cloth firmly into it, right down to where the blood is coming from, and keep feeding more in until it is packed tight. Then press hard on top with both hands for at least 10 minutes, and keep pressing until help arrives.</p>

<p>For a bleeding neck wound, press firmly with a cloth, but never tie a bandage around the neck. Don't pack wounds in the chest or stomach: cover them with a clean cloth, press gently and wait for the ambulance crew.</p>

<h2>What if something is stuck in the wound?</h2>

<p>If a knife, rod, piece of glass or wood is stuck in the body, <strong>don't pull it out</strong>. It may be plugging a damaged blood vessel, and removing it can start bleeding you can't control. Leave it for the hospital.</p>

<ul>
  <li>Press on either side of the object, not on it, to slow the bleeding.</li>
  <li>Build up rolled cloth or bandages around the object so it can't move.</li>
  <li>Bandage over the padding without pressing on the object itself.</li>
  <li>Keep the person still, and don't let anyone cut, bend or wiggle the object.</li>
</ul>

<p>If a finger or limb has been cut off, wrap the part in clean cloth or cling film, put it in a plastic bag, and place that bag in a second bag or container with ice. Never put the part directly on ice or in water. Send it to hospital with the patient.</p>

<h2>Signs of shock from blood loss</h2>

<p>When a person loses a lot of blood, inside or outside the body, their organs stop getting enough oxygen. This is called shock, and it can be fatal even after the bleeding seems controlled. Watch for:</p>

<ul>
  <li>Pale, grey or bluish skin, especially around the lips</li>
  <li>Cold, clammy, sweaty skin</li>
  <li>A fast, weak pulse and fast, shallow breathing</li>
  <li>Thirst, dizziness or nausea</li>
  <li>Restlessness, confusion or drowsiness</li>
</ul>

<p>Lay them flat, keep them warm with a blanket, loosen tight clothing and keep the pressure on the wound. Give <strong>nothing by mouth</strong>, not even water, because they may need surgery. Call the dispatcher back to say the person is getting worse.</p>

<h2>If things get worse: unconscious or not breathing</h2>

<p>If the person stops responding but is still breathing normally, keep up the pressure (or ask a helper to take over). If you don't suspect a neck or back injury, turn them onto their side in the recovery position, and keep checking their breathing.</p>

<p>If they are unresponsive and <strong>not breathing normally</strong>, start CPR immediately and keep going until help arrives. With two helpers, one keeps pressing on the wound while the other does chest compressions. Our <a href="<?= post_url('how-to-do-cpr') ?>">guide to hands-only CPR for adults</a> shows the technique. After a road crash, also follow our <a href="<?= post_url('road-accident-first-aid') ?>">road accident first aid steps</a> to keep the scene safe.</p>

<h2>Severe bleeding first aid: do's and don'ts</h2>

