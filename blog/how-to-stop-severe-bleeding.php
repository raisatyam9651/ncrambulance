  <div class="do">
    <h3>Do</h3>
    <ul>
      <li>Call 112 or an ambulance straight away</li>
      <li>Press hard on the wound for at least 10 minutes</li>
      <li>Add more cloth on top if blood soaks through</li>
      <li>Use a tourniquet for limb bleeding you can't control</li>
      <li>Keep the person lying down and warm</li>
    </ul>
  </div>
  <div class="dont">
    <h3>Don't</h3>
    <ul>
      <li>Lift the cloth to check if the bleeding has stopped</li>
      <li>Pull out an object stuck in the wound</li>
      <li>Use wire, string or a rubber band as a tourniquet</li>
      <li>Loosen a tourniquet once it is on</li>
      <li>Put haldi, coffee powder, chilli, mud or ash on the wound</li>
    </ul>
