<p>A glass door shatters, a kitchen knife slips, a worker's hand is caught in a machine, or a road crash leaves someone bleeding on the pavement. There is blood everywhere, people are shouting, and someone reaches for haldi or coffee powder. Severe bleeding can kill within minutes, often faster than any ambulance can get through traffic, so the person standing next to the victim is the most important first responder.</p>

<p>This guide shows you how to stop severe bleeding with your own hands while an <a href="<?= link_to('emergency') ?>">emergency ambulance</a> is on its way. You'll learn how to apply pressure properly, when and how to use a tourniquet, what to do if something is stuck in the wound, and how to spot shock from blood loss.</p>

<h2>How to tell if bleeding is life-threatening</h2>

<p>Small cuts stop on their own. Treat bleeding as an emergency and call for help if you see any of these:</p>

<ul>
  <li>Blood that is <strong>spurting or pulsing</strong> out of the wound</li>
  <li>Blood that <strong>flows steadily</strong> and doesn't slow down</li>
  <li>Blood <strong>pooling on the ground</strong> or quickly soaking through clothes or cloth</li>
  <li>A <strong>partly or fully cut-off</strong> finger, hand, arm or leg</li>
  <li>A deep wound in the <strong>neck, armpit or groin</strong></li>
  <li>The person turning <strong>pale, confused or drowsy</strong>, which can mean they have already lost a lot of blood</li>
</ul>

<h2>Protect yourself first</h2>

<p>Blood can carry infections such as hepatitis B, hepatitis C and HIV. The risk through unbroken skin is low, but put a barrier between your hands and the blood if you can. Use disposable gloves from a first-aid kit, or slip your hands into clean polythene bags. If the injured person is awake and able, ask them to press on their own wound while you get ready.</p>

<p>Don't let this delay you. If nothing is at hand, use a thick folded cloth and wash your hands with soap and water as soon as you can afterwards. A well-stocked <a href="<?= post_url('home-first-aid-kit-checklist') ?>">home first-aid kit</a> should always include gloves and plenty of gauze.</p>

<h2>How to stop severe bleeding: step by step</h2>

<h3>Step 1: Call for help, or get someone else to call</h3>

<p>If you are alone, call <strong>112</strong> or an ambulance helpline such as ours (<a href="<?= BLOG_TEL ?>"><?= BLOG_PHONE ?></a>), put the phone on speaker and start pressing on the wound while you talk. If others are around, point at one person and tell them to call. They should say "severe bleeding", where on the body it is, and whether the person is awake. For heavy blood loss, ask for an <a href="<?= link_to('als') ?>">ALS ambulance with oxygen and life-support equipment</a>.</p>

<h3>Step 2: Find the wound and press hard with a clean cloth</h3>

<p>Expose the wound so you can see where the blood is coming from, cutting or tearing clothing away if needed. Put a clean cloth, gauze pad, folded handkerchief, towel or dupatta directly on it. A clean sanitary pad also works well, because it is very absorbent. Then press down <strong>hard</strong> with the flat of your palm, using both hands and leaning your body weight over the wound.</p>

<p>Keep pressing for <strong>at least 10 minutes</strong> by the clock, without lifting to peek. Every time you lift your hands, you can disturb the clot that is starting to form, and the bleeding starts again. Kneel beside the person so you can keep up the pressure without tiring.</p>

<div class="callout callout-danger">
  <strong>Don't put powders or pastes on the wound</strong>
  <p>Haldi (turmeric), coffee powder, chilli, mud, ash and similar home remedies don't stop serious bleeding. They push dirt and germs deep into the wound, raise the risk of infection and make it much harder for doctors to clean and stitch. Plain, firm pressure with a clean cloth is what works. Read more in our guide to <a href="<?= post_url('first-aid-myths-india') ?>">common first-aid myths in India</a>.</p>
</div>

<h3>Step 3: If blood soaks through, add more on top</h3>

<p>If the cloth becomes soaked, don't remove it. Put more cloth on top and press harder. Pulling away the first layer tears away the clot that is forming underneath. If firm pressure still isn't controlling bleeding from an arm or leg, move on to a tourniquet (see below).</p>

<h3>Step 4: Raise the limb and bandage the dressing in place</h3>

<p>If the wound is on an arm or leg and you don't suspect a broken bone, raising it can help, but only if that doesn't interrupt the pressure. Once the bleeding is under control, tie a strip of cloth or a bandage firmly over the pad to keep the pressure on. Then check the fingers or toes beyond it: if they turn cold, pale, blue or numb, the bandage is too tight, so loosen it slightly.</p>

<h3>Step 5: Lay them down and keep them warm</h3>

<p>Help the person lie down on a mat, a blanket or the floor. This keeps blood flowing to the brain and stops them fainting and falling. Cover them with a blanket or shawl, keep the pressure on and keep talking to them until the ambulance arrives.</p>

