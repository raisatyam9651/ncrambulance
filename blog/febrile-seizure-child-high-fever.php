<h2>When should you call an ambulance?</h2>

<p>Call 112 or an ambulance straight away if:</p>

<ul>
  <li>the fit lasts <strong>longer than 5 minutes</strong>,</li>
  <li>it is your child's <strong>first-ever febrile seizure</strong>,</li>
  <li>your child has <strong>trouble breathing</strong>, or their lips or face stay <strong>blue</strong>,</li>
  <li>they <strong>don't wake up normally</strong> afterwards, or stay very confused or floppy,</li>
  <li>they have a <strong>stiff neck</strong>, a <strong>rash</strong> (especially one that doesn't fade when you press a glass against it), a bulging soft spot on the head, or seem <strong>very unwell</strong>, or</li>
  <li>they have <strong>another fit</strong> soon after the first.</li>
</ul>

<p>A stiff neck, an unusual rash or a very drowsy child can be signs of serious infections such as meningitis, which need urgent hospital treatment. For babies and young children, ask the dispatcher about <a href="<?= link_to('neonatal') ?>">neonatal and paediatric ambulance support</a>. If your child seems seriously unwell, an <a href="<?= link_to('als') ?>">ALS ambulance with oxygen and monitoring</a> gives closer care on the way.</p>

<p>If your child has had febrile seizures before, and this one was brief with a quick, full recovery, follow the plan your doctor gave you. They still need a doctor to find the cause of the fever.</p>

<h2>How to bring the fever down safely (and what not to do)</h2>

<p>Once your child is <strong>fully awake</strong>, you can make them more comfortable:</p>

<ul>
  <li><strong>Paracetamol</strong> can ease the discomfort. Give the correct dose for your child's <strong>weight</strong>, as advised by your doctor or printed on the label, and use the measuring syringe or cup that came with it, not a kitchen spoon. Syrups come in different strengths, so check before every dose.</li>
  <li>Dress them in light cotton clothes and keep the room comfortably cool. A fan is fine.</li>
  <li>Offer frequent sips of water, or breastfeed, to prevent dehydration.</li>
  <li>Let them rest, and keep checking on them through the night.</li>
</ul>

<p>Fever medicine makes children feel better, but it has <strong>not been shown to prevent febrile seizures</strong>. If your child has a fit despite the medicine, it isn't your fault. Don't give extra doses or mix medicines to "stop" another fit unless a doctor advises it, and never give aspirin to children.</p>

