<p>Your two-year-old has had a fever since the evening. You've given the syrup, and she has finally fallen asleep in your bed in your Greater Noida flat. Then you feel her body go stiff. Her eyes roll up, her arms and legs start jerking and she doesn't respond to her name. Your mother rushes in with a bucket of cold water and an onion. It's one of the most terrifying moments a parent can face.</p>

<p>Very often, this is a <strong>febrile seizure</strong>, a fit triggered by fever. Most stop on their own within a few minutes and don't cause lasting harm, but how you react matters. This guide explains what's happening, what to do during the fit, how to bring the fever down safely, and when to call an <a href="<?= link_to('emergency') ?>">emergency ambulance for your child</a>.</p>

<h2>What is a febrile seizure, and is it dangerous?</h2>

<p>A febrile seizure is a fit caused by a fever, usually in children between <strong>6 months and 5 years</strong> old. It often happens on the first day of an illness, sometimes before parents have even noticed the temperature. Doctors don't fully understand why, but a young child's developing brain seems to be more sensitive to fever, and febrile seizures often run in families.</p>

<p>The reassuring part: most febrile seizures are <strong>brief, usually under 5 minutes</strong>, and stop by themselves. A typical febrile seizure doesn't cause brain damage or learning problems, and most children who have one never develop epilepsy. Afterwards the child is often drowsy or sleepy for a while, sometimes up to an hour.</p>

<div class="callout callout-info">
  <strong>What a febrile seizure looks like</strong>
  <p>The child may suddenly go stiff, then their arms and legs jerk or twitch. Their eyes may roll back, they may drool or froth, look pale or bluish around the lips, wet themselves and not respond to you. Some children simply go floppy and stare. It looks far worse than it usually is, but a first fit always needs a doctor to check the cause of the fever.</p>
</div>

<p>Fits without a fever, or in older children and adults, are handled a little differently. See our guide to <a href="<?= post_url('seizure-first-aid') ?>">seizure first aid</a> for those.</p>

<h2>What to do during the fit: step by step</h2>

<h3>Step 1: Stay calm and note the time</h3>

<p>Check the clock or start your phone's stopwatch. The length of the fit is the most important thing the doctor will ask about, and it decides whether you need an ambulance. If someone else is home, ask them to bring your phone while you stay with your child.</p>

<h3>Step 2: Put your child on their side, on a safe surface</h3>

<p>Lay your child on the floor, or in the middle of a large bed where they can't fall, away from furniture and hard edges. Turn them onto their <strong>side</strong> so saliva or vomit can drain from the mouth. Don't pick them up and run for the car. You might drop them, and they're safer lying down.</p>

<h3>Step 3: Put nothing in the mouth, and don't hold them down</h3>

<p>Don't put a spoon, your finger, water, medicine or anything else in your child's mouth. They can't swallow their tongue. Don't hold their arms and legs still or try to stop the jerking. Stay close, keep them on their side and talk to them gently.</p>

<h3>Step 4: Remove extra clothing, but never use cold water</h3>

<p>Take off heavy clothes, blankets and socks so your child doesn't overheat, and keep the room at a comfortable temperature, with a fan on if it's hot. Don't do anything more than that during the fit.</p>

<div class="callout callout-danger">
  <strong>Never put a child in a cold bath</strong>
  <p>Never dip a fitting child in a bucket or tub of cold water, pour water over them, or sponge them with cold water, ice, alcohol or cologne. Water can cause choking or drowning during a fit, and cold makes the child shiver, which can push the temperature up. Alcohol is absorbed through the skin and is poisonous to children. Holding an onion or a shoe to the nose won't stop the fit either.</p>
</div>

<h3>Step 5: Call for help</h3>

<p>Call <strong>112</strong> or a 24/7 helpline such as ours (<a href="<?= BLOG_TEL ?>"><?= BLOG_PHONE ?></a>) if this is your child's <strong>first-ever fit</strong>, if it lasts <strong>longer than 5 minutes</strong>, or if you see any of the danger signs listed below. Put the phone on speaker so you can stay beside your child. If you're not sure, call anyway. Our guide on <a href="<?= post_url('how-to-call-ambulance-delhi-ncr') ?>">how to call an ambulance in Delhi NCR</a> explains what the dispatcher will ask.</p>

<h3>Step 6: When the fit stops, keep them on their side and watch</h3>

<p>Once the jerking stops, keep your child on their side and check that they're breathing normally. They will probably be sleepy, confused or cranky. Let them rest, stay with them and speak softly. Don't give food, drink or medicine until they're <strong>fully awake</strong> and alert enough to swallow normally.</p>

