<h2>After a febrile seizure: what happens next</h2>

<p>A doctor will look for the cause of the fever, such as a viral infection, an ear or throat infection, or a urine infection. During and after the monsoon, dengue, malaria and typhoid are common causes of high fever in Delhi NCR, so blood tests may be advised. Most children with a simple febrile seizure don't need brain scans or other special tests.</p>

<p>Some children have another febrile seizure during a later illness, and most grow out of them by around five or six. Keep a working thermometer and paracetamol in your <a href="<?= post_url('home-first-aid-kit-checklist') ?>">home first-aid kit</a>, make sure grandparents, house help and the creche know these steps, and save an ambulance number in everyone's phone. Families can reach our <a href="<?= link_to('greater-noida') ?>">ambulance service in Greater Noida</a> round the clock.</p>

