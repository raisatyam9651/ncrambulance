  <p>A person having a seizure cannot swallow their tongue. That is a myth. Forcing a spoon, keys, a cloth, your fingers or water into the mouth can break teeth, cause choking or leave your fingers badly bitten. A bitten tongue heals. A broken tooth or a spoon in the airway can kill.</p>
