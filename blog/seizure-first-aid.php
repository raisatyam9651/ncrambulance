<h2>What to do during a seizure: step by step</h2>

<h3>Step 1: Stay calm and time it</h3>

<p>Look at your watch or start your phone's stopwatch as soon as the seizure begins. How long it lasts decides whether you need an ambulance, and seconds feel like minutes when you're frightened. If someone else is around, ask them to stand by to call for help while you stay with the person.</p>

<h3>Step 2: Make the space around them safe</h3>

<p>Move chairs, tables, hot tea and anything sharp out of the way. Ask the crowd to step back and give the person air and privacy. Only move the person if they are in immediate danger, such as on a road, at the edge of a platform or near a fire, and then move them as gently as you can.</p>

<h3>Step 3: Protect the head and loosen tight clothing</h3>

<p>Slide something soft under their head: a folded jacket, a dupatta, a bag or a cushion. Loosen a tie, a tight collar or anything around the neck, and remove their spectacles if you can do so easily.</p>

<h3>Step 4: Let the seizure run its course</h3>

<p>Don't restrain them, don't try to stop the jerking and don't put anything in their mouth. Stay beside them, talk calmly and keep timing. If another person is free, a short phone video can help the doctor later, but the person's safety comes first.</p>

<h3>Step 5: Roll them into the recovery position once the jerking stops</h3>

<p>When the jerking has stopped, gently roll them onto their side, with the top leg bent to stop them rolling forward and the head tilted slightly back. This keeps the airway open and lets saliva or vomit drain out of the mouth. Check that they are breathing. Our guide to <a href="<?= post_url('unconscious-person-first-aid') ?>">first aid for an unconscious person</a> shows the recovery position in detail.</p>

<h3>Step 6: Stay until they are fully alert</h3>

<p>Most people are confused, sleepy or embarrassed after a seizure. Stay with them, tell them calmly what happened and where they are, and keep onlookers away. If they have wet themselves, cover them with a sheet or shawl to protect their dignity. Give <strong>nothing to eat or drink</strong> until they are fully awake and able to swallow normally.</p>

