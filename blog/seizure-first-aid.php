<p>It happens without warning. A young man waiting on a Metro platform in Gurgaon cries out, falls and starts jerking. Within seconds a crowd gathers. Someone runs for a shoe to hold under his nose, someone else pushes a bunch of keys into his hand, and a well-meaning uncle tries to force a spoon between his teeth.</p>

<p>None of these help, and some cause real injuries. This guide explains what a seizure (also called a fit or <em>mirgi ka daura</em>) looks like, how to keep the person safe while it runs its course, what to do once the jerking stops, and which seizures need an <a href="<?= link_to('emergency') ?>">emergency ambulance service across Delhi NCR</a>.</p>

<h2>What a seizure looks like</h2>

<p>A seizure is a sudden burst of abnormal electrical activity in the brain. It can look very different from one person to another, but the most familiar type, a tonic-clonic seizure, usually follows a pattern:</p>

<ul>
  <li>The person may cry out, then <strong>stiffen and fall</strong>.</li>
  <li>The arms and legs <strong>jerk rhythmically</strong>, often for one to two minutes.</li>
  <li>They may froth at the mouth, bite their tongue, look slightly blue around the lips, or wet themselves.</li>
  <li>Afterwards they are usually <strong>drowsy and confused</strong> for a while, and may have a headache.</li>
</ul>

<p>Some seizures involve no falling or jerking at all. The person may stare blankly, smack their lips, pick at their clothes or wander about, unaware of their surroundings. Gently guide them away from danger, such as a road or stairs, and stay with them until they are fully aware again.</p>

<p>Epilepsy is the most common cause, but seizures can also be triggered by a head injury, very low blood sugar, a stroke, brain infections, alcohol withdrawal, some poisonings and, in young children, a high fever. For fits in a feverish child, read our guide to <a href="<?= post_url('febrile-seizure-child-high-fever') ?>">febrile seizures in children</a>.</p>

<h2>Shoes, onions, keys and spoons: myths that cause harm</h2>

<p>Much of what people do during a fit in India comes from tradition, not medicine. A seizure stops by itself when the brain's electrical storm settles, usually within a couple of minutes. Whatever someone happened to be doing at that moment gets the credit.</p>

<ul>
  <li><strong>Making them smell a shoe, chappal or onion</strong> does nothing to the brain. It only wastes time and crowds the person's face.</li>
  <li><strong>Putting keys or an iron rod in their hand</strong> has no effect. Forcing a clenched hand open can injure the fingers.</li>
  <li><strong>Splashing water on the face</strong> won't wake them and can be breathed into the lungs.</li>
  <li><strong>Holding them down</strong> can dislocate a shoulder or break a bone. The jerking will not stop because you grip the limbs.</li>
</ul>

