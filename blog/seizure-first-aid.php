<h2>When is a seizure a medical emergency?</h2>

<p>Many people with known epilepsy have seizures that stop on their own, and they may not need an ambulance every time. Call 112 or an ambulance straight away if:</p>

<ul>
  <li>the seizure lasts <strong>longer than 5 minutes</strong>,</li>
  <li>one seizure follows another <strong>without the person waking up</strong> in between,</li>
  <li>it is their <strong>first-ever seizure</strong>, or you don't know whether they have epilepsy,</li>
  <li>they have been <strong>injured</strong>, for example by hitting their head as they fell,</li>
  <li>they are <strong>pregnant</strong> or have <strong>diabetes</strong>,</li>
  <li>the seizure happened <strong>in water</strong>, such as a pool, pond or bathtub, or</li>
  <li>they have <strong>trouble breathing</strong> or don't start to wake up after the seizure ends.</li>
</ul>

<p>A seizure that goes on beyond 5 minutes may not stop by itself and can need emergency medicine to end it. Tell the dispatcher how long it has lasted, and ask for an <a href="<?= link_to('als') ?>">ALS ambulance with oxygen and emergency medicines</a> if the fit is prolonged or keeps coming back.</p>

<h2>If they have epilepsy and carry rescue medicine</h2>

<p>Some people with epilepsy are prescribed a rescue medicine for long or clustered seizures, such as midazolam given into the nose or inside the cheek (buccal). Use it <strong>only</strong> if it is prescribed for that person, you have been shown how to give it, and their written care plan says when. Note the time you gave it and tell the ambulance crew.</p>

<p>Look for a medical ID bracelet, a card in their wallet or emergency information on their phone. It may tell you about their condition, their usual seizure pattern and whom to call.</p>

<h2>If things get worse: breathing problems or another seizure</h2>

<p>Right after a seizure, breathing is often noisy or heavy for a short while. This usually settles as the person recovers. Keep watching and act if:</p>

<ol>
  <li><strong>They are not breathing normally</strong> once the jerking has stopped (no breathing, or only occasional gasps). Call for an ambulance, put the phone on speaker and start <a href="<?= post_url('how-to-do-cpr') ?>">hands-only CPR</a>.</li>
  <li><strong>Another seizure starts.</strong> Repeat the steps above, keep timing, and call an ambulance if you haven't already.</li>
  <li><strong>They hit their head</strong> and are becoming more drowsy or confused, or start vomiting. These are danger signs, explained in our guide to <a href="<?= post_url('head-injury-first-aid') ?>">head injury first aid</a>.</li>
</ol>

