<h2>Make an emergency information card</h2>

<p>Tape a card inside the lid of the kit, and keep a photo of it on every adult's phone. It should list:</p>

<ul>
  <li>Each person's name, age and blood group</li>
  <li>Allergies to medicines, foods or latex</li>
  <li>Regular medicines and doses</li>
  <li>Major conditions such as heart disease, diabetes, epilepsy, asthma or pregnancy</li>
  <li>Your family doctor's name and number</li>
  <li>The health insurance company, policy number and TPA helpline</li>
  <li>Emergency numbers: 112, your state ambulance number and a private 24/7 ambulance helpline. Families in Faridabad, for example, can add the number for our <a href="<?= link_to('faridabad') ?>">ambulance service in Faridabad</a>.</li>
