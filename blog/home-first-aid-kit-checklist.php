<h2>Which emergency medicines should you keep?</h2>

<p>Medicines belong in the kit only after you have spoken to your family doctor, who knows everyone's allergies, conditions and regular medicines. Items doctors commonly suggest include:</p>

<ul>
  <li><strong>Paracetamol</strong> for fever and pain, in the dose your doctor advises</li>
  <li><strong>An antihistamine</strong> for mild allergic reactions such as itching or hives</li>
  <li><strong>An antacid</strong> for indigestion, but never as a response to unexplained chest pain</li>
  <li><strong>Aspirin</strong>, for adults with heart risk, to chew if a heart attack is suspected, as discussed with your doctor</li>
  <li><strong>Each person's own prescribed emergency medicines</strong>: reliever inhalers, an adrenaline auto-injector or heart tablets, kept exactly as prescribed</li>
</ul>

<p>Keep every medicine in its original strip or bottle, with the name and expiry date visible. Loose, unlabelled tablets are dangerous in an emergency, when nobody can be sure what they are.</p>

