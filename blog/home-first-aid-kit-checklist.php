<p>Sunday lunch preparations, a slip of the knife, and suddenly there is blood on the kitchen counter. Someone runs for cotton, someone else digs through a drawer of loose medicine strips and finds a tube of ointment that expired two years ago. In many Indian homes, "first aid" is scattered across three cupboards.</p>

<p>A well-stocked kit in one known place changes that. This checklist covers the supplies every home should have, the medicines to keep only after talking to your doctor, extras for elderly people, babies and diabetics, and how to store and check your kit. It won't replace an <a href="<?= link_to('emergency') ?>">emergency ambulance</a> in a serious emergency, but it helps you act well until one arrives.</p>

<h2>What a home first-aid kit is for</h2>

<p>A first-aid kit has two jobs. The first is treating small problems at home: cuts, scrapes, minor burns, sprains and fever. The second is helping you protect someone in a bigger emergency until help arrives, for example by pressing gauze on a bleeding wound while you wait for the crew.</p>

<p>It can't treat a heart attack, a stroke, a serious burn or a major injury. For those, the most important thing you own is your phone. Call 112 or an ambulance first, then use the kit.</p>

