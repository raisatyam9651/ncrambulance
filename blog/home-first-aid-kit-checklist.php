<h2>Where to store the kit and how often to check it</h2>

<ul>
  <li><strong>Cool and dry:</strong> not in the bathroom, where it gets damp, and not on a shelf near the stove. Medicines kept in hot places can lose strength, a real risk in Delhi NCR summers.</li>
  <li><strong>Reachable by adults, but not by children:</strong> a high shelf or a cupboard with a child lock works well.</li>
  <li><strong>Checked every six months:</strong> replace anything expired, used, damp or damaged. Many families tie this to Diwali cleaning and the start of summer.</li>
  <li><strong>Restocked after every use</strong>, so the next emergency doesn't find an empty box.</li>
</ul>

<p><strong>Keep a car kit too.</strong> A smaller kit in the car should hold gloves, gauze, bandages, tape, scissors, a torch, a CPR face shield, ORS and a card with emergency numbers. Parked cars get extremely hot in summer, so keep medicines there to a minimum and check them often.</p>

<h2>When the first-aid kit isn't enough</h2>

<p>Call an ambulance before you reach for the kit if someone:</p>

<ul>
  <li>is unconscious, or not breathing normally</li>
  <li>has chest pain, or signs of a stroke such as a drooping face or slurred speech</li>
  <li>is bleeding heavily and it doesn't slow with firm pressure</li>
  <li>has a large burn, or a burn on the face, hands, feet or genitals</li>
  <li>may have broken their neck, back, hip or thigh</li>
  <li>is having a severe allergic reaction, or a fit that won't stop</li>
</ul>

<p>If the person stops breathing normally, start CPR straight away: push hard and fast in the centre of the chest until the ambulance crew takes over. If they're bleeding heavily, press hard with gauze from the kit and keep pressing, as our guide on <a href="<?= post_url('how-to-stop-severe-bleeding') ?>">how to stop severe bleeding</a> shows. For burns, cool the area under running water for 20 minutes before anything else; our <a href="<?= post_url('burns-first-aid') ?>">burns first-aid guide</a> explains why toothpaste and ice make burns worse.</p>

