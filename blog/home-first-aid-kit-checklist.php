<h2>How to build your home first-aid kit: step by step</h2>

<h3>Step 1: Choose one sturdy box</h3>

<p>A plastic box with a tight lid and a handle works well. Label it clearly as FIRST AID so anyone at home, including domestic help and visiting relatives, can find it quickly.</p>

<h3>Step 2: Buy the basic supplies</h3>

<p>Work through the table above. A ready-made kit from a chemist is a good start, but check what is inside: many lack gloves, a cold pack or a thermometer.</p>

<h3>Step 3: Talk to your doctor about medicines</h3>

<p>Take your list to the next routine appointment. Ask which medicines suit your family, the right doses for each person, and whether any adult should keep aspirin for a suspected heart attack.</p>

<h3>Step 4: Add your family's extras</h3>

<p>Add what your household needs: glucose for a diabetic, a spare spacer for an asthmatic, baby supplies for a newborn.</p>

<h3>Step 5: Fill in the emergency card</h3>

<p>Do it on a calm day, check it with each family member and update it whenever a medicine changes.</p>

<h3>Step 6: Show everyone where it is</h3>

<p>Every adult, older children and domestic staff should know where the kit lives and how to call for help. A short first-aid course makes the kit far more useful.</p>

<h3>Step 7: Set a six-month reminder</h3>

<p>Put a repeating reminder in your phone to check expiry dates and restock.</p>

