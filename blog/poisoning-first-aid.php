<p>A toddler in a Noida flat is found in the bathroom with the cap off a bottle of toilet cleaner, coughing and drooling. His grandmother wants to make him vomit with salt water, and someone else runs to fetch a glass of milk. Both mean well, and both could make things worse.</p>

<p>Poisoning is common in Indian homes, from children swallowing medicines or cleaning liquids to adults who drink pesticide, kerosene or far too much alcohol. This guide explains what to do in the first few minutes, which home remedies to avoid, how to handle the most common household poisons, and when to ask for an <a href="<?= link_to('als') ?>">ALS ambulance with emergency medicines and monitoring</a>.</p>

<h2>Signs that someone may have been poisoned</h2>

<p>Sometimes you see it happen. More often you find someone unwell next to an open bottle or an empty medicine strip. Look for:</p>

<ul>
  <li>Vomiting, stomach pain or diarrhoea</li>
  <li>Burns, redness or blisters around the lips and mouth, drooling or difficulty swallowing</li>
  <li>An unusual smell on the breath, such as kerosene or a chemical smell</li>
  <li>Drowsiness, confusion, slurred speech or seizures</li>
  <li>Coughing, choking or difficulty breathing</li>
  <li>Heavy sweating, excess saliva, very small pupils or muscle twitching, which are typical of some pesticides</li>
</ul>

<p>Many poisons, including paracetamol, iron tablets and some rat poisons, cause <strong>few or no symptoms for hours</strong> while they damage the liver or other organs. A person who looks fine may still be in serious danger.</p>

<h2>Should you make them vomit? No</h2>

<p>Making someone vomit is the most common home remedy for poisoning in India, and it is dangerous. Current first-aid guidance is clear: <strong>don't induce vomiting</strong>, whether with salt water, fingers down the throat or anything else.</p>

<ul>
  <li><strong>Corrosive chemicals</strong> such as toilet cleaner or acid burn the food pipe a second time on the way back up.</li>
  <li><strong>Kerosene, petrol and turpentine</strong> can be breathed into the lungs during vomiting and cause severe chemical pneumonia.</li>
  <li>A <strong>drowsy person</strong> can choke on their own vomit.</li>
  <li>Vomiting removes little of the poison and delays proper treatment.</li>
</ul>

