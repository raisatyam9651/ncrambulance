<h2>Common household poisons and what to do</h2>

<h3>Kerosene, petrol, diesel and turpentine</h3>

<p>Children often drink these when they are stored in old water or soft-drink bottles. The main danger is to the lungs rather than the stomach: even a small amount breathed in can cause severe pneumonia. Never induce vomiting. Keep the person sitting up, watch for coughing, fast breathing or blue lips, and take them to hospital even if they seem fine, because breathing problems can appear hours later.</p>

<h3>Toilet cleaners, acids, drain cleaners and phenyl</h3>

<p>These can burn the mouth, food pipe and stomach. Signs include burning pain, drooling, difficulty swallowing and vomiting blood. <strong>Don't try to neutralise them</strong> with baking soda, lemon juice, vinegar or milk, as the reaction can cause more damage. Rinse the lips and skin with water, and give small sips of water only if the person is fully alert and the dispatcher or doctor advises it.</p>

<h3>Pesticides and insecticides</h3>

<p>Organophosphate pesticides, used widely on farms and in some insect killers, cause some of the most serious poisonings in India. They are absorbed through the skin as well as the stomach. Signs include heavy sweating, drooling, very small pupils, vomiting, diarrhoea, muscle twitching and breathing difficulty. <strong>Protect yourself with gloves</strong>, remove the person's clothes, wash their skin with soap and water, and keep the container. Hospitals have specific antidotes, and severe cases may need breathing support in a <a href="<?= link_to('ventilator') ?>">ventilator ambulance</a> on the way.</p>

<h3>Rat poison and grain-storage tablets</h3>

<p>Some rat poisons and grain-storage tablets contain zinc or aluminium phosphide, and some rat pastes contain yellow phosphorus. These are <strong>extremely dangerous even if the person looks well</strong>, because serious damage to the heart, liver or other organs can follow within hours or days. Phosphide poisons can also release a toxic gas from vomit, so keep the room well ventilated and avoid breathing over the person. Go to hospital immediately and take the packet with you.</p>

<h3>Medicines</h3>

<p>Toddlers often swallow tablets dropped by grandparents, such as blood pressure, diabetes or heart medicines, which can be dangerous even in small numbers. Iron tablets look like sweets and are a well-known cause of serious poisoning in young children. A paracetamol overdose may cause no symptoms at first while it damages the liver. Collect all the strips you can find, including empty ones.</p>

<h3>Button batteries and magnets</h3>

<p>A swallowed button battery (the coin-shaped type used in remotes, watches, toys and car keys) can burn through the food pipe within a couple of hours. Two or more swallowed magnets can pull together through the bowel wall. Both are <strong>urgent emergencies</strong>, even if the child seems fine. Don't make them vomit, don't give food or drink, and go to hospital immediately with the battery packaging or the toy.</p>

<h2>Alcohol poisoning and drug overdose</h2>

<p>Drinking a large amount of alcohol quickly, which is common at parties, weddings and late-night celebrations, can slow breathing and switch off the gag reflex. Call an ambulance if the person:</p>

<ul>
  <li>can't be woken, or keeps slipping back into unconsciousness</li>
  <li>is breathing slowly or irregularly, with long pauses between breaths</li>
  <li>has a seizure</li>
  <li>vomits while semi-conscious</li>
  <li>has pale, bluish or cold, clammy skin</li>
</ul>

<p>While you wait, put them in the recovery position, keep them warm and <strong>never leave them alone</strong>. Don't give coffee, a cold shower or "one more drink", and don't let them sleep it off on their back. Illicit or spurious liquor can contain methanol, which may cause blurred vision, stomach pain and breathlessness hours after drinking, and needs hospital care at once.</p>

<p>The same steps apply to an overdose of sleeping pills, painkillers or other drugs: call, use the recovery position, collect the strips and stay with them. If you think the overdose was deliberate, stay close, remove other medicines or harmful objects and listen without judging. Once the emergency is over, help them reach a doctor or mental health professional.</p>

<h2>If they become unconscious or stop breathing</h2>

<p>If the person does not respond and is not breathing normally, start CPR immediately and continue until the crew takes over. If there is poison on their lips or face, <strong>avoid mouth-to-mouth</strong>: give hands-only chest compressions, or use a face shield or pocket mask if you have one and know how. Children's hearts usually stop because of breathing problems, so rescue breaths matter more for them, given through a barrier where possible.</p>

