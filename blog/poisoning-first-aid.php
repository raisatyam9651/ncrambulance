<h2>Preventing poisoning at home</h2>

<ul>
  <li>Never store kerosene, acid, phenyl or pesticides in water bottles, soft-drink bottles or kitchen containers.</li>
  <li>Keep all medicines, including grandparents' tablets and iron supplements, locked away and out of children's reach.</li>
  <li>Store cleaning products up high, not under the kitchen or bathroom sink.</li>
  <li>Keep button batteries and magnetic toys away from small children, and tape battery compartments shut.</li>
  <li>Lock away pesticides and grain-storage tablets, far from food and living areas.</li>
</ul>

