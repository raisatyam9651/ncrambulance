<h2>What information should you collect?</h2>

<p>The hospital team needs to know exactly what they are dealing with. While you wait, find out:</p>

<ul>
  <li><strong>What</strong>: the name of the product, medicine, chemical or plant. Keep the bottle, box, strip or a piece of the plant, or photograph the label. Don't smell or taste it.</li>
  <li><strong>How much</strong>: count the remaining tablets, or estimate how much liquid is missing.</li>
  <li><strong>When</strong>: the time it happened, even roughly.</li>
  <li><strong>How</strong>: swallowed, breathed in, splashed on the skin or in the eyes.</li>
  <li><strong>Who</strong>: the person's age, approximate weight, other illnesses and regular medicines.</li>
</ul>

<p>Hand the container to the ambulance crew. It is often the single most useful thing you can give them.</p>

<h2>First aid for poisoning: step by step</h2>

<h3>Step 1: Call 112 or an ambulance</h3>

<p>Call immediately, even if the person seems well. Tell the dispatcher what was taken, how much and when, and whether the person is awake and breathing. If you are not sure what details to give, our guide on <a href="<?= post_url('how-to-call-ambulance-delhi-ncr') ?>">how to call an ambulance in Delhi NCR</a> has a simple script. Follow the dispatcher's instructions.</p>

<h3>Step 2: Make the scene safe and protect yourself</h3>

<p>Take the bottle or tablets away so nobody else, especially another child, swallows more. If there are fumes, open the windows. If a chemical or pesticide is on the person's skin or clothes, <strong>wear gloves</strong>, or put plastic bags over your hands, before you touch them.</p>

<h3>Step 3: Clear the mouth</h3>

<p>If there are tablets, powder or liquid still in the mouth, ask the person to spit it out. For a small child, wipe out what you can see with a clean cloth. Don't push your fingers deep into the throat, and don't try to make them vomit.</p>

<h3>Step 4: Wash off chemicals on the skin or in the eyes</h3>

<p>Remove contaminated clothing and wash the skin with plenty of soap and water. If a chemical has splashed into the eyes, rinse them with gently running clean water for at least 15 minutes, holding the eyelids open.</p>

<h3>Step 5: Give nothing by mouth unless advised</h3>

<p>No water, milk, food or medicine unless the dispatcher or a doctor specifically advises it. For a corrosive chemical, they may suggest small sips of water if the person is fully alert, but don't decide this on your own.</p>

<h3>Step 6: Position them and keep watching</h3>

<p>Keep a conscious person sitting up or lying on their side. If they become unconscious but are breathing normally, put them in the <a href="<?= post_url('unconscious-person-first-aid') ?>">recovery position for an unconscious person</a> so vomit can drain out of the mouth. Stay with them and watch their breathing until the crew arrives.</p>

