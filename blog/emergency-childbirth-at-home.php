<h2>The cord and the placenta</h2>

<p><strong>Don't cut the cord.</strong> There is no rush, and the ambulance crew can clamp and cut it safely with sterile instruments. Leave the baby attached, and once the placenta comes out, keep it close to the baby.</p>

<p>If help is truly many hours away and you must cut the cord, wait until it has stopped pulsing. Tie it tightly with clean string or thread in two places, the first about a hand's width from the baby's tummy and the second a few centimetres further along, then cut between the ties with a new or boiled blade or scissors. Keep the stump clean and dry.</p>

<p>The placenta usually comes out on its own within about half an hour, often with another contraction. <strong>Never pull the cord</strong> to bring it out, as this can cause heavy bleeding. Catch it in a bowl or plastic bag and keep it with the baby so the crew can check that it is complete. Then give the mother a pad or clean cloth, keep her warm and offer her a drink if she wants one.</p>

