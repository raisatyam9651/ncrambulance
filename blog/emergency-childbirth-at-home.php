<p>It's 1 am in Greater Noida. Your sister-in-law is 38 weeks pregnant, and her contractions have suddenly become strong and close together. You have called for an ambulance, but she says she can't hold back any more and the baby is coming now.</p>

<p>Most babies are born without complications, and the mother's body does most of the work. Your job is to stay calm, keep mother and baby warm and clean, and know which danger signs need urgent help. This guide walks you through each stage, from the first call to caring for the newborn, until the <a href="<?= link_to('emergency') ?>">emergency ambulance</a> arrives.</p>

<h2>First, call for help</h2>

<p>Call an ambulance before anything else. In many states, <strong>102</strong> runs free government ambulances for pregnant women and newborns, and <strong>112</strong> works everywhere in India. You can also call a private ambulance helpline such as ours. Tell the dispatcher:</p>

<ul>
  <li>how many weeks pregnant she is, and whether this is her first baby</li>
  <li>how often the contractions come, and whether her waters have broken</li>
  <li>whether she feels the urge to push or the baby's head can be seen</li>
  <li>any known problems, such as twins, a breech baby, high blood pressure or bleeding</li>
  <li>the exact address with a landmark</li>
</ul>

<p>Put the phone on speaker and keep it close, as many dispatchers can talk you through a delivery step by step. If you are unsure what to say, see our guide on <a href="<?= post_url('how-to-call-ambulance-delhi-ncr') ?>">calling an ambulance in Delhi NCR</a>.</p>

<h2>How to know the baby is coming now</h2>

<p>Early labour can last many hours, especially with a first baby. Birth is close when you see these signs:</p>

<ul>
  <li><strong>Strong contractions every 2 to 3 minutes</strong>, each lasting about a minute</li>
  <li>A <strong>strong urge to push</strong> or bear down, or a feeling of needing to pass stool</li>
  <li>The mother says the baby is coming</li>
  <li>Bulging at the vaginal opening, or the <strong>baby's head is visible</strong> (crowning)</li>
</ul>

<p>The waters breaking on their own does not mean birth is minutes away. But if the signs above are present, don't rush to hospital in a car, because the baby may be born on the way with nobody free to help. Stay where you are, get ready and let the ambulance come to you.</p>

<h2>Get ready: what you need</h2>

<ul>
  <li>Wash your hands well with soap and water, and wear clean gloves if you have them.</li>
  <li>Spread a plastic sheet or newspapers, covered with clean sheets or towels, where she will give birth.</li>
  <li>Keep several clean towels or cloths ready: one to dry the baby and a dry one to wrap it in.</li>
  <li>Make the room warm: switch off the fan or AC, close the windows in winter and keep a blanket or shawl handy.</li>
  <li>Keep a cap or soft cloth for the baby's head, sanitary pads or clean cloth for the mother, and a bowl or plastic bag for the placenta.</li>
</ul>

<p>Send someone else to open the gate, tell the society guard and hold the lift. Keep her hospital file and antenatal card ready. Our <a href="<?= post_url('before-ambulance-arrives-checklist') ?>">checklist for families waiting for an ambulance</a> covers the rest.</p>

<h2>How to help with the delivery: step by step</h2>

<h3>Step 1: Let her choose a comfortable position</h3>

<p>Many women find a semi-sitting position easiest, propped up with pillows against a wall or bed, knees bent and apart. Some prefer to kneel on all fours or lie on their side. Let her decide, and give her privacy, with only the people she wants in the room.</p>

<h3>Step 2: Let her body do the work</h3>

<p>Encourage her to push with each contraction and rest in between. As the head starts to come out, ask her to stop pushing hard and to pant or blow in short breaths, so the head is born slowly and gently. <strong>Never pull the baby</strong>, and don't put your hands inside the vagina.</p>

<h3>Step 3: Support the head as it emerges</h3>

<p>Place a clean towel beneath her. As the head comes out, cup it gently in your hands without pulling. The face usually points downwards, and the head then turns to one side by itself.</p>

<h3>Step 4: Check for the cord around the neck</h3>

<p>Gently feel around the baby's neck. If the umbilical cord is looped around it and is loose, slip it carefully over the baby's head. If it is too tight to move, don't pull on it. Tell the dispatcher; the baby can usually still be born with the next contraction.</p>

<h3>Step 5: Support the body as it slides out</h3>

<p>With the next contraction or two, the shoulders come out one at a time and the rest of the body slides out quickly. Newborns are very slippery, so hold the baby firmly in a towel, supporting the head and neck. Note the time of birth.</p>

<h2>Right after birth: caring for the newborn</h2>

<ol>
  <li><strong>Dry the baby straight away</strong>, rubbing the head, back and body firmly with a clean towel. This keeps the baby warm and stimulates breathing. Then remove the wet towel.</li>
  <li><strong>Place the baby skin-to-skin</strong> on the mother's bare chest, tummy down, and cover both of them with a dry blanket. Cover the baby's head with a cap or cloth, because newborns lose heat very quickly.</li>
  <li><strong>Check breathing.</strong> Most babies cry or start breathing within moments. Hands and feet may look bluish at first, which is normal. If there is mucus in the mouth or nose, wipe it gently with a clean cloth.</li>
  <li><strong>Help her start breastfeeding</strong> as soon as the baby shows interest. The first thick, yellowish milk (colostrum) is exactly what the baby needs, and feeding helps the womb contract and reduces bleeding.</li>
</ol>

