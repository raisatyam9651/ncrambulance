<h2>Danger signs: when things don't go to plan</h2>

<h3>Heavy bleeding after the birth</h3>

<p>Some bleeding, like a heavy period, is normal. It is too much if blood flows steadily, soaks through pads or cloths quickly, or the mother becomes pale, cold, dizzy or faint. Update the dispatcher urgently. Firmly massage her lower belly just below the navel in a circular motion until you feel the womb tighten into a firm ball, put the baby to the breast, lay her down with her legs raised if she feels faint, and keep her warm.</p>

<h3>The cord comes out before the baby</h3>

<p>If a loop of cord appears at the vaginal opening before the baby (cord prolapse), the baby's oxygen supply is at risk. Tell the dispatcher immediately. Help the mother onto her knees with her chest down and her bottom raised, which takes pressure off the cord. Don't try to push the cord back in, and touch it as little as possible.</p>

<h3>Bottom or feet first (breech)</h3>

<p>If you see the baby's bottom or feet first, tell the dispatcher at once. Don't pull on the baby's legs or body. Let the birth happen with the contractions, support the body as it comes, keep it warm and wait for the head, which comes last.</p>

<h3>Other warning signs</h3>

<ul>
  <li><strong>Fits (seizures) in the mother</strong>: lay her on her left side, protect her from injury and update the dispatcher urgently. Our guide to <a href="<?= post_url('seizure-first-aid') ?>">seizure first aid</a> explains what to do during a fit.</li>
  <li><strong>A premature baby</strong> born well before the due date: keep it skin-to-skin and very warm. Small babies may need a <a href="<?= link_to('neonatal') ?>">neonatal ambulance with an incubator</a> for the journey.</li>
  <li><strong>Green or brown waters</strong>, a severe headache or blurred vision before the birth, or a mother with fever: tell the crew as soon as they arrive.</li>
</ul>

<h2>If the baby isn't breathing</h2>

<p>If the baby is still not breathing or crying after you have dried and rubbed it, rub its back and gently flick the soles of its feet. If there is still no breathing, start infant CPR straight away with the dispatcher's guidance: keep the head level, cover the baby's mouth and nose with your mouth and give gentle breaths, followed by gentle chest compressions in the centre of the chest. Our guide to <a href="<?= post_url('cpr-on-child-and-baby') ?>">CPR on a child or baby</a> explains each step. Keep going until the ambulance crew takes over.</p>

