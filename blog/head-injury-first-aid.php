<h2>Should you let them sleep after a head injury?</h2>

<p>Many families believe a person with a head injury must be kept awake all night. This is an old myth. Feeling tired after a knock on the head is common, and rest is part of recovery. Forcing someone to stay awake doesn't prevent a bleed.</p>

<p>What matters is the difference between <strong>normal tiredness</strong> and <strong>abnormal drowsiness</strong>:</p>

<ul>
  <li>Once a doctor has checked them, or they have no danger signs, they can rest and sleep.</li>
  <li>Someone should <strong>stay with them for the first 24 hours</strong>. Don't leave them alone at home.</li>
  <li>Check on them while they sleep, as often as the doctor advises. Make sure they're breathing normally, can be woken easily, and know who and where they are.</li>
  <li>If they are <strong>hard to wake</strong>, confused when woken, or their breathing seems unusual, call an ambulance.</li>
</ul>

<p>For the first day or two, they should avoid alcohol, sleeping pills, driving and heavy exercise, and take painkillers only as a doctor advises.</p>

<h2>What if a neck injury is also possible?</h2>

<p>A blow hard enough to injure the head can also injure the spine. Moving someone with a neck injury can damage the spinal cord and cause permanent paralysis. So if the way they were hurt suggests it, assume the neck is injured until doctors say otherwise.</p>

<ul>
  <li>Keep them still, lying as you found them, and support the head with your hands.</li>
  <li>Don't lift them into a car or an auto, sit them up or let them walk.</li>
  <li>If they must be moved because of danger, or they start vomiting, roll them onto their side with several helpers, keeping the head, neck and body in a straight line like a log.</li>
  <li>Wait for the ambulance crew, who carry the equipment to move them safely.</li>
</ul>

