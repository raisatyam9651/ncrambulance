<h2>If things get worse: unconscious, fitting or not breathing</h2>

<ol>
  <li><strong>Unresponsive but breathing normally</strong>: if a neck injury is unlikely, place them in the recovery position. If it is possible, keep them still with the head supported and watch their breathing closely. Turn them onto their side, keeping the head and body in line, if they vomit or their breathing sounds blocked.</li>
  <li><strong>A fit</strong>: clear the space, cushion the head without twisting the neck, and time it. Don't hold them down or put anything in their mouth.</li>
  <li><strong>Not breathing normally</strong>: tell the dispatcher and start <a href="<?= post_url('how-to-do-cpr') ?>">hands-only CPR</a> immediately. CPR takes priority over protecting the neck.</li>
</ol>

<h2>Watching someone at home after a minor head injury</h2>

<p>If a doctor has seen them and sent them home, or the bump was clearly minor with no danger signs, keep a close eye on them for the next 24 hours, and for longer if they are elderly or on blood thinners:</p>

<ul>
  <li>Keep a responsible adult with them at all times for the first 24 hours.</li>
  <li>Watch for any of the danger signs above. They can appear hours, or occasionally days, after the injury.</li>
  <li>A mild headache, tiredness, dizziness or irritability for a few days is common after a concussion. These should slowly improve.</li>
  <li>Children should avoid rough play and sport until a doctor says it's safe.</li>
  <li>If any danger sign appears, go back to the hospital without delay.</li>
</ul>

