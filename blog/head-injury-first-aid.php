<p>A teenager on a scooter in Dwarka hits a pothole and is thrown off, helmet strap left unfastened. A grandmother slips on a wet bathroom floor and strikes her head on the tap. A toddler rolls off the bed onto a marble floor. In each case, the person might sit up a minute later and say they're fine, and the family is tempted to put some haldi or ice on the bump and move on.</p>

<p>Most bumps on the head are minor. But some cause bleeding inside the skull that builds up slowly, and the warning signs can appear hours after the fall. This guide explains which signs need an <a href="<?= link_to('emergency') ?>">emergency ambulance service</a> straight away, how to handle a bleeding scalp, what to do if the neck might be hurt, and how to watch someone safely at home.</p>

<h2>Which head injury signs mean an emergency?</h2>

<p>Call <strong>112</strong> or an ambulance immediately if, after a blow to the head, the person has any of these:</p>

<ul>
  <li><strong>Any loss of consciousness</strong>, even for a few seconds, or no memory of the injury.</li>
  <li><strong>Vomiting more than once</strong>.</li>
  <li>A <strong>severe headache</strong>, or one that keeps getting worse.</li>
  <li><strong>Confusion, unusual drowsiness</strong> or being hard to wake.</li>
  <li>A <strong>seizure (fit)</strong> at any time after the injury.</li>
  <li><strong>Clear fluid or blood</strong> coming from the nose or ears.</li>
  <li><strong>Unequal pupils</strong> (the black centre of one eye bigger than the other), or blurred or double vision.</li>
  <li><strong>Weakness or numbness</strong> in the arms or legs, <strong>slurred speech</strong>, or trouble walking or balancing.</li>
  <li>A dent or a soft, boggy area in the skull, or bruising behind the ears or around both eyes.</li>
</ul>

<p>Some people are at higher risk of bleeding inside the skull, so get them checked at a hospital even if they seem fine:</p>

<ul>
  <li>anyone on <strong>blood thinners</strong> such as warfarin, apixaban, rivaroxaban, dabigatran or clopidogrel, or with a bleeding disorder,</li>
  <li><strong>older adults</strong>, especially those who live alone,</li>
  <li><strong>babies and infants</strong>, who can't tell you how they feel,</li>
  <li>anyone hurt in a <strong>high-energy accident</strong>: a road crash, being thrown from a two-wheeler, being hit by a vehicle, or a fall from a height or down a flight of stairs, and</li>
  <li>anyone who has been <strong>drinking alcohol</strong> or taken drugs, because this hides the warning signs.</li>
</ul>

