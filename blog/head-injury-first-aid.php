<h2>What to do after a head injury: step by step</h2>

<h3>Step 1: Make the scene safe and check them</h3>

<p>On a road, switch on hazard lights, warn oncoming traffic and keep yourself out of the way of vehicles. Speak to the person and ask what happened. If they're wearing a helmet, <strong>leave it on</strong> unless it's stopping them from breathing or they are vomiting, because removing it badly can injure the neck. Our guide to <a href="<?= post_url('road-accident-first-aid') ?>">first aid at a road accident</a> covers scene safety in more detail.</p>

<h3>Step 2: Call for help if there are danger signs</h3>

<p>If you notice any danger sign, call <strong>112</strong> or a 24/7 helpline such as ours (<a href="<?= BLOG_TEL ?>"><?= BLOG_PHONE ?></a>). Say how the injury happened, whether they were knocked out and how they are now. For someone who is unconscious, confused or has had a fit, an <a href="<?= link_to('icu') ?>">ICU ambulance with a critical care team</a> is the safest choice. If they're awake but you're worried, an <a href="<?= link_to('als') ?>">ALS ambulance with monitoring and oxygen</a> can take them for a scan.</p>

<p>The right hospital for a serious head injury has a CT scanner available round the clock and a neurosurgery team. If the patient first reaches a smaller hospital, they may need a monitored <a href="<?= link_to('hospital-transfer') ?>">hospital-to-hospital transfer</a> to a centre that can operate.</p>

<h3>Step 3: Protect the neck if it could be injured</h3>

<p>Assume the neck may be injured if the person fell from a height, was in a road crash, was knocked out, or has neck pain or tingling in the arms or legs. Ask them not to move. Kneel behind their head and hold it gently with a hand on each side, keeping the head, neck and body in line. Don't put a pillow under the head. There's more on this below.</p>

<h3>Step 4: Control bleeding from the scalp</h3>

<p>The scalp has a rich blood supply, so even a small cut can bleed heavily and look frightening. Press a clean cloth, handkerchief or gauze pad firmly on the wound and hold it for at least 10 minutes without lifting it to check. If blood soaks through, add another pad on top. Once it stops, cover it with a clean dressing. A gaping or deep cut needs stitches at a hospital.</p>

<div class="callout callout-danger">
  <strong>Suspected skull fracture</strong>
  <p>If the skull feels dented, soft or spongy, or you can see bone, <strong>don't press directly on the wound</strong>. Press around the edges instead, or use a ring-shaped pad made from a rolled cloth. Don't remove anything stuck in the wound, and don't plug the nose or ears if clear fluid or blood is coming out. Cover them lightly with a clean pad and tell the ambulance crew.</p>
</div>

<p>For heavy bleeding elsewhere on the body, see our guide on <a href="<?= post_url('how-to-stop-severe-bleeding') ?>">how to stop severe bleeding</a>.</p>

<h3>Step 5: Use something cold on the swelling</h3>

<p>For a bump with no open wound, hold an ice pack or ice cubes wrapped in a thin cloth against it for about 10 minutes at a time. A packet of frozen peas works well. Never put ice directly on the skin. Skip the old remedies: rubbing oil or ghee into the lump, massaging it, or putting haldi on a cut won't help and can irritate or contaminate the wound.</p>

<h3>Step 6: Keep them resting and watched</h3>

<p>If there's no neck injury, help them lie down or sit comfortably with the <strong>head and shoulders slightly raised</strong>. While you wait for an ambulance, don't give food or drink, as they may vomit or need a procedure. Keep talking to them and watch for any change: new confusion, drowsiness, vomiting or weakness means the injury may be getting worse.</p>

