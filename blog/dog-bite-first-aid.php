<p>It can happen in seconds. A stray dog in your housing society chases a child on a cycle, a neighbour's pet snaps when someone reaches out to pat it, or a monkey on the balcony scratches a hand reaching for the washing. Many families then reach for haldi, chilli powder or mustard oil, tie a bandage on and decide to "watch the dog for a few days". That delay is how rabies happens.</p>

<p>India has one of the highest numbers of rabies deaths in the world, and most of them follow dog bites. Rabies is almost always fatal once symptoms start, but it is preventable with prompt wound washing and timely vaccination. This guide explains what to do in the first 15 minutes, which bites need rabies vaccine and immunoglobulin, and when a bite is serious enough to call an <a href="<?= link_to('emergency') ?>">emergency ambulance service</a>.</p>

<h2>First, get safe and check how serious it is</h2>

<p>Move away from the animal and get the person somewhere safe. Don't chase the dog or try to catch it, because that leads to more bites. Then take a quick look at the wounds.</p>

<p>Call 112 or an ambulance straight away if there is:</p>

<ul>
  <li>bleeding that is heavy or won't stop with firm pressure</li>
  <li>a bite to the face, head or neck</li>
  <li>several deep bites or torn flesh, for example when a child has been attacked by a pack of stray dogs</li>
  <li>signs of shock: pale, cold, sweaty skin, fast breathing, confusion or drowsiness</li>
  <li>a deep bite to the hand or over a joint, with loss of movement or feeling</li>
</ul>

<p>Attacks on young children by packs of stray dogs in housing societies and parks have become a known problem in Noida, Gurugram and other parts of the NCR. These injuries can be severe. For a badly injured child, ask for an <a href="<?= link_to('als') ?>">ALS ambulance with trained medical staff</a>.</p>

<h2>Dog bite first aid: step by step</h2>

<h3>Step 1: Control heavy bleeding first</h3>

<p>If the wound is bleeding heavily, press firmly on it with a clean cloth or pad and keep pressing until the bleeding slows or the ambulance crew takes over. If blood soaks through, add another cloth on top rather than lifting the first. Our guide on <a href="<?= post_url('how-to-stop-severe-bleeding') ?>">how to stop severe bleeding</a> explains direct pressure step by step. With severe wounds, leave the washing to the hospital team once bleeding is under control.</p>

<h3>Step 2: Wash the wound with soap and running water for 15 minutes</h3>

<p>This is the most effective thing you can do at home to prevent rabies. The virus is carried in the animal's saliva, and thorough washing with soap and water removes much of it from the wound before it can take hold.</p>

<ul>
  <li>Use any soap or detergent and plenty of running water: a tap, or a mug or bottle poured continuously.</li>
  <li>Wash every bite and scratch, including small ones, for a <strong>full 15 minutes</strong>. Use a timer on your phone, because 15 minutes feels much longer than you expect.</li>
  <li>Let the water run into puncture wounds, and wash gently. Don't scrub hard enough to tear the skin further.</li>
  <li>If saliva got into the eyes, nose or mouth, rinse them well with plenty of clean water.</li>
</ul>

<h3>Step 3: Apply an antiseptic and cover loosely</h3>

<p>After washing, apply an antiseptic such as povidone-iodine solution, which is worth keeping in your <a href="<?= post_url('home-first-aid-kit-checklist') ?>">home first-aid kit</a>. Cover the wound loosely with clean gauze or cloth. Don't bandage it tightly, and don't insist on stitches straight away: doctors often delay or avoid stitching animal bites, because closing them early can trap infection inside.</p>

<h3>Step 4: Go to a hospital or anti-rabies clinic the same day</h3>

<p>Don't wait until tomorrow or until the weekend is over. Rabies vaccine works best when it is started as early as possible. Government hospitals and many health centres run anti-rabies clinics, and most large private hospitals give the vaccine in their emergency department. The doctor will:</p>

<ul>
  <li>check and clean the wound again</li>
  <li>decide your exposure category and start the rabies vaccine</li>
  <li>give rabies immunoglobulin into and around the wound if it is a category III exposure</li>
  <li>check whether you need a tetanus injection and, sometimes, antibiotics</li>
</ul>

<h3>Step 5: Note the animal's details, but don't wait on it</h3>

<p>If it was a pet, get the owner's name, phone number and the dog's vaccination record. If it was a stray, note where it was so the local municipal body can be informed. Tell the doctor whether the animal seemed ill or behaved strangely. But don't delay vaccination to see whether the animal stays healthy. Watching the dog doesn't replace treatment.</p>

