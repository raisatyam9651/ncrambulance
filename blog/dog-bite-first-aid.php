<h2>Rabies vaccine and immunoglobulin: how urgent are they?</h2>

<p><strong>The rabies vaccine</strong> trains the body to make its own antibodies against the virus. Modern vaccines are given in the upper arm, in a few doses over several weeks, on dates the doctor will give you. Complete every dose on time, even if the wound has healed and you feel well. The old course of 14 injections in the stomach is no longer used.</p>

<p><strong>Rabies immunoglobulin (RIG)</strong> is ready-made antibody injected into and around the wound. It protects the wound area immediately, during the first days before the vaccine has had time to work. It is needed for category III exposures and should be given as early as possible, ideally with the first vaccine dose. Not every clinic stocks it, so ask, and if needed go to a larger hospital the same day.</p>

<p>There is no safe waiting period with rabies. Symptoms can appear weeks or even months after a bite, and once they do, the disease can't be cured. If you were bitten days or weeks ago and were never vaccinated, see a doctor now: it is still worth starting. If you have had a full rabies vaccine course before, tell the doctor, as you may need fewer doses.</p>

<h2>Monkey, cat and other animal bites</h2>

<p>Any mammal can carry rabies. In Delhi, monkey bites and scratches are common around homes, offices, temples and parks, and they need exactly the same care as a dog bite: 15 minutes of washing, an antiseptic, and a doctor's assessment for rabies vaccine the same day. The same applies to cats and to wild animals such as jackals and mongooses. Cat bites are small but deep and often become infected, so they may need antibiotics too. Bites from rats and squirrels rarely carry rabies, but clean them well and ask a doctor.</p>

