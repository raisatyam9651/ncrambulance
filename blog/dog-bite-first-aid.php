<h2>If things get worse</h2>

<p>After a severe attack, a person can go into shock from blood loss and pain. If they become pale, cold, sweaty, breathless or drowsy, lay them down, raise their legs if the legs aren't injured, keep them warm and keep pressing on bleeding wounds. If they stop responding and aren't breathing normally, call 112 and start CPR. For a young child, follow our guide to <a href="<?= post_url('cpr-on-child-and-baby') ?>">CPR on a child or baby</a>.</p>

<p>In the days after a bite, see a doctor quickly if the wound becomes red, hot, swollen or more painful, oozes pus, or the person develops a fever. These are signs of infection, which is common with cat bites and deep dog bites.</p>

