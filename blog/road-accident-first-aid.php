<p>You are on the expressway in the evening when traffic suddenly slows. A motorbike lies on its side, the rider is on the road and a crowd is gathering, with more phones filming than hands helping. Most people want to help but freeze, because they don't know what is safe to do.</p>

<p>What the first few people at the scene do, before the ambulance reaches, can decide whether the injured survive. This guide walks you through road accident first aid in the right order: making the scene safe, calling an <a href="<?= link_to('emergency') ?>">emergency ambulance for road accident victims</a>, deciding whether to move anyone, dealing with breathing and bleeding, and handling a biker's helmet. It also explains how Indian law protects you for helping.</p>

<h2>Road accident first aid: step by step</h2>

<h3>Step 1: Make the scene safe before you go near</h3>

<p>You can't help anyone if you become the next casualty. On fast roads, the biggest danger to helpers is other traffic, so think about vehicles before you think about the injured.</p>

<ul>
  <li><strong>Park safely</strong> on the side of the road, away from moving lanes, and switch on your hazard lights. At night, point your headlights at the scene if you can do it without dazzling oncoming drivers.</li>
  <li><strong>Warn approaching traffic.</strong> Place a warning triangle well back from the crash if you carry one, or ask two people to stand at the roadside, behind the barrier if there is one, and wave traffic down. Nobody should stand in a live lane.</li>
  <li><strong>Switch off the ignition</strong> of the crashed vehicles if you can reach the key safely, and pull up the handbrake.</li>
  <li><strong>No smoking</strong>, and no matches or lighters anywhere near. Look and smell for leaking petrol or diesel, listen for a hissing CNG cylinder, and watch for smoke or flames.</li>
</ul>

<p>Stay back if there is a fire you can't put out, a fallen electric wire, an overturned tanker or a vehicle that could still roll. Call for help from a safe distance and keep other people back too.</p>

<h3>Step 2: Call 112 or an ambulance with the exact location</h3>

<p>Dial <strong>112</strong>, India's national emergency number, or a 24/7 ambulance helpline such as ours (<a href="<?= BLOG_TEL ?>"><?= BLOG_PHONE ?></a>). If several people are around, point at one person and give them the job of calling, so you can start helping. Tell the dispatcher:</p>

<ul>
  <li><strong>Exactly where you are</strong>: the road, your direction of travel, the last exit, toll plaza, flyover or metro pillar number you passed, and any landmark.</li>
  <li><strong>How many people are hurt</strong>, and whether anyone is trapped, unconscious, not breathing or bleeding heavily.</li>
  <li><strong>Any hazards</strong>, such as fire, leaking fuel or a blocked carriageway.</li>
</ul>

<p>Location details matter most on fast roads such as the Delhi–Gurugram expressway, the Noida–Greater Noida expressway, the DND flyway and the Yamuna Expressway, where exits are far apart and an ambulance on the wrong side may have a long way to turn around. If the dispatcher asks, share your live location on WhatsApp.</p>

<p>For serious injuries, ask for an <a href="<?= link_to('als') ?>">ALS ambulance with oxygen and cardiac monitoring</a>. Our helpline arranges ambulances across the region, including <a href="<?= link_to('gurgaon') ?>">ambulance service in Gurgaon</a> and <a href="<?= link_to('noida') ?>">emergency ambulance in Noida</a>.</p>

<h3>Step 3: Leave the injured where they are, unless there is danger</h3>

<p>Well-meaning crowds often pull people out of cars or lift them off the road straight away. Unless there is <strong>immediate danger</strong>, such as fire, a serious fuel leak or traffic you can't stop, leave them where they are. A person thrown from a bike or hit by a car may have a broken neck or back, and bending or twisting the spine can turn a survivable injury into permanent paralysis.</p>

<p>If someone is sitting in a car and is conscious, tell them to keep still. Reach in from behind or from the side and hold their head with both hands so it stays in line with the body. If you truly must move a person, drag them along the length of the body by the clothing at the shoulders, keeping the head, neck and back in a straight line. Our guide on <a href="<?= post_url('spinal-injury-first-aid') ?>">first aid for a suspected spinal injury</a> shows how to hold the head still.</p>

<div class="callout callout-danger">
  <strong>Don't let the crowd carry them to an auto</strong>
  <p>At accident scenes in India, bystanders often grab the injured by the arms and legs and rush them off in the nearest auto, taxi or car. This folds and twists the spine and can make bleeding worse. Unless there is immediate danger and no ambulance can reach you, keep the person still and wait for a crew with a stretcher.</p>
</div>

<h3>Step 4: Check who is hurt and whether they are breathing</h3>

<p>If there are several victims, check the quiet ones first. A person who is shouting or crying is at least breathing; someone silent and still may be in the most danger. Kneel beside each person, speak loudly and ask them to open their eyes. Then watch the chest and listen near the mouth for up to 10 seconds.</p>

<ul>
  <li><strong>Awake and talking:</strong> tell them to keep still and move on to bleeding.</li>
  <li><strong>Unconscious but breathing normally:</strong> keep their head supported in line with the body and watch their breathing all the time. If they vomit or their breathing turns gurgling, roll them onto their side with helpers, keeping the head, neck and body in line.</li>
  <li><strong>Not breathing normally:</strong> start CPR straight away (see below).</li>
</ul>

<h3>Step 5: Stop severe bleeding with direct pressure</h3>

<p>Heavy bleeding can kill within minutes, before any ambulance can arrive. Put a clean cloth, handkerchief or dupatta on the wound and press down hard with the palm of your hand. Keep pressing without lifting to check. If blood soaks through, add more cloth on top and press harder.</p>

<p>Cover your hands with gloves or a plastic bag if you can, but don't let that delay you. For bleeding from an arm or leg that won't stop with firm pressure, a tourniquet may be needed. Our guide on <a href="<?= post_url('how-to-stop-severe-bleeding') ?>">how to stop severe bleeding</a> covers pressure, tourniquets and objects stuck in a wound.</p>

<h3>Step 6: Keep them warm, still and reassured</h3>

<p>Injured people lose body heat quickly lying on a road, even in mild weather, and getting cold makes bleeding and shock worse. Cover them with a jacket, shawl or blanket without moving them. In a Delhi summer, shade them from the sun with an umbrella or a cloth instead.</p>

<p>Talk to them calmly. Tell them your name, that an ambulance is coming and that they should keep still. <strong>Don't give water</strong>, tea or food, even if they ask: they may need surgery and an anaesthetic, and an injured person can vomit and choke. If they are very thirsty, moisten their lips with a wet cloth.</p>

