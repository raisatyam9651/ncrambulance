<h2>Should you remove a biker's helmet?</h2>

<p>Usually, <strong>no</strong>. The helmet supports the head and neck, and pulling it off can twist a broken neck. You can lift the visor to check breathing and talk to the rider. Leave the helmet on unless it is blocking the airway, the rider is vomiting, or they are not breathing and you can't do CPR with it on.</p>

<p>If you must take it off, use two people:</p>

<ol>
  <li>One person kneels behind the head and holds the helmet steady with a hand on each side, keeping the head in line with the body.</li>
  <li>The second person undoes or cuts the chin strap, then places one hand under the back of the neck and the other on the jaw to support the head from below.</li>
  <li>The first person eases the helmet off slowly, straight along the line of the body, tilting it slightly to clear the nose.</li>
  <li>Once it is off, the first person takes over holding the head still with both hands.</li>
</ol>

<h2>If things get worse: when to start CPR</h2>

<p>If an injured person is unresponsive and <strong>not breathing normally</strong> (not breathing at all, or only gasping now and then), start CPR straight away. Breathing comes first, even if you suspect a neck injury.</p>

<ol>
  <li>Roll them onto their back on a firm surface, with helpers if you can, keeping the head and neck in line as you turn them.</li>
  <li>Put the heel of one hand in the centre of the chest and the other hand on top. Push hard and fast: about 5 to 6 cm deep, 100 to 120 times a minute.</li>
  <li>Keep going until the ambulance crew takes over or the person starts breathing normally. Swap with someone every two minutes if you can.</li>
</ol>

<p>Put the phone on speaker and follow any instructions the dispatcher gives. Our <a href="<?= post_url('how-to-do-cpr') ?>">step-by-step guide to hands-only CPR</a> teaches the technique in a few minutes, so learn it before you ever need it.</p>

<h2>Will the police or hospital trouble you for helping?</h2>

<p>Fear of police cases and hospital paperwork stops many people in India from helping accident victims. The law is on your side. In 2016 the Supreme Court gave legal force to the Good Samaritan guidelines (SaveLIFE Foundation v. Union of India), and in 2019 Section 134A was added to the Motor Vehicles Act to protect people who help.</p>

<ul>
  <li>You are <strong>not liable</strong> for the victim's injury or death if you acted in good faith.</li>
  <li>You are <strong>not forced to give your name</strong> or personal details.</li>
  <li>A hospital <strong>can't detain you</strong> or demand payment from you for the victim's treatment.</li>
</ul>

<p>Read our guide to the <a href="<?= post_url('good-samaritan-law-india') ?>">Good Samaritan law in India</a> for your full rights as a helper.</p>

