<h2>What to do when someone can't breathe properly: step by step</h2>

<h3>Step 1: Call for help early</h3>

<p>Don't wait for the breathing to get worse before you call. Dial <strong>112</strong> or a 24/7 helpline such as ours (<a href="<?= BLOG_TEL ?>"><?= BLOG_PHONE ?></a>). Tell the dispatcher the person's age, whether they can speak in full sentences, the colour of their lips, and any known condition such as asthma, COPD or heart disease. Ask for an <a href="<?= link_to('als') ?>">ALS ambulance with oxygen support and cardiac monitoring</a>.</p>

<h3>Step 2: Help them into the best position</h3>

<p>Most breathless people instinctively want to sit up. Let them, and help them find the position that suits them best:</p>

<ul>
  <li><strong>Sitting upright</strong> on a chair or the edge of the bed. Never lay them flat.</li>
  <li><strong>Leaning forward on a table</strong>, with their forearms resting on a pillow. This lets the chest and shoulder muscles help with breathing.</li>
  <li><strong>The tripod position</strong>: sitting and leaning forward with the hands on the knees.</li>
  <li>For suspected <strong>heart failure</strong>, sitting up with the legs hanging down over the side of the bed can ease breathing.</li>
</ul>

<h3>Step 3: Loosen clothing and keep calm</h3>

<p>Loosen tight collars, ties, belts and anything tight around the chest. Keep your own voice calm and slow, because panic makes breathlessness worse. A fan blowing gently towards the face can make breathing feel easier. Ask onlookers to give them space. If the air outside is thick with smog, keep the windows closed and run an air purifier if you have one, rather than letting polluted air in.</p>

<h3>Step 4: Help with their own reliever inhaler</h3>

<p>If they have asthma or COPD and carry a reliever inhaler (usually blue, often salbutamol), help them use it, ideally with a spacer. Follow their written action plan or the dispatcher's advice on how many puffs to give. Our guide to <a href="<?= post_url('severe-asthma-attack-first-aid') ?>">severe asthma attack first aid</a> explains the puff-by-puff method and what to do if there's no spacer.</p>

<h3>Step 5: Use home oxygen only as prescribed</h3>

<p>If the person has home oxygen, help them use it at the <strong>flow rate their doctor prescribed</strong>. Don't turn it up on your own: more oxygen is not always better, especially for people with COPD. Keep every flame, cigarette and diya well away. The safety rules are in the next section.</p>

<h3>Step 6: Look for a cause you can treat</h3>

<ul>
  <li><strong>Severe allergy</strong> (swelling, hives or wheeze after a food, sting or medicine): use their adrenaline auto-injector if they have one, and read our guide on <a href="<?= post_url('anaphylaxis-severe-allergic-reaction') ?>">anaphylaxis and severe allergic reactions</a>.</li>
  <li><strong>Smoke, a gas heater or an angithi</strong> in a closed room: get everyone into fresh air first. Carbon monoxide has no smell. Learn more about <a href="<?= post_url('carbon-monoxide-poisoning-angithi-heater') ?>">carbon monoxide poisoning from angithis and heaters</a>.</li>
  <li><strong>Choking</strong> while eating: if they can't breathe, cough or speak, give back blows and abdominal thrusts.</li>
</ul>

<h3>Step 7: Get ready for the crew</h3>

<p>Don't make them walk down the stairs or out to the car, as the effort can tip them into collapse. The crew can bring a carry chair or stretcher. Call the lift, tell the guard, and keep their inhalers, oxygen prescription, medicine list and latest discharge summary ready.</p>

