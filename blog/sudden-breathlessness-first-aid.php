<h2>Danger signs: when breathlessness is an emergency</h2>

<p>Call <strong>112</strong> or an ambulance straight away if the person:</p>

<ul>
  <li><strong>can't speak in full sentences</strong>, only a few words at a time,</li>
  <li>has <strong>blue, grey or very pale lips</strong>, face or fingertips,</li>
  <li>is <strong>confused, drowsy</strong> or unusually agitated,</li>
  <li>has <strong>chest pain</strong> or pressure along with the breathlessness,</li>
  <li>looks <strong>exhausted</strong>, as if they can't keep up the effort of breathing,</li>
  <li>has <strong>noisy breathing</strong>: wheezing, a high-pitched sound when breathing in, gurgling or rattling,</li>
  <li>is breathing very fast, or straining the neck and shoulder muscles to pull air in, or</li>
  <li>has <strong>swelling of the face, lips or tongue</strong>, or a rash, after a food, a medicine or a sting.</li>
</ul>

