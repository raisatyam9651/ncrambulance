<h2>Using home oxygen safely while you wait</h2>

<p>Since the pandemic, many families in Delhi NCR keep an oxygen concentrator, a cylinder or a pulse oximeter at home. Used correctly, they help. Used wrongly, they can be dangerous.</p>

<ul>
  <li><strong>Use the prescribed flow</strong>, and only for the person it was prescribed for. In some people with COPD, too much oxygen can make them drowsy and slow their breathing.</li>
  <li><strong>No smoking, flames or sparks nearby.</strong> Oxygen makes fires start easily and burn fiercely. Keep it well away from gas stoves, candles, diyas, agarbattis, heaters and matches.</li>
  <li>Keep cylinders <strong>upright and secured</strong>, away from heat and direct sun.</li>
  <li>Check that the tubing isn't kinked or disconnected, and that the concentrator is switched on and plugged in. Keep a backup cylinder if power cuts are common in your area.</li>
  <li>Don't use oil, ghee or petroleum jelly on the face or near the fittings while oxygen is running.</li>
</ul>

<p>A pulse oximeter can help, but don't rely on it alone. Readings can be wrong with cold fingers, nail polish or movement. If the person looks unwell, is struggling to talk or their lips are blue, call for help whatever the number says. A reading that keeps falling, or that is lower than their doctor has said is safe, is also a reason to call.</p>

<h2>If things get worse: when to start CPR</h2>

<ol>
  <li><strong>Becoming drowsy, confused or quiet</strong>: tell the dispatcher immediately. This can mean they're tiring or their oxygen level is falling.</li>
  <li><strong>Unresponsive but breathing normally</strong>: lay them on their side in the recovery position and keep checking their breathing.</li>
  <li><strong>Not breathing normally</strong> (no breathing, or only gasps): put the phone on speaker and start <a href="<?= post_url('how-to-do-cpr') ?>">hands-only CPR</a>. Send someone for an AED if there's one nearby.</li>
</ol>

<h2>Delhi NCR winters, smog and breathing emergencies</h2>

<p>Many families notice that breathing problems get worse when winter smog settles over the region. Cold air and pollution irritate the airways and can trigger asthma and COPD flare-ups, and chest infections spread more easily. If someone in your family has a lung or heart condition:</p>

<ul>
  <li>Keep their inhalers, spacer and written action plan where everyone can find them, and check the expiry dates.</li>
  <li>On days when the air quality index is very poor, limit outdoor exercise and early-morning walks, and use a well-fitted N95 mask outdoors if their doctor agrees.</li>
  <li>Never burn an angithi or coal heater in a closed room.</li>
  <li>Ask their doctor about flu and pneumonia vaccines, and what to do if symptoms worsen.</li>
</ul>

