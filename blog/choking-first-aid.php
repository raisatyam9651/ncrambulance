<h2>Mild choking: help them cough it out</h2>

<p>A strong cough is the most effective way to clear the airway. If the person can cough, speak or breathe, <strong>encourage them to keep coughing hard</strong>. Don't slap their back while they are upright, don't give water, and don't put your fingers in their mouth. Stay with them and watch closely. If the cough becomes weak or silent, or they can no longer breathe or speak, it has become severe choking. Act immediately.</p>

<h2>Severe choking in adults and children over 1: step by step</h2>

<h3>Step 1: Shout for help and get someone to call 112</h3>

<p>Tell the person you are going to help. Shout for someone to call <strong>112</strong> or an ambulance and put the phone on speaker. If you are alone with them, start the back blows first. You can call between rounds or as soon as the object comes out.</p>

<h3>Step 2: Give up to 5 back blows</h3>

<p>Stand to the side and slightly behind them. Support their chest with one hand and <strong>lean them well forward</strong>, so that the object comes out of the mouth instead of going further down. With the heel of your other hand, give up to <strong>5 sharp blows between the shoulder blades</strong>. Check after each blow whether the object has come out.</p>

<h3>Step 3: Give up to 5 abdominal thrusts</h3>

<p>If back blows don't work, move behind them for abdominal thrusts (the Heimlich manoeuvre):</p>

<ol>
  <li>Stand behind the person and put your arms around their waist. Lean them forward.</li>
  <li>Make a fist and place it, thumb side in, just <strong>above the navel</strong> and well below the bottom of the breastbone.</li>
  <li>Grab your fist with your other hand.</li>
  <li>Pull <strong>sharply inwards and upwards</strong>, as if trying to lift them off their feet. Give up to 5 thrusts, checking after each one.</li>
</ol>

<h3>Step 4: Keep alternating until it clears</h3>

<p>If the object still hasn't come out, repeat <strong>5 back blows, then 5 abdominal thrusts</strong>. Keep going until the object comes out, the person can breathe and cough, or they become unresponsive.</p>

<div class="callout callout-info">
  <strong>Pregnant, very large or a small child?</strong>
  <p>If the person is visibly pregnant or so large that you can't reach around their stomach, give <strong>chest thrusts</strong> instead: wrap your arms under their armpits, place your fist on the lower half of the breastbone and pull sharply straight back towards you. For a child over one year, kneel behind them so you are at their height and use less force than for an adult. A small child can be laid face down across your lap for back blows.</p>
</div>

