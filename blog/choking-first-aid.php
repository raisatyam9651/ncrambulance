<h2>Choking baby under 1 year: what to do</h2>

<p>A baby's organs are delicate, so the technique is different. <strong>Never give abdominal thrusts to a baby under one year old.</strong> If the baby can cough or cry, let them cough and watch closely. If the baby can't cry, cough or breathe:</p>

<ol>
  <li><strong>Back blows:</strong> sit or kneel and lay the baby face down along your forearm, resting on your thigh, with the <strong>head lower than the body</strong>. Support the head by holding the jaw, keeping your fingers off the soft throat. Give up to <strong>5 firm back blows</strong> between the shoulder blades with the heel of your hand.</li>
  <li><strong>Chest thrusts:</strong> if the object hasn't come out, turn the baby face up along your other forearm, head still lower than the body. Using <strong>two fingers or the heel of one hand</strong> on the lower half of the breastbone, just below the nipple line, give up to <strong>5 sharp chest thrusts</strong>, pressing down about a third of the depth of the chest.</li>
  <li><strong>Repeat</strong> 5 back blows and 5 chest thrusts until the object comes out, the baby starts crying or coughing, or the baby becomes unresponsive. Call 112 or have someone call as soon as possible.</li>
</ol>

<p>After any serious choking episode, a baby should be checked by a doctor. Ask the dispatcher for a <a href="<?= link_to('neonatal') ?>">neonatal ambulance for babies and newborns</a> if the baby is very young or still struggling to breathe.</p>

<div class="callout callout-danger">
  <strong>Dangerous habits to avoid</strong>
  <p>Don't hang a child upside down by the ankles and shake them, give water, banana or rice to "push it down", or put your finger down the throat to make them vomit. Blind finger sweeps can push the object deeper and block the airway completely. Remove an object only if you can clearly see it and easily pick it out.</p>
</div>

<h2>What if you are alone and choking?</h2>

<p>If you are choking and nobody is around, don't go into a bathroom or another room to cough in private. Go to where people can see you, or make noise to get attention: bang on a door or knock things over. Then give yourself abdominal thrusts:</p>

<ul>
  <li>Place your fist just above your navel, grab it with your other hand and <strong>thrust sharply inwards and upwards</strong>.</li>
  <li>Or lean over the <strong>back of a chair</strong>, the edge of a table or a railing and press your upper stomach hard against it, again and again, until the object comes out.</li>
</ul>

<p>Once you can breathe, call 112 or an ambulance and get checked, especially if you used a chair or table edge for the thrusts.</p>

<h2>What if the person becomes unresponsive?</h2>

<p>If a choking person goes limp, carefully lower them to the floor so they don't fall and hit their head. Call 112 or an ambulance if no one has yet, and <strong>start CPR immediately</strong>. Chest compressions can push the object out.</p>

<p>Each time you open the mouth to give rescue breaths, look inside. If you can clearly see the object, pick it out. Otherwise, keep going with CPR until the ambulance crew takes over. Follow our guide to <a href="<?= post_url('how-to-do-cpr') ?>">CPR on an adult</a>, or the separate steps for <a href="<?= post_url('cpr-on-child-and-baby') ?>">CPR on a child or baby</a>, which give rescue breaths a bigger role.</p>

<p>If the person starts breathing again but is not fully awake, place them in the <a href="<?= post_url('unconscious-person-first-aid') ?>">recovery position for an unconscious person</a> and keep watching their breathing until help arrives.</p>

<h2>After the object comes out: get a medical check</h2>

<p>Even when choking ends well, the person may still need a doctor. Get them checked if:</p>

<ul>
  <li>you gave <strong>abdominal or chest thrusts</strong>, which can bruise or injure internal organs,</li>
  <li>they still have a cough, wheeze, noisy breathing or chest pain,</li>
  <li>they find it hard or painful to swallow, or feel something is still stuck,</li>
  <li>a child choked on a nut or seed and later develops a cough or fever, since small pieces can slip into the lungs and cause infection days later.</li>
</ul>

<p>A swallowed <strong>button battery or magnet</strong> is an emergency even if the child seems fine, because it can badly damage the food pipe within hours. Go to an emergency department immediately and don't make the child vomit.</p>

<h2>Common choking hazards in Indian homes</h2>

<ul>
  <li><strong>Food for young children:</strong> whole peanuts, roasted chana, popcorn, whole grapes, cherry tomatoes, jamun and other fruit with seeds, boiled sweets, and chunks of ladoo or barfi. Cut grapes into quarters lengthwise and avoid whole nuts for children under five.</li>
  <li><strong>Small objects:</strong> coins, buttons, marbles, small toy parts, balloon pieces, bottle caps, pen caps and button batteries from remotes and toys.</li>
  <li><strong>Adults and the elderly:</strong> large bites of roti or meat, eating while talking or laughing, loose dentures, alcohol, and swallowing problems after a stroke.</li>
</ul>

<p>Seat children while they eat, never let them run or play with food in their mouth, and keep small objects out of reach. Many choking myths still circulate in families, and our guide to <a href="<?= post_url('first-aid-myths-india') ?>">common first-aid myths in India</a> sets the record straight.</p>

