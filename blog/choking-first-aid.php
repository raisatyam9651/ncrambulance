<p>The good news is that the right first aid often clears the airway before the ambulance even arrives. This guide explains how to tell mild choking from severe choking, how to give back blows and abdominal thrusts, what to do for a baby under one year, how to help yourself if you are alone, and what to do if the person collapses. If the airway doesn't clear quickly, call 112 or our <a href="<?= link_to('emergency') ?>">24/7 emergency ambulance service</a> straight away.</p>

<h2>How to tell mild choking from severe choking</h2>

<p>Choking happens when food or an object blocks the airway. The first thing to work out is whether the blockage is <strong>partial (mild)</strong> or <strong>complete (severe)</strong>. Ask: "Are you choking?"</p>

