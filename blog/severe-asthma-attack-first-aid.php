<h2>How to use an inhaler with a spacer</h2>

<p>A spacer is a plastic tube that fits on the inhaler. It holds the medicine cloud so the person can breathe it in slowly, which gets far more of the medicine into the lungs, especially when they are breathless and panicking.</p>

<ol>
  <li>Remove the inhaler cap, shake the inhaler and fit it into the end of the spacer.</li>
  <li>Ask the person to breathe out gently, then seal their lips around the spacer mouthpiece. Young children should use a spacer with a face mask fitted snugly over the nose and mouth.</li>
  <li>Press the inhaler once to release one puff into the spacer.</li>
  <li>Let them breathe in and out slowly through the spacer for about four to five breaths, or take one slow deep breath and hold it for up to 10 seconds if they can.</li>
  <li>Remove, shake again and repeat for each puff.</li>
</ol>

<div class="callout callout-tip">
  <strong>Homemade spacer in an emergency</strong>
  <p>If there is no spacer, a clean, empty 500 ml plastic water or soft-drink bottle can work. Cut a hole in the base just big enough for the inhaler mouthpiece, push the inhaler in so it fits snugly, and have the person breathe through the bottle's open neck. Use it exactly like a normal spacer, one puff at a time. A paper cup with a hole in the bottom can also help. Without any spacer, use the inhaler directly: breathe out, seal the lips around the mouthpiece, press once as they start a slow breath in, then hold the breath.</p>
</div>

<p>Some people use a dry-powder inhaler, such as a capsule device, which doesn't work with a spacer. Help them take their doses as their doctor advised and call for help if they aren't improving.</p>

<h2>What to do if there is no inhaler</h2>

<p>There is <strong>no home substitute</strong> for a reliever inhaler in a severe attack. If the person doesn't have their inhaler, the most important thing you can do is get an ambulance on the way quickly.</p>

<ul>
  <li><strong>Call 112 or an ambulance immediately.</strong> Don't wait to see if it passes. Tell the dispatcher there is no inhaler.</li>
  <li><strong>Keep them upright</strong>, leaning slightly forward, and stay with them.</li>
  <li><strong>Coach slow breathing:</strong> in gently through the nose, then out slowly through pursed lips, as if blowing out a candle. Breathe with them and count slowly. This can ease panic and help empty trapped air.</li>
  <li><strong>Remove the trigger</strong> and move them to cleaner air. On a smoggy day, stay indoors with windows closed and an air purifier on if you have one.</li>
  <li><strong>Ask the dispatcher</strong> before using any medicine that isn't theirs. If a neighbour has a reliever inhaler, mention it and follow the dispatcher's advice.</li>
</ul>

<div class="callout callout-danger">
  <strong>Home remedies that waste time</strong>
  <p>Steam inhalation, hot coffee or tea, honey and ginger, ajwain potlis, mustard oil or balm rubs on the chest, and breathing into a paper bag do not treat a severe asthma attack. Some can make it worse: steam can irritate the airways and a paper bag reduces the oxygen they breathe. Don't nebulise someone with another person's medicine. Use the reliever, keep them upright and call for help.</p>
</div>

<h2>If things get worse: when to start CPR</h2>

<p>If the person becomes so exhausted that they can't stay awake, or they stop responding, lay them on their back on the floor and check their breathing. If they are <strong>unresponsive and not breathing normally</strong>, start CPR straight away and keep going until the crew takes over. Breaths are especially important in asthma, because the problem started with oxygen. Follow our guide on <a href="<?= post_url('how-to-do-cpr') ?>">how to do CPR on an adult</a>.</p>

<p>A patient with a life-threatening attack may need oxygen, nebulised medicines and sometimes breathing support during the journey. In the most severe cases, doctors may ask for a <a href="<?= link_to('ventilator') ?>">ventilator ambulance for patients who need breathing support</a>, particularly for a transfer between hospitals.</p>

