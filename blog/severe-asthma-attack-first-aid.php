<p>It is a smoggy November evening in Delhi NCR. Your teenage son comes home from tuition wheezing, his shoulders heaving, and he can only say two or three words before stopping to breathe. His inhaler is in the school bag he left in a friend's car. Or your elderly mother, whose asthma has been worse since Diwali, is sitting on the edge of the bed, too breathless to speak.</p>

<p>A severe asthma attack can become life-threatening within minutes, but the right first aid helps the airways open while help is on the way. This guide explains the danger signs, the right position, how to use an inhaler with a spacer (including a homemade one), and what to do if there is no inhaler at all. In a severe attack, ask for an <a href="<?= link_to('als') ?>">ALS ambulance with oxygen support and emergency medicines</a>.</p>

<h2>Signs that an asthma attack is life-threatening</h2>

<p>During an asthma attack, the airways in the lungs tighten, swell and fill with mucus, so air can't get in and out easily. Call <strong>112</strong> or an ambulance immediately if the person has any of these signs:</p>

<ul>
  <li><strong>Can't speak in full sentences</strong>, or is too breathless to eat, walk or talk.</li>
  <li><strong>Blue or grey lips, tongue or fingertips</strong>, or very pale, sweaty skin.</li>
  <li><strong>Exhaustion, drowsiness or confusion</strong>, as the effort of breathing wears them out.</li>
  <li><strong>The reliever inhaler isn't helping</strong>, or they need it again within minutes.</li>
  <li><strong>Skin sucking in</strong> between the ribs or at the base of the throat with each breath, or nostrils flaring in a child.</li>
  <li><strong>A "quiet chest"</strong>: wheezing that becomes softer or stops, while they are still struggling.</li>
</ul>

<div class="callout callout-danger">
  <strong>Less wheezing can mean worse, not better</strong>
  <p>Wheezing is the sound of air squeezing through narrowed airways. If the wheeze fades but the person still looks distressed, drowsy or blue, it can mean very little air is moving at all. This is a sign of a life-threatening attack. Call an ambulance immediately.</p>
</div>

<h2>What position helps breathing?</h2>

<p><strong>Sit the person upright, leaning slightly forward</strong>, with their hands resting on their knees or on a table in front of them. This position lets the chest and breathing muscles work most easily. Many people instinctively take it.</p>

<ul>
  <li>Never make them lie down flat. It makes breathing harder.</li>
  <li>Loosen tight collars, ties, belts, saris or anything around the chest and waist.</li>
  <li>Move them away from the trigger: smoke, incense, mosquito coils, dust, perfume or cold air.</li>
  <li>Stay calm and speak slowly. Panic makes the muscles tighten and the breathing faster.</li>
</ul>

<h2>What to do during a severe asthma attack: step by step</h2>

<h3>Step 1: Sit them up and keep them calm</h3>

<p>Get them into the upright, slightly forward position and stay with them. Reassure them that help is coming. If they show any of the danger signs above, call 112 or an ambulance <em>now</em>, before you do anything else, and put the phone on speaker.</p>

<h3>Step 2: Help them use their reliever inhaler</h3>

<p>The <strong>reliever inhaler</strong> contains a medicine such as salbutamol or levosalbutamol that relaxes the airway muscles within minutes. In many countries relievers are blue, but in India the colour varies by brand, so check the label. Help the person take <strong>1 puff every 30 to 60 seconds, up to 10 puffs</strong>, ideally through a spacer. Shake the inhaler before each puff.</p>

<p>If the person uses one combined inhaler for both prevention and relief, as some doctors now prescribe, follow their written asthma action plan, because the number of extra puffs can differ.</p>

<h3>Step 3: Call an ambulance if they don't improve</h3>

<p>If they feel <strong>worse at any point</strong>, or are <strong>not better after 10 puffs</strong>, call 112 or an ambulance immediately. Say: "Severe asthma attack, can't speak properly, reliever not working," and give the address with a landmark.</p>

<h3>Step 4: Repeat the puffs while you wait</h3>

<p>If the ambulance hasn't arrived after 10 minutes and they are still struggling, repeat <strong>1 puff every 30 to 60 seconds, up to 10 puffs</strong>. A reliever inhaler is safe to use like this in an emergency. A shaky feeling or fast heartbeat is a common side effect and not a reason to stop.</p>

<h3>Step 5: Prepare for the ambulance crew</h3>

<p>Keep the inhalers, spacer, any written asthma action plan and a list of the person's medicines ready to hand over. Send someone to unlock the gate, call the lift and guide the crew in. Even if the attack settles, the person should be seen by a doctor the same day, because severe attacks can return.</p>

