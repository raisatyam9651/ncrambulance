<h2>Dust, grit or an insect in the eye</h2>

<ul>
  <li><strong>Don't rub.</strong> Rubbing scratches the clear front surface of the eye and can push the particle in deeper.</li>
  <li>Let the eye water and blink several times. Gently pulling the upper lid down over the lower lashes can help sweep the particle out.</li>
  <li>Rinse with clean water from a cup or a gentle stream.</li>
  <li>If you can see the particle on the white of the eye, try to lift it off with the damp corner of a clean cloth. Never touch the coloured part of the eye.</li>
  <li>If it won't come out, the eye still feels gritty, or it came from grinding, drilling or hammering metal, see a doctor. Fast-moving particles can embed in the eye.</li>
</ul>

<h2>A blow to the eye</h2>

<p>A cricket ball, a fist or a fall can cause a black eye. Hold a cold compress, such as ice wrapped in a cloth or a cold pack, gently against the area around the eye for about 10 minutes, without pressing on the eyeball itself.</p>

<p>Go to hospital urgently if there is blurred or double vision, blood in the eye, severe pain, an eye that can't move normally, numbness of the cheek, or vomiting. Don't let them blow their nose after a hard blow to the face, as the bones around the eye may be broken. A heavy blow can also injure the brain, so check the warning signs in our <a href="<?= post_url('head-injury-first-aid') ?>">head injury first-aid guide</a>.</p>

<h2>Why you should never rub, press or put remedies in an injured eye</h2>

<p>The eye is a delicate, fluid-filled ball. Rubbing it drags particles across its clear surface, causing painful scratches that can become infected. Pressing on an eye that has been cut or punctured can squeeze out the fluid and tissue inside, which may cause permanent loss of sight. That's why the advice for serious injuries is to shield the eye without touching it.</p>

<p>Home remedies such as rose water, ghee, honey, kajal, breast milk or someone else's eye drops aren't sterile and can cause infection or hide how serious the injury is. Don't use any eye drops unless a doctor has prescribed them for this injury. Our guide to <a href="<?= post_url('first-aid-myths-india') ?>">first-aid myths in India</a> covers more of these well-meant but harmful habits.</p>

<h2>If things get worse</h2>

<p>Eye injuries from explosions, road accidents or assaults often come with other injuries. Check the whole person, and deal first with anything that threatens life: heavy bleeding, serious burns or difficulty breathing. If they stop responding and aren't breathing normally, call 112 and start CPR; the eye can wait. If they feel faint, help them lie down with the head and shoulders raised, keeping the eye shield in place.</p>

<p>Workshops, factories and construction sites in industrial areas across the NCR see frequent eye injuries from metal and chemicals. Keep clean water or an eyewash station ready, insist on safety glasses, and save the number for an <a href="<?= link_to('ghaziabad') ?>">emergency ambulance in Ghaziabad</a> along with your nearest eye hospital.</p>

