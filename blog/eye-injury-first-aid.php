<h2>Object stuck in the eye: don't pull it out</h2>

<p>Fragments from a firecracker, a metal chip from grinding or welding, glass from a broken windscreen or a sharp stick can pierce the eye. If anything is stuck in the eye, or you think the eyeball has been cut or punctured:</p>

<ul>
  <li><strong>Don't remove the object</strong>, however small. Pulling it out can cause more damage and let the contents of the eye leak out.</li>
  <li><strong>Don't press on the eye</strong> or rub it, and don't try to rinse it.</li>
  <li><strong>Shield the eye</strong> with a paper cup, the bottom of a plastic glass or a cut-off plastic bottle, placed so it doesn't touch the object, and tape it loosely to the forehead and cheek.</li>
  <li><strong>Cover the other eye</strong> loosely with a clean cloth too. Both eyes move together, so keeping the good eye still reduces movement of the injured one.</li>
  <li><strong>Keep them still and sitting upright</strong> or half-sitting. Ask them not to bend over, strain or blow their nose.</li>
  <li><strong>Give nothing to eat or drink</strong>, because they may need surgery.</li>
</ul>

<p>With both eyes covered the person can't see, so stay with them, explain everything you are doing and guide them by the arm. This is one situation where an ambulance is much safer than an auto or a two-wheeler. For a stable patient who can't travel alone, a <a href="<?= link_to('bls') ?>">BLS ambulance with a trained attendant</a> is usually enough.</p>

<h2>Firecracker eye injuries on Diwali</h2>

<p>Every Diwali, eye departments across Delhi NCR see a rise in firecracker injuries, many of them in children and in bystanders who were only watching. A cracker can cause a burn, a blast injury and flying fragments all at once, so treat the eye as possibly pierced unless the injury is clearly minor:</p>

<ul>
  <li>If the eye may have been cut or hit by fragments, follow the steps above: don't rinse, don't press, shield the eye and go to hospital.</li>
  <li>If only the skin around the eye is burned, cool the skin with gently running clean water without pressing on the eye. Our guide to <a href="<?= post_url('burns-first-aid') ?>">burns first aid</a> explains how to cool burns safely.</li>
  <li>If powder or residue has gone into the eye and there is no wound, flush it as you would a chemical splash.</li>
  <li>Check the face, hands and body for other burns and injuries.</li>
</ul>

<p>To prevent these injuries, let adults light the crackers, keep children at a safe distance, wear glasses or protective goggles, never hold a lit cracker in the hand, never bend over one that didn't go off, and keep a bucket of water nearby.</p>

