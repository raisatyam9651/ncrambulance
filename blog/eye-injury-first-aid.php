<p>Eye injuries happen in the most ordinary moments. A toddler gets hold of the little packet of chuna from a grandparent's paan box and rubs it into an eye. Cement splashes up at a building site. A metal chip flies off a grinder in a workshop. And every Diwali, a rocket or anar bursts close to someone's face. In each case, what you do in the first few minutes can decide how much sight is saved.</p>

<p>This guide explains how to flush a chemical splash properly, what to do if something is stuck in the eye, how to handle a firecracker injury, and which home remedies cause harm. Serious eye injuries need a hospital with an eye emergency service quickly, so call 112 or our <a href="<?= link_to('emergency') ?>">emergency ambulance service</a> while you start first aid.</p>

<h2>Which eye injuries are emergencies?</h2>

<p>Get to hospital immediately, by ambulance if needed, for:</p>

<ul>
  <li>any chemical in the eye, especially lime (chuna), cement or cleaning chemicals</li>
  <li>an object stuck in the eye, or any cut or puncture to the eyeball</li>
  <li>a firecracker or explosion injury</li>
  <li>blood visible in front of the coloured part of the eye, or a pupil that looks misshapen</li>
  <li>sudden blurred vision, double vision or loss of vision</li>
  <li>severe pain, or an eye that can't open or move normally after a blow</li>
</ul>

<h2>Chemical splash in the eye: step by step</h2>

<p>With chemicals, every second of contact causes more damage. Start rinsing first and ask questions later.</p>

<h3>Step 1: Start flushing with water immediately</h3>

<p>Don't wait to find eye drops or to reach a doctor. Use the nearest source of clean water: a tap, a shower, a jug, a mug or bottled water. Clean drinking water is ideal and lukewarm water is more comfortable, but any clean water now is better than perfect water later. If there is dry powder such as chuna or cement on the face, quickly brush it away from the eyes first so you don't wash more of it in.</p>

<h3>Step 2: Hold the eyelids open and tilt the head</h3>

<p>The eyelids will clamp shut with pain, so gently hold them open with your fingers. Tilt the head so the injured eye is lower, and pour from the inner corner near the nose outwards, so the water runs away from the other eye. Ask the person to roll the eye up, down and side to side so water reaches every part. If both eyes are affected, rinse both, under a shower or by alternating between them.</p>

<h3>Step 3: Remove contact lenses</h3>

<p>If they wear contact lenses, take them out, or ask them to, once flushing has started. Lenses can trap the chemical against the eye. Don't stop flushing for long to do this.</p>

<h3>Step 4: Keep flushing for at least 15 to 20 minutes</h3>

<p>Rinse continuously for at least 15 to 20 minutes, and longer for alkalis such as lime or cement. Use a phone timer, because it will feel much longer than it is. Meanwhile, someone else should call 112 or an ambulance and find the chemical's container or label.</p>

<h3>Step 5: Go straight to hospital</h3>

<p>After flushing, go directly to a hospital with an eye emergency service, even if the eye feels better. Keep rinsing on the way if you can. Take the container or a photo of its label. Don't cover the eye tightly or put anything in it.</p>

