<h2>What can bystanders do to save time? Step by step</h2>

<h3>Step 1: Recognise it and call immediately</h3>

<p>The biggest delays happen before anyone picks up the phone: "let's see if it settles", "let's call his son first", "it's probably acidity". If you suspect something serious, call 112 or an ambulance helpline straight away. Calling early and being wrong costs you very little. Waiting and being wrong can cost a life.</p>

<h3>Step 2: Give a precise location</h3>

<p>Give the full address, floor, tower, landmark and pin code, and share a WhatsApp live location. A crew that has to search for you loses the minutes you just saved. Our guide on <a href="<?= post_url('how-to-call-ambulance-delhi-ncr') ?>">what to tell the ambulance dispatcher</a> has a ready script.</p>

<h3>Step 3: Start CPR if they aren't breathing normally</h3>

<p>If the person doesn't respond and isn't breathing normally, start chest compressions immediately and send someone to find an AED. For a cardiac arrest, nothing a bystander does buys more time than this. Our guide to <a href="<?= post_url('how-to-do-cpr') ?>">hands-only CPR for adults</a> shows how.</p>

<h3>Step 4: Control heavy bleeding</h3>

<p>Press firmly on the wound with a clean cloth, or with your hand if nothing else is available, and keep pressing until help arrives. Don't keep lifting the cloth to check; add more on top if blood soaks through. See <a href="<?= post_url('how-to-stop-severe-bleeding') ?>">how to stop severe bleeding</a> for more.</p>

<h3>Step 5: Ask for the right ambulance</h3>

<p>Tell the dispatcher the problem in plain words: "chest pain", "can't speak properly", "bleeding heavily after an accident". This helps them send the right type of ambulance and plan the right hospital, as explained below.</p>

<h3>Step 6: Be ready to go</h3>

<p>Note the time the symptoms started and any medicine you gave. Keep the patient's medicines, recent reports and ID in one bag, unlock the gate and hold the lift. Tell the crew if the patient already has a hospital with their records.</p>

