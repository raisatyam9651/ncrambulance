<h2>If the person collapses while you wait</h2>

<p>If the person stops responding and isn't breathing normally, or is only gasping, tell the dispatcher and start CPR right away. Put the heel of your hand in the centre of the chest, your other hand on top, and push hard and fast, 100 to 120 times a minute, about 5 to 6 cm deep. Switch on an AED as soon as it arrives and follow its voice prompts. Don't stop until the crew takes over.</p>

<p>If they are unconscious but breathing normally, and you don't suspect a neck or back injury, turn them onto their side in the recovery position and keep checking their breathing until help arrives.</p>

