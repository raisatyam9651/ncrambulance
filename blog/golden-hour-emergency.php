<p>A delivery rider is knocked off his bike at a busy junction. A grandmother's speech slurs at the dinner table. A colleague complains of "gas" and sits quietly at his desk, sweating. In each case, the people nearby have a choice: act in the first few minutes, or wait to see what happens. The minutes spent deciding often decide how much can be saved.</p>

<p>Doctors call this window the "golden hour". This guide explains what it really means, where the idea comes from, how it applies to heart attacks, strokes and accidents, and the practical things you can do to save time until the <a href="<?= link_to('emergency') ?>">emergency ambulance</a> reaches you.</p>

<h2>What is the golden hour?</h2>

<p>The golden hour is the idea that the first hour or so after a serious injury or sudden illness is when treatment makes the biggest difference. The sooner the right care starts, the better the chance of survival, and of recovering without lasting damage.</p>

<p>It is a principle, not a stopwatch. A patient isn't safe at 59 minutes and lost at 61. For some emergencies, such as a cardiac arrest, the critical window is a few minutes. For others, it stretches over a few hours. The lesson is the same in every case: don't waste time.</p>

<h2>Where does the golden hour idea come from?</h2>

<p>The term comes from trauma care and is most closely associated with Dr R Adams Cowley, an American surgeon who pioneered dedicated trauma centres. He argued that what happened in the short time between a severe injury and definitive treatment, meaning care that actually fixes the problem, such as surgery to stop internal bleeding, largely decided whether a patient lived.</p>

<p>Later research hasn't found a magic 60-minute cut-off, and doctors now apply the idea far beyond injuries. But the core lesson has held up across emergency medicine: earlier definitive care improves outcomes. That is why ambulance systems, trauma centres and hospital emergency teams are organised around saving time.</p>

