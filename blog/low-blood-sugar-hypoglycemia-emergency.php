<p>It is four in the afternoon in a Delhi office. Your colleague, who takes insulin for diabetes, skipped lunch to finish a report, and now he is sweating, shaky and snapping at people for no reason. Minutes later his speech is slurred and someone jokes that he looks drunk. He isn't drunk: his blood sugar has crashed and his brain is running out of fuel.</p>

<p>Severe low blood sugar (hypoglycaemia) is one of the most common emergencies in people with diabetes, and one of the easiest to reverse if someone acts early. This guide explains how to spot it, exactly how much sugar to give, what to do if the person can't swallow, and when to call an <a href="<?= link_to('emergency') ?>">emergency ambulance for a diabetic emergency</a>.</p>

<h2>What is hypoglycaemia and who is at risk?</h2>

<p>Hypoglycaemia means the glucose level in the blood has dropped too low, usually <strong>below 70 mg/dL</strong>. The brain runs almost entirely on glucose, so when the level falls, thinking, behaviour and consciousness are the first things to suffer. Left untreated, a severe low can cause a seizure and unconsciousness.</p>

<p>It mostly affects people with diabetes who take <strong>insulin</strong> or a group of tablets called <strong>sulfonylureas</strong> (glimepiride and gliclazide are common examples). Metformin on its own rarely causes a low. The usual triggers are:</p>

<ul>
  <li><strong>A skipped, late or smaller meal</strong>, or vomiting that stops food staying down.</li>
  <li><strong>More exercise or physical work than usual</strong>, such as a long walk, gardening or an evening on the dance floor at a wedding.</li>
  <li><strong>Alcohol</strong>, especially on an empty stomach. The low can come hours later, even overnight.</li>
  <li><strong>Fasting</strong> for a vrat, Navratri, Karva Chauth or Ramzan without adjusting medicines with a doctor.</li>
  <li><strong>Too much insulin</strong>, a double dose taken by mistake, or an injection at the wrong time.</li>
</ul>

<p>Older people, people with kidney disease and those who have had diabetes for many years are at higher risk. Some of them stop feeling the early warning signs, so a low can arrive with little warning.</p>

<h2>Signs of low blood sugar</h2>

<p>A low usually develops over minutes, not hours. The early signs are the body's alarm system:</p>

<ul>
  <li>Shaking or trembling hands</li>
  <li>Sweating, with cold and clammy skin</li>
  <li>Sudden, strong hunger</li>
  <li>A pounding or racing heart (palpitations)</li>
  <li>Anxiety, irritability or a sudden change in mood</li>
  <li>A pale face and tingling lips</li>
</ul>

<p>If the sugar keeps falling, the brain starts to struggle:</p>

<ul>
  <li>Confusion, poor concentration, odd or aggressive behaviour</li>
  <li>Slurred speech and unsteady walking</li>
  <li>Blurred or double vision</li>
  <li>Drowsiness, then seizures or unconsciousness</li>
</ul>

