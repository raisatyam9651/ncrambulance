<h2>If they are drowsy, fitting or unconscious</h2>

<p>Once the person can't swallow safely, the plan changes completely.</p>

<ol>
  <li><strong>Give nothing by mouth.</strong> No sugar, juice, water or honey, not even a pinch of sugar under the tongue. It can go into the windpipe and choke them.</li>
  <li><strong>Call 112 or an ambulance immediately.</strong> Say: "Diabetic, suspected low sugar, unconscious, breathing," and give the address with a landmark. Where possible, ask for an <a href="<?= link_to('als') ?>">ALS ambulance with trained medical staff</a>, as the crew can check the sugar and give glucose into a vein.</li>
  <li><strong>Put them in the recovery position</strong> if they are breathing, so saliva or vomit drains out of the mouth. Our guide to <a href="<?= post_url('unconscious-person-first-aid') ?>">first aid for an unconscious person</a> shows how.</li>
  <li><strong>If they have a seizure</strong>, clear the space around them, cushion the head, and don't hold them down or put anything in the mouth. See <a href="<?= post_url('seizure-first-aid') ?>">what to do during a seizure</a>.</li>
  <li><strong>Glucagon</strong>: some people with diabetes are prescribed a glucagon injection or nasal spray for exactly this situation. Use it only if it was prescribed for them and you have been shown how, following the pack instructions. They may vomit afterwards, so keep them on their side.</li>
  <li><strong>Stay with them</strong> and keep watching their breathing until the crew arrives.</li>
</ol>

<div class="callout callout-danger">
  <strong>Never force sugar into an unconscious person</strong>
  <p>In panic, families often pour sweet tea, sugar water or honey into the mouth of someone who has collapsed. In an unconscious person the swallowing reflex doesn't work, so the liquid can go straight into the lungs. It does far more harm than good. Wait for the ambulance crew, who can give sugar safely through a drip.</p>
</div>

<h2>If they stop breathing</h2>

<p>Rarely, a severe low leads to collapse and breathing stops. If the person does not respond and is not breathing normally (no breathing, or only occasional gasps), start hands-only CPR straight away: push hard and fast in the centre of the chest, 100 to 120 times a minute, until help arrives. Our <a href="<?= post_url('how-to-do-cpr') ?>">step-by-step guide to hands-only CPR</a> explains the technique.</p>

<h2>When to call an ambulance for low blood sugar</h2>

<ul>
  <li>They are drowsy, getting more confused, fitting or unconscious.</li>
  <li>They are not better after two rounds of sugar.</li>
  <li>The low was caused by too much insulin or too many tablets, whether by mistake or on purpose.</li>
  <li>They hurt themselves when they fell, especially their head.</li>
  <li>They are not known to have diabetes, so the cause is unclear.</li>
  <li>They live alone and nobody can stay with them for the next few hours.</li>
</ul>

<p>If the person has fully recovered but still needs to be taken for a check-up, a <a href="<?= link_to('bls') ?>">BLS ambulance for stable patients</a>, with oxygen and a trained attendant, is usually enough. The dispatcher can help you decide.</p>

