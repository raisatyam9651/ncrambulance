<p><strong>If you can't tell which it is and the person is conscious and able to swallow, give sugar.</strong> A little extra sugar won't make high sugar meaningfully worse, but it can quickly reverse a low that would otherwise become dangerous. Then get the sugar checked. Never give an extra insulin dose yourself to "bring the sugar down" unless the person's doctor has given them a clear written plan.</p>

