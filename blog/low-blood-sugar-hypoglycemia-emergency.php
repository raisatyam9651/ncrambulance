<h2>The 15-15 rule: step by step</h2>

<p>If the person is awake and can swallow, this is the standard method recommended by diabetes specialists. It is simple enough for anyone to follow.</p>

<h3>Step 1: Sit them down and check the sugar if you can</h3>

<p>Help them sit down so they don't fall. If they or someone nearby has a glucometer, check the level: below 70 mg/dL confirms a low. If there is no meter, <strong>don't wait</strong>. Treat based on the symptoms.</p>

<h3>Step 2: Give 15 g of fast-acting sugar</h3>

<p>Any one of these contains roughly 15 g of sugar that the body absorbs quickly:</p>

<ul>
  <li>3 to 4 teaspoons of table sugar or glucose powder dissolved in a small glass of water</li>
  <li>About 150 ml (a small glass) of fruit juice</li>
  <li>About 150 ml of a regular soft drink, not a diet, zero or sugar-free one</li>
  <li>Glucose tablets: check the pack for how many make 15 g</li>
</ul>

<p>Avoid chocolate, mithai made with ghee or khoya, ice cream and nuts for this first dose. The fat in them slows down how fast the sugar gets into the blood, so they take too long to work.</p>

<h3>Step 3: Wait 15 minutes, then check again</h3>

<p>Keep them sitting and resting. Don't let them walk off, climb stairs or drive. After 15 minutes, recheck the sugar or ask how they feel. Most people start to feel better within 10 to 15 minutes.</p>

<h3>Step 4: Repeat if they are still low</h3>

<p>If the reading is still below 70 mg/dL or the symptoms haven't improved, give another 15 g of fast sugar and wait another 15 minutes. If they are not better after two rounds, or they become more drowsy or confused at any point, <strong>call an ambulance</strong>.</p>

<h3>Step 5: Follow with a starchy snack</h3>

<p>Fast sugar is used up quickly, and the level can drop again. Once they feel better, give something that releases energy slowly: a roti, a slice of bread, a few biscuits, a glass of milk, or their next meal if it is due. If the low was caused by long-acting insulin or a sulfonylurea tablet, the sugar can fall again over several hours, so someone should stay with them and they should speak to their doctor the same day.</p>

