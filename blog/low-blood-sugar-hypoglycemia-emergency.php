<h2>Preventing the next low</h2>

<ul>
  <li>Anyone on insulin or sulfonylureas should carry glucose tablets, sugar sachets or a small juice pack at all times.</li>
  <li>Eat meals on time, and have a snack before extra exercise or physical work.</li>
  <li>Before fasting for a festival or Ramzan, ask the doctor how to adjust the doses.</li>
  <li>Check the sugar before driving or a long journey.</li>
  <li>Drink alcohol only with food, if at all.</li>
  <li>Tell family, colleagues and your driver what a low looks like and where the sugar is kept.</li>
</ul>

