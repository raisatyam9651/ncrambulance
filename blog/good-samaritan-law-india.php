<h2>Who is a Good Samaritan?</h2>

<p>Under Indian law, a Good Samaritan is a person who, in good faith, voluntarily and without expecting any reward, gives emergency medical or non-medical help to a victim at the scene of an accident, or takes the victim to hospital. You don't need to be a doctor or have first-aid training. Calling 112, warning traffic, pressing on a wound or driving someone to hospital all count.</p>

<h2>What does the Good Samaritan law say?</h2>

<p>The protection was built in three stages:</p>

<ol>
  <li><strong>2015: Government guidelines.</strong> The Ministry of Road Transport and Highways (MoRTH) issued guidelines to protect Good Samaritans from harassment by the police and hospitals.</li>
  <li><strong>2016: The Supreme Court.</strong> In <em>SaveLIFE Foundation v. Union of India</em>, the Supreme Court gave these guidelines the force of law, making them binding.</li>
  <li><strong>2019: Section 134A of the Motor Vehicles Act.</strong> The Motor Vehicles (Amendment) Act, 2019 added Section 134A, which gives Good Samaritans protection in the law itself.</li>
</ol>

<p>Section 134A says a Good Samaritan shall not be liable for any civil or criminal action for injury to, or the death of, the victim caused by their negligence while giving emergency care in good faith. In simple terms: if you honestly try to help and something goes wrong, the law says you are not to be held responsible for it.</p>

<h2>Do you have to give your name or pay?</h2>

<ul>
  <li><strong>Your name is optional.</strong> No one can force you to disclose your name, address, phone number or other identity details, whether at the hospital or to the police. You can share them voluntarily if you wish.</li>
  <li><strong>You can leave.</strong> Once you have informed the police or the hospital about the victim, you are free to go. You don't have to wait until relatives arrive.</li>
  <li><strong>You don't pay.</strong> A hospital cannot demand payment or registration fees from you for the victim's treatment.</li>
</ul>

<h2>Can the police force you to be a witness?</h2>

<p>No. Being a witness is your choice. If you do volunteer to be a witness, the guidelines say you should be examined only once, at a time and place convenient to you. The examination can also be done in ways that save you a trip to the police station or court, such as by video conferencing or through an affidavit.</p>

<p>Many people avoid helping because they picture years of court dates. That is exactly what the protections were designed to prevent.</p>

<h2>What are your rights at the hospital?</h2>

<ul>
  <li>The hospital must not delay emergency care for the victim. Treatment comes first; paperwork comes later.</li>
  <li>It can't detain you or make you wait until the victim's family or the police arrive.</li>
  <li>It can't demand payment or registration fees from you.</li>
  <li>It can't force you to fill in your personal details.</li>
</ul>

<p>Formalities such as registering an accident case and informing the police are handled by the hospital. They are not a reason to delay treatment, and they don't require you to stay.</p>

