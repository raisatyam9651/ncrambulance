<h2>If the victim stops breathing</h2>

<p>If the victim doesn't respond and isn't breathing normally, or is only gasping, roll them gently onto their back while keeping the head, neck and body in a straight line, and start CPR. Push hard and fast in the centre of the chest, 100 to 120 times a minute, about 5 to 6 cm deep, until the crew takes over. Our guide to <a href="<?= post_url('how-to-do-cpr') ?>">hands-only CPR</a> shows how. Section 134A covers this too: an honest attempt at CPR is protected.</p>

<p>If they are unconscious but breathing normally, leave them as they are and keep checking their breathing. Turn them onto their side, keeping the head, neck and body in line, only if they start vomiting or you have to leave them to get help. For the full picture, read our <a href="<?= post_url('road-accident-first-aid') ?>">road accident first-aid guide</a>.</p>

