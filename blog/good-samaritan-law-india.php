<p>Many states also give cash rewards to Good Samaritans who help road accident victims reach hospital. The rules vary, so ask your local police or transport department.</p>

<h2>What to say at the hospital</h2>

<p>If you bring a victim to the emergency department, or go along in the ambulance, you only need to share what helps the doctors. Keep it short and calm.</p>

<div class="callout callout-tip">
  <strong>A simple script</strong>
  <p>"I'm a Good Samaritan. I found this person injured near [place] at about [time]. I don't know them. They were [awake or unconscious] and I [pressed on the bleeding or gave CPR]. I've informed you, and I'd now like to leave."</p>
</div>

<p>If anyone asks you to pay, to sign as the patient's relative or to wait for the police, say politely that you are a Good Samaritan and that the guidelines protect you. You can still choose to stay, or to leave your number for the family, if you want to.</p>

<h2>Should you take the victim to hospital yourself?</h2>

<p>The law protects you either way: taking a victim to hospital is one of the things a Good Samaritan does. But an ambulance is usually the safer choice for a badly injured person, because the crew can support breathing, control bleeding and keep the spine still on the way. If the ambulance will be delayed, ask the dispatcher for advice. If you must use a car, several people should lift the victim together, keeping the head, neck and body in a straight line, and keep them as flat and still as possible on the way.</p>

<h2>How to help an accident victim safely: step by step</h2>

<h3>Step 1: Keep yourself safe</h3>

<p>Park well away from the crash, switch on your hazard lights and watch for moving traffic. Don't approach if there is fire, leaking fuel or a fallen electric wire. On a highway or expressway, ask others to warn oncoming vehicles from a safe distance. You can't help anyone if you are hit too.</p>

<h3>Step 2: Call 112 or an ambulance</h3>

<p>Give the exact location (the road, direction of travel, and the nearest landmark, exit, flyover or kilometre stone), the number of people hurt, and whether anyone is trapped or unconscious. Our guide on <a href="<?= post_url('how-to-call-ambulance-delhi-ncr') ?>">calling an ambulance in Delhi NCR</a> explains what to say.</p>

<h3>Step 3: Check response and breathing</h3>

<p>Speak loudly and tap their shoulder. If they respond, tell them help is coming and keep talking to them. If they don't respond and aren't breathing normally, start CPR (see below).</p>

<h3>Step 4: Stop heavy bleeding</h3>

<p>Press firmly on the wound with a clean cloth, dupatta or handkerchief, and keep pressing. If something is stuck in the wound, don't pull it out; press around it instead. Read <a href="<?= post_url('how-to-stop-severe-bleeding') ?>">how to control severe bleeding</a> for more detail.</p>

<h3>Step 5: Keep them still</h3>

<p>After any serious crash, assume the neck or back may be injured. Unless the person is in immediate danger, don't lift them, sit them up or take off a rider's helmet. Keep the head and neck steady in the position you found them. See our guide to <a href="<?= post_url('spinal-injury-first-aid') ?>">first aid for a suspected spinal injury</a>.</p>

<h3>Step 6: Hand over, then stay or go</h3>

<p>When the ambulance crew arrives, tell them what you saw and what you did. An <a href="<?= link_to('als') ?>">ALS ambulance with trained medical staff</a> can monitor and treat the victim on the way to hospital. You may go along, stay to help the police, or leave once you have informed the police or hospital. It is your choice.</p>

