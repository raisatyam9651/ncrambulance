<p>The law has changed, and it is firmly on the helper's side. This guide explains, in plain words, what India's Good Samaritan law says, your rights with the police and at the hospital, and how to help a victim safely until the <a href="<?= link_to('emergency') ?>">emergency ambulance</a> arrives.</p>

