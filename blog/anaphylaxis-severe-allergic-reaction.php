<h2>Can antihistamines treat anaphylaxis?</h2>

<p>No. Antihistamine tablets and syrups, such as cetirizine, can ease itching and hives in a mild reaction. But they don't open the airways, reduce throat swelling or raise blood pressure, and they take too long to work. Waiting for a tablet to work wastes the minutes that matter most.</p>

<div class="callout callout-danger">
  <strong>A tablet is not enough</strong>
  <p>Never give an antihistamine and wait to see if it works when someone has breathing difficulty, throat swelling or dizziness. Call the ambulance first. Don't give tablets or syrups to anyone who is struggling to swallow or breathe, as they may choke.</p>
</div>

<h2>No auto-injector? What to do in India</h2>

<p>Adrenaline auto-injectors are less commonly prescribed and carried in India than in some other countries, so in many emergencies there won't be one. That makes speed even more important:</p>

<ul>
  <li>Call 112 or an ambulance at once and say "anaphylaxis". The ambulance crew can give adrenaline and oxygen.</li>
  <li>Position the person as described above and keep them still.</li>
  <li>Let them use their asthma inhaler for wheezing, if they have one.</li>
  <li>If a hospital emergency department is very close and the ambulance will take a long time, ask the dispatcher whether to take them directly, keeping them lying or sitting as needed.</li>
  <li>Don't drive from chemist to chemist looking for an injector.</li>
</ul>

