<h2>Anaphylaxis first aid: step by step</h2>

<h3>Step 1: Call an ambulance immediately</h3>

<p>Call 112 or our 24/7 helpline (<a href="<?= BLOG_TEL ?>"><?= BLOG_PHONE ?></a>) as soon as you suspect anaphylaxis. If someone else is with you, one person calls while the other gets the adrenaline. If you are alone and the person has an auto-injector, give it first, then call. Say "anaphylaxis" or "severe allergic reaction" clearly, describe the breathing problems and give the exact address.</p>

<h3>Step 2: Use their adrenaline auto-injector straight away</h3>

<p>Adrenaline (also called epinephrine) is the first-line treatment for anaphylaxis. It reduces swelling, opens the airways and supports blood pressure. If the person has their own prescribed auto-injector, use it at the first signs of anaphylaxis, without waiting for symptoms to get worse. If they can't use it themselves, you can do it for them.</p>

<ol>
  <li>Take the pen out of its case.</li>
  <li>Hold it in your fist, without putting your thumb or fingers over either end.</li>
  <li>Remove the safety cap as shown on the label.</li>
  <li>Press the tip firmly into the <strong>outer thigh</strong>, midway between the hip and the knee. It works through clothing such as trousers or jeans.</li>
  <li>Hold it in place for as long as the device's instructions say, then remove it.</li>
  <li>Note the time, and keep the used pen to hand to the ambulance crew.</li>
</ol>

<p>Devices differ slightly, so follow the instructions printed on the pen. If there is no improvement after <strong>5 minutes</strong> and a second auto-injector is available, give the second dose.</p>

<h3>Step 3: Lie them down with their legs raised</h3>

<p>Lie the person flat on their back and raise their legs on a pillow, bag or chair. This helps blood reach the heart and brain if blood pressure is falling.</p>

<ul>
  <li>If they are <strong>struggling to breathe</strong>, let them sit up instead, with their legs out in front of them.</li>
  <li>If they are <strong>pregnant</strong>, lie them on their left side.</li>
  <li>If they are <strong>unconscious but breathing</strong>, put them in the recovery position.</li>
  <li>Hold a <strong>baby or young child</strong> lying flat in your arms rather than upright.</li>
</ul>

<h3>Step 4: Don't let them stand up or walk</h3>

<p>Even if they start to feel better, don't let them stand, walk to the car or climb stairs. Suddenly standing up during anaphylaxis can make blood pressure crash and the heart stop. Wait for the ambulance crew to move them on a stretcher.</p>

<h3>Step 5: Remove the trigger if you can</h3>

<p>Stop them eating the food, but don't try to make them vomit. If a bee sting is still in the skin, scrape it out sideways with a fingernail or the edge of a card. Don't spend time on this before adrenaline has been given.</p>

<h3>Step 6: Use their asthma inhaler for wheezing</h3>

<p>If they have asthma and are wheezing, they can use their own reliever inhaler as prescribed, after adrenaline has been given. It may ease the wheeze, but it doesn't treat throat swelling or falling blood pressure, so it is never a substitute for adrenaline or the ambulance. Our guide to <a href="<?= post_url('severe-asthma-attack-first-aid') ?>">severe asthma attack first aid</a> shows how to use an inhaler with a spacer.</p>

