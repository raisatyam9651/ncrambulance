<h2>If things get worse: start CPR</h2>

<p>If the person becomes unresponsive and isn't breathing normally, call 112 if you haven't already, put the phone on speaker and start CPR immediately. Push hard and fast in the centre of the chest, and send someone for an AED. If a second adrenaline dose is due and available, another person can give it while you continue CPR. Our <a href="<?= post_url('how-to-do-cpr') ?>">hands-only CPR guide</a> shows the technique.</p>

<p>If they are unresponsive but still breathing normally, put them in the recovery position and keep checking their breathing. Our guide to <a href="<?= post_url('unconscious-person-first-aid') ?>">first aid for an unconscious person</a> shows how.</p>

<h2>Why hospital is needed even after they recover</h2>

<p>Adrenaline can work dramatically, and the person may feel almost normal within minutes. But its effect wears off, and symptoms can come back hours later, even without further contact with the trigger. This is called a biphasic reaction. That's why anyone who has had anaphylaxis, or been given adrenaline, must go to hospital and be observed for several hours, as the doctor decides.</p>

<p>Severe reactions may need intensive care, and some patients are moved to a bigger hospital in an <a href="<?= link_to('icu') ?>">ICU ambulance for critical patients</a>. After recovery, ask about seeing an allergy specialist to confirm the trigger, get a written emergency plan and, if advised, a prescription for adrenaline auto-injectors.</p>

<h2>Living with a severe allergy: simple precautions</h2>

<ul>
  <li>If auto-injectors are prescribed, carry two at all times, and teach family, friends and teachers how to use them.</li>
  <li>Tell the school, the office and anyone cooking for you about the allergy.</li>
  <li>Read food labels, and ask in restaurants: many North Indian gravies and sweets contain cashew paste, almonds or peanuts.</li>
  <li>Wear a medical alert bracelet or keep an allergy card in your wallet.</li>
  <li>Tell every doctor and pharmacist about medicine allergies before any new treatment.</li>
</ul>

