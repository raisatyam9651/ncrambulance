<p>It can begin with something small. A child at a birthday party in Dwarka eats a sweet made with peanuts and starts coughing, or a guest at a wedding has a few prawns and feels their lips tingle. Within minutes the lips swell, the voice turns hoarse and breathing becomes noisy. Someone hands over an antihistamine tablet and everyone waits for it to work. With anaphylaxis, that waiting can be deadly.</p>

<p>Anaphylaxis is a severe, whole-body allergic reaction that can affect breathing and blood pressure within minutes. This guide explains how to recognise it, how to use an adrenaline auto-injector, how to position the person, and what to do when no auto-injector is available, which is common in India. The priority is always the same: call an <a href="<?= link_to('als') ?>">ALS ambulance with oxygen and emergency medicines</a> straight away.</p>

<h2>What is anaphylaxis, and what causes it?</h2>

<p>In anaphylaxis, the immune system overreacts to a trigger and releases chemicals throughout the body. These can make the tongue and throat swell, tighten the airways and make blood pressure fall sharply. Symptoms usually start within minutes of contact with the trigger, though sometimes later. Common triggers include:</p>

<ul>
  <li><strong>Foods:</strong> peanuts, tree nuts such as cashews and almonds, shellfish such as prawns, fish, milk, eggs and sesame</li>
  <li><strong>Insect stings:</strong> bees, wasps and hornets</li>
  <li><strong>Medicines:</strong> some antibiotics, painkillers and other tablets or injections</li>
  <li><strong>Latex</strong>, such as rubber gloves or balloons, in people allergic to it</li>
</ul>

<p>People with a known allergy who also have asthma are at higher risk of a severe reaction. But anaphylaxis can also happen in someone who has never had an allergic reaction before.</p>

<h2>Signs of anaphylaxis</h2>

<p>Think of the airway, breathing and circulation. Anaphylaxis is likely if allergy symptoms come with <strong>any</strong> of these:</p>

<ul>
  <li><strong>Airway:</strong> swelling of the tongue or throat, a hoarse voice, difficulty swallowing or speaking, or a high-pitched noise when breathing in</li>
  <li><strong>Breathing:</strong> wheezing, breathlessness, a persistent cough, or lips turning blue or grey</li>
  <li><strong>Circulation:</strong> dizziness, feeling faint, pale and clammy skin, confusion or collapse. Young children may become pale and floppy.</li>
</ul>

<p>Other signs often come with these: hives (a raised, itchy red rash), flushing, swelling of the lips, face or eyes, vomiting and stomach cramps. Skin signs aren't always present, so a person can have anaphylaxis without any rash.</p>

