<h2>How to do CPR on a child (1 year to puberty): step by step</h2>

<h3>Step 1: Check for a response and call</h3>

<p>Tap the child's shoulders and call their name loudly. If there is no response and they are not breathing normally, shout for help and get the phone on speaker.</p>

<h3>Step 2: Open the airway and give 5 rescue breaths</h3>

<p>Lay the child on their back on the floor. Tilt the head back gently with a hand on the forehead and lift the chin. Pinch the soft part of the nose, seal your mouth over theirs and blow steadily for about one second until the chest rises. Give five breaths.</p>

<h3>Step 3: Give 30 chest compressions</h3>

<p>Place the <strong>heel of one hand</strong> on the lower half of the breastbone, in the centre of the chest. For a bigger child, use two hands, one on top of the other. Keep your arm straight, shoulders over your hand, and push down about <strong>5 cm</strong>, one-third of the chest depth, at 100 to 120 pushes a minute.</p>

<h3>Step 4: Keep going with 30:2</h3>

<p>Continue cycles of 30 compressions and 2 breaths. If a second adult is there, swap every two minutes so the pushes stay deep enough. Some courses teach starting with compressions rather than the first 5 breaths. If that is how you were trained, follow it: both approaches work, and what matters most is starting quickly and including breaths.</p>

<h2>Using an AED on a child or baby</h2>

<p>An AED (automated external defibrillator) can be used on children and babies. If the AED has <strong>child pads</strong> or a child key or switch, use them for children under about eight years old. If only adult pads are available, use them anyway. On a small chest, place one pad in the centre of the front of the chest and the other in the centre of the back, so the pads don't touch each other. Our guide on <a href="<?= post_url('how-to-use-aed-defibrillator') ?>">how to use an AED step by step</a> walks you through the prompts.</p>

<h2>What if the baby or child was choking first?</h2>

<p>If a child was choking and then becomes unresponsive, lay them down and start CPR straight away. Chest compressions can push the object out. Each time you open the mouth to give breaths, look inside: if you can <strong>clearly see</strong> the object and can easily pick it out, remove it. Never sweep a finger blindly in the mouth, because you can push the object deeper.</p>

<p>If the child is still awake and trying to cough, use back blows and thrusts instead of CPR. Our <a href="<?= post_url('choking-first-aid') ?>">choking first aid guide for adults, children and babies</a> shows exactly how.</p>

