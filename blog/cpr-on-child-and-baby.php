<h2>Why rescue breaths matter more for children</h2>

<p>In adults, the heart usually stops suddenly because of an electrical problem, while the blood is still full of oxygen. Children are different. Most children's hearts stop <strong>after a breathing problem</strong>: choking, drowning, a severe asthma attack, pneumonia, smoke or suffocation. By the time the heart stops, the blood has already run low on oxygen.</p>

<p>That is why rescue breaths are a key part of CPR for babies and children. Chest compressions alone move blood around, but if that blood carries little oxygen, it can't protect the brain for long. If you truly cannot give breaths, compressions alone are still far better than nothing.</p>

<h2>First: call for help the right way</h2>

<p>Before anything else, check it is safe for you. If the child is in water, near a live wire or on a road, get them to safety only if you can do it without putting yourself in danger, for example by switching off the mains first. Then:</p>

<ul>
  <li><strong>If you have a mobile phone:</strong> call <strong>112</strong> or an ambulance immediately, put it on speaker and start CPR while you talk. The dispatcher can coach you.</li>
  <li><strong>If someone else is there:</strong> ask them to call while you start, and to fetch an AED if one is nearby.</li>
  <li><strong>If you are alone without a phone:</strong> give about <strong>2 minutes of CPR first</strong>, then go and call. Carry a small baby with you to the phone or a neighbour's door, so you can restart CPR the moment help is on the way.</li>
</ul>

<h2>How to do CPR on a baby (under 1 year): step by step</h2>

<h3>Step 1: Check for a response</h3>

<p>Lay the baby on their back on a firm, flat surface such as a table or the floor. Tap the sole of the foot and call their name. Never shake a baby. If there is no response and the baby is not breathing normally, or is only gasping, start CPR.</p>

<h3>Step 2: Open the airway gently</h3>

<p>A baby's head is large and their airway is soft and narrow. Place one hand on the forehead and keep the head in a <strong>neutral position</strong>, level with the body, as if the baby is looking straight up at the ceiling. Lift the chin with one fingertip. Tilting a baby's head far back can actually block the airway. A folded towel under the shoulders can help keep the head level.</p>

<h3>Step 3: Give 5 rescue breaths</h3>

<p>Take a normal breath, cover the baby's <strong>mouth and nose</strong> with your mouth and blow gently and steadily for about one second, just enough to see the chest rise. Use small puffs from your cheeks, not a full adult breath. Let the chest fall, then repeat to give five breaths. If the chest doesn't rise, adjust the head position and try again, but don't delay compressions.</p>

<h3>Step 4: Give 30 chest compressions</h3>

<p>Find the lower half of the breastbone, just below an imaginary line between the nipples. Use one of these techniques:</p>

<ul>
  <li><strong>Two-thumb technique:</strong> wrap both hands around the baby's chest with your thumbs side by side on the breastbone and your fingers supporting the back. Press down with your thumbs.</li>
  <li><strong>Heel of one hand:</strong> if your hands can't wrap around the chest, or you are alone and switching to breaths each time, use the heel of one hand on the same spot.</li>
</ul>

<p>Press down about <strong>4 cm</strong>, one-third of the depth of the chest, at <strong>100 to 120 pushes a minute</strong>. Let the chest rise fully after each push. Many older guides show two fingertips. Newer American Heart Association guidance has moved away from this method because two fingers often don't push deep enough, but if two fingers is what you were taught, use them and press firmly.</p>

<h3>Step 5: Continue 30 compressions and 2 breaths</h3>

<p>After 30 compressions, give 2 gentle breaths, then 30 more compressions. Keep repeating without long pauses until the ambulance crew takes over, the baby starts breathing normally or moving, or you are too exhausted to continue.</p>

