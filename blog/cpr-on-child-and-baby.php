<p>Every parent's worst nightmare can begin in an ordinary moment. A toddler is found face-down in a bucket of water in the bathroom, a baby goes limp and blue after a feed, or a child chokes on a peanut and then stops responding. In the minutes before the ambulance arrives, the adult in the room is the only one who can keep that child's brain supplied with oxygen.</p>

<p>CPR on a child or a baby is not hard to learn, but it is different from adult CPR in a few important ways. This guide explains those differences step by step: how to open a small airway, how to give rescue breaths, where to push and how deep, and what to do if a baby was choking first. When you call for help, ask for a <a href="<?= link_to('neonatal') ?>">neonatal ambulance with an incubator and infant monitoring</a> if the patient is a newborn or small baby.</p>

<h2>How is CPR on a child or baby different from adult CPR?</h2>

<p>The basic idea is the same: push on the chest to pump blood and give breaths to add oxygen. What changes is the size of the patient and the reason their heart stopped. For first aid, a <strong>baby (infant)</strong> is under one year old, and a <strong>child</strong> is from one year until the signs of puberty. After puberty, use the <a href="<?= post_url('how-to-do-cpr') ?>">step-by-step adult CPR technique</a>.</p>

