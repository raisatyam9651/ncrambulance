<h2>If the child starts breathing again</h2>

<p>If the child starts breathing normally but stays drowsy or unconscious, turn them onto their side in the <strong>recovery position</strong>, so the airway stays open and any vomit can drain. Hold a baby in your arms on their side, with the head slightly lower than the body. Keep watching their breathing until the ambulance arrives. If they stop breathing normally again, start CPR again immediately.</p>

<p>Even if the child seems fully recovered, they must be checked in hospital. A child who has needed rescue breaths, especially after <a href="<?= post_url('drowning-first-aid') ?>">drowning in a bucket, tank or pool</a>, can develop breathing problems hours later.</p>

