<h2>Where drowning happens in Delhi NCR, and how to prevent it</h2>

<p>Drownings in Delhi NCR often happen in places that don't look dangerous:</p>

<ul>
  <li><strong>Homes:</strong> buckets, tubs and drums of stored water, and open underground or terrace tanks. Toddlers are most at risk.</li>
  <li><strong>Swimming pools:</strong> society, hotel, school and farmhouse pools, especially at parties where everyone assumes someone else is watching the children.</li>
  <li><strong>Rivers, canals and ponds:</strong> the Yamuna, canals and village ponds, particularly in summer heat, during festival immersions or ritual bathing, and after drinking alcohol.</li>
  <li><strong>Monsoon hazards:</strong> waterlogged underpasses, flooded basements and rain-filled pits at construction sites.</li>
</ul>

<p>A few habits prevent most of these deaths:</p>

<ul>
  <li>Empty buckets and tubs after use, and keep lids on tanks and drums.</li>
  <li>Never leave a young child alone near water, even for a moment to answer the door.</li>
  <li>At pool parties, choose one adult as the "water watcher" who stays off their phone.</li>
  <li>Swim only where there is a lifeguard, never in rivers or canals, and never after alcohol.</li>
  <li>Teach children to swim, and learn CPR yourself.</li>
</ul>

