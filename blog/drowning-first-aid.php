<p>Drowning is fast and almost silent. A toddler tips into a bucket or an open water tank while the family is busy, a child goes under at the deep end of a society pool in Gurugram while the adults chat nearby, or a group of friends wades into a canal or the Yamuna on a hot afternoon and one of them doesn't come back up. There is rarely shouting or splashing. By the time anyone notices, the person may already have stopped breathing.</p>

<p>This guide explains what an ordinary bystander can do: how to get someone out of the water without becoming a second victim, how CPR for drowning differs from CPR after a heart attack, and how to look after them until an <a href="<?= link_to('als') ?>">ALS ambulance with oxygen and airway equipment</a> arrives. You don't need to be a swimmer or a doctor. You need to stay safe, act quickly and get oxygen back into their body.</p>

<h2>What drowning really looks like</h2>

<p>Films show drowning people waving and screaming. In real life, a person who is drowning usually can't call out, because all their effort goes into keeping their mouth above the water. Watch for:</p>

<ul>
  <li><strong>Head low in the water</strong>, mouth at water level, head tilted back.</li>
  <li><strong>An upright body</strong> with little or no kicking, as if climbing an invisible ladder.</li>
  <li><strong>Glassy or closed eyes</strong>, hair over the face, gasping or bobbing.</li>
  <li><strong>Silence.</strong> A child who was splashing noisily and has suddenly gone quiet needs checking at once.</li>
</ul>

<p>Young children often don't struggle at all. Toddlers are top-heavy, so once they tip into a bucket, a bathtub or a paddling pool they can't lift their head out, and they can drown in a few centimetres of water.</p>

<h2>How to rescue a drowning person safely: reach, throw, don't go</h2>

<p>A panicking person in water grabs whatever is near them, including the rescuer, and can push them under. Too often, a drowning claims the would-be rescuer as well. Lifeguards follow a simple rule, and so should you:</p>

<ul>
  <li><strong>Reach.</strong> Lie flat on the edge or hold on to something fixed, then reach out with a long object: a bamboo pole, a branch, an oar, a belt, a rope, or a dupatta or saree twisted into a rope. Pull them in slowly while staying low so you aren't dragged in.</li>
  <li><strong>Throw.</strong> If they are too far away, throw anything that floats: a life ring, an empty plastic can or water bottle with the cap on, a thermocol sheet, a cooler box or an inflated tyre tube. Throw it close to them and shout to them to hold on and kick.</li>
  <li><strong>Don't go.</strong> Don't jump in unless you are trained in water rescue. Rivers, canals and flooded drains hide currents, deep mud and debris. If you are a strong swimmer and must go in, take something that floats and push it to them rather than letting them grab you.</li>
</ul>

<p>The exception is shallow water where you can stand safely, such as a bucket, a bathtub or the shallow end of a pool: lift the child out immediately. Shout for help while you work, and get someone to call 112 or an ambulance straight away.</p>

<h2>Drowning first aid: step by step after they are out of the water</h2>

<h3>Step 1: Call for an ambulance</h3>

<p>If someone else is with you, one person calls while the other starts first aid. If you are alone, call 112 or our 24/7 helpline (<a href="<?= BLOG_TEL ?>"><?= BLOG_PHONE ?></a>), put the phone on speaker and start first aid while you talk. If you have no phone, give about one minute of CPR before you leave to get help. Tell the dispatcher: "Drowning, pulled from water, not breathing" (or "breathing but drowsy"), then the exact location with a landmark or gate number.</p>

<h3>Step 2: Check whether they are breathing</h3>

<p>Lay them on their back on a firm, flat surface, away from the water's edge. Tap their shoulders and shout their name. If they don't respond, gently tilt the head back and lift the chin to open the airway, then look, listen and feel for normal breathing for no more than 10 seconds. Occasional gasps are <strong>not</strong> normal breathing.</p>

<p>If they dived into shallow water or were hit by something, they may have a neck injury. Move the head as little as possible, but don't let that stop you opening the airway: breathing comes first. Our guide to <a href="<?= post_url('spinal-injury-first-aid') ?>">neck and spine injury first aid</a> explains how to protect the neck.</p>

<h3>Step 3: Not breathing? Rescue breaths first, then CPR</h3>

<p>When the heart stops in drowning, it is usually because the body has run out of oxygen, not because of a sudden heart rhythm problem. That's why CPR for drowning starts with breaths.</p>

<ul>
  <li><strong>If you are trained:</strong> give <strong>5 rescue breaths</strong>. Pinch the nose, seal your mouth over theirs and blow steadily for about one second, watching the chest rise. Then start chest compressions and continue with <strong>30 compressions to 2 breaths</strong>.</li>
  <li><strong>If you are not trained, or can't give breaths:</strong> start <strong>chest compressions immediately</strong>. Push hard and fast in the centre of the chest, 100 to 120 times a minute. Compressions alone are far better than doing nothing.</li>
</ul>

<p>Keep going until the ambulance crew takes over, the person starts breathing normally, or you physically can't continue. Our <a href="<?= post_url('how-to-do-cpr') ?>">step-by-step CPR guide for adults</a> shows hand position and depth. For children and babies, breaths matter even more and the technique is gentler: see <a href="<?= post_url('cpr-on-child-and-baby') ?>">how to give CPR to a child or baby</a>. If there is an AED at the pool or clubhouse, send someone for it, move the person away from standing water, wipe the chest dry and follow the voice prompts.</p>

<h3>Step 4: Don't try to get the water out</h3>

<div class="callout callout-danger">
  <strong>Never press the stomach or hang them upside down</strong>
  <p>Pressing on the belly, rolling the person over a drum or holding a child upside down to "drain the water" is one of the most common <a href="<?= post_url('first-aid-myths-india') ?>">first-aid myths in India</a>. The amount of water in the lungs is usually small, and the body absorbs it. These manoeuvres waste the minutes the brain needs oxygen, and they push water and food up from the stomach, which can then be breathed into the lungs. Give breaths and compressions instead.</p>
</div>

<h3>Step 5: If they vomit, turn them on their side</h3>

<p>Vomiting is very common during CPR after drowning. If it happens, roll them onto their side quickly, keeping the head, neck and body in line, let the vomit drain out and wipe the mouth clean with a cloth. Then roll them onto their back and carry on with CPR.</p>

<h3>Step 6: Keep them warm and watch them closely</h3>

<p>If they are breathing, or start breathing again, put them in the recovery position so the airway stays clear. Our guide to <a href="<?= post_url('unconscious-person-first-aid') ?>">first aid for an unconscious person</a> shows how. Remove wet clothes if you can do it without moving them too much, and cover them with dry towels, blankets or a jacket. Even in a Delhi summer, someone who has been in water loses body heat, and cold water in winter is a danger in itself.</p>

<p>Stay with them and keep checking their breathing. Don't give food or drink, and don't let them walk around "to recover". Even if they seem fine, they need a hospital check.</p>

