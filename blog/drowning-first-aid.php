<h2>If things get worse: when to restart CPR</h2>

<p>Keep watching their breathing until the crew arrives, because a rescued person can get worse after seeming to recover.</p>

<ul>
  <li>If they <strong>stop breathing normally</strong>, roll them onto their back and start CPR again, beginning with rescue breaths if you are trained.</li>
  <li>If they become <strong>drowsy, confused or hard to wake</strong>, keep them in the recovery position and tell the dispatcher.</li>
  <li>If their <strong>breathing becomes fast, noisy or laboured</strong>, or their lips turn blue or grey, update the dispatcher, who may send a <a href="<?= link_to('ventilator') ?>">ventilator ambulance for breathing support</a>.</li>
</ul>

<p>Don't stop CPR because you think they were underwater for too long. You can't judge that at the scene. Keep going and let the ambulance crew and doctors decide.</p>

<h2>Why everyone rescued from water needs a hospital check</h2>

<p>Water that enters the lungs, even a small amount, can irritate them and make it harder for oxygen to pass into the blood. A person may cough, seem to recover, and then develop breathing problems over the next few hours. That's why anyone who needed rescuing, lost consciousness, needed breaths or CPR, or kept coughing afterwards should be checked in a hospital emergency department, even if they look well.</p>

