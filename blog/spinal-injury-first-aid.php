<h2>When must you move them anyway?</h2>

<p>Move a person with a suspected spinal injury <strong>only</strong> if:</p>

<ul>
  <li>there is <strong>immediate danger</strong> to life, such as fire, smoke, traffic you can't stop, a collapsing structure or rising water, or</li>
  <li>they are <strong>not breathing normally</strong> and you need to get them onto their back to start CPR, or</li>
  <li>they are <strong>vomiting</strong> or bleeding into the mouth and you need to keep the airway clear.</li>
</ul>

<p>If you must move them out of danger, drag them in a straight line along the length of the body, by the clothing at the shoulders or on a blanket pulled from the head end. Never drag them sideways, fold them in half or lift them by the arms and legs. Don't pull someone out of a car unless there is danger: support their head from behind the seat and wait. If someone has dived into shallow water, our <a href="<?= post_url('drowning-first-aid') ?>">drowning first aid guide</a> explains how to get them out safely.</p>

<h2>If they vomit or stop breathing</h2>

<p>Breathing always comes first. If the person vomits, or their breathing becomes gurgling, roll them onto their side using the <strong>log roll</strong>, with two or three helpers if possible:</p>

<ol>
  <li>The person at the head keeps holding it and gives the commands.</li>
  <li>Helpers kneel on one side and place their hands on the far shoulder, hip and legs.</li>
  <li>On the count of three, everyone rolls the person towards them together, keeping the head, neck and body in one straight line, like rolling a log.</li>
  <li>Keep them supported on their side so they can't roll back, and let the vomit drain out of the mouth.</li>
</ol>

<p>If they are unresponsive and <strong>not breathing normally</strong>, log-roll them onto their back and start CPR immediately, even with a suspected neck injury. A spinal injury is serious, but nobody survives without breathing. Our <a href="<?= post_url('how-to-do-cpr') ?>">hands-only CPR guide</a> shows exactly what to do.</p>

