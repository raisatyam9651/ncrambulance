<p>Your father falls off a ladder while cleaning the fans before Diwali, a worker slips from scaffolding, or a teenager dives into a shallow pool and doesn't come up. In each case, the people around want to help them up, sit them on a chair or carry them to the nearest car. If the neck or back is broken, that kind instinct can damage the spinal cord and leave the person paralysed for life.</p>

<p>This guide explains who might have a spinal injury, why you shouldn't move them, how to keep the head and neck still with your hands, and the few situations when you must move them anyway. The goal is simple: keep the spine still until a <a href="<?= link_to('bls') ?>">BLS ambulance with a stretcher and a trained attendant</a> can lift the patient safely.</p>

<h2>Who might have a spinal injury?</h2>

<p>Suspect a neck or back injury after any of these:</p>

<ul>
  <li><strong>Falls from height</strong>: a ladder, roof, balcony, staircase, tree or scaffolding</li>
  <li><strong>Road accidents</strong>, especially bike riders, people thrown from a vehicle, pedestrians who were hit and vehicles that rolled over</li>
  <li><strong>Diving</strong> into shallow water in a pool, pond, canal or river</li>
  <li><strong>A heavy blow</strong> to the head, neck or back, from a falling object, a fight or sport</li>
  <li><strong>Falls in older people</strong>: weaker bones mean even a slip in the bathroom or a fall out of bed can break the neck or back</li>
  <li><strong>Any serious head injury</strong>, or unconsciousness after an injury, because you can't ask the person what hurts</li>
</ul>

<h2>Signs of a spinal injury</h2>

<ul>
  <li>Pain in the neck or back, or tenderness when the area is touched</li>
  <li>Numbness, tingling or "pins and needles" in the arms, hands, legs or feet</li>
  <li>Weakness, or being unable to move the arms or legs</li>
  <li>Loss of bladder or bowel control</li>
  <li>The head or neck held at an odd angle</li>
  <li>Difficulty breathing, which can happen with high neck injuries</li>
</ul>

<p>No pain doesn't mean no injury. Shock, alcohol or another painful injury, such as a broken leg, can mask neck pain. If the way they were hurt makes a spinal injury possible, treat it as one.</p>

<h2>Why shouldn't you move them?</h2>

<p>The spinal cord is a bundle of nerves that carries messages between the brain and the body, and it runs through a tunnel in the bones of the spine. When those bones are broken or out of place, bending, twisting or lifting the person can press bone fragments into the cord. Damage to the cord is often permanent. It can cause paralysis below the injury or stop the breathing muscles working.</p>

<p>Some people with an unstable spine can still walk and talk at first, so looking fine is not proof that the spine is fine. Keeping them still buys time for the ambulance crew to immobilise the spine and move them properly.</p>

<div class="callout callout-danger">
  <strong>Don't let a crowd lift them into an auto or car</strong>
  <p>In India it is common for bystanders to grab an injured person by the arms and legs and bundle them into the nearest auto, taxi or car. This folds and twists the spine at exactly the point it may be broken. Unless there is immediate danger, keep the crowd back, hold the head still and wait for an ambulance with a stretcher.</p>
</div>

<h2>Spinal injury first aid: step by step</h2>

<h3>Step 1: Call 112 or an ambulance</h3>

<p>Call <strong>112</strong> or our helpline (<a href="<?= BLOG_TEL ?>"><?= BLOG_PHONE ?></a>), or ask someone else to call so you can stay with the patient. Say that you suspect a <strong>neck or spine injury</strong>, explain how it happened, and say whether the person is awake, breathing and able to move their arms and legs. Tell the dispatcher which floor you are on and whether the lift can take a stretcher, so the crew comes prepared.</p>

<h3>Step 2: Tell them to keep still and keep talking</h3>

<p>Kneel where they can see you without turning their head. Explain that they may have hurt their neck and must not move, even to look around or sit up. Keep your voice calm. A frightened person tends to move, and talking to them helps keep them still and lets you notice early if they become drowsy.</p>

<h3>Step 3: Hold the head still with your hands</h3>

<p>This is called <strong>manual in-line stabilisation</strong>, and anyone can do it:</p>

<ol>
  <li>Kneel or lie on the ground behind the person's head.</li>
  <li>Place one hand on each side of the head, over the ears, with your fingers spread along the jaw and the back of the head.</li>
  <li>Keep the head in line with the body without pulling, pushing or turning it. If the head is at an odd angle, don't force it straight: support it in the position you found it.</li>
  <li>Rest your elbows on the ground or on your knees so you can hold the position for a long time.</li>
</ol>

<p>If you need your hands free, place rolled-up towels, blankets or clothes firmly on either side of the head to stop it rolling. Otherwise, keep holding until the ambulance crew takes over.</p>

<h3>Step 4: Watch their breathing and keep them warm</h3>

<p>Keep checking that their chest is rising and falling and that they still respond to you. Cover them with a blanket or shawl without moving them, because people with spinal injuries can lose body heat quickly, especially on a cold floor in a Delhi winter. Give them nothing to eat or drink.</p>

<h3>Step 5: Keep the crowd back and prepare for the ambulance</h3>

<p>Ask one person to keep onlookers away and another to meet the ambulance: unlock the society gate, tell the guard and hold the lift on the ground floor. Clear furniture from the path so the crew can bring a stretcher right to the patient. If the person is struggling to breathe or has other serious injuries, an <a href="<?= link_to('icu') ?>">ICU ambulance with a critical care team</a> may be needed, and the dispatcher can advise.</p>

