<p>Heat exhaustion can turn into heat stroke if the person stays in the heat. If they don't improve within 30 minutes of resting and cooling, or they become confused at any point, treat it as heat stroke and call for help.</p>

<h2>What to do for heat stroke: step by step</h2>

<h3>Step 1: Call 112 or an ambulance</h3>

<p>Call straight away, or ask someone else to call while you start cooling. Put the phone on speaker. Say: "Suspected heat stroke, very hot and confused (or unconscious)," and give the exact location with a landmark. If the person is unstable, an <a href="<?= link_to('icu') ?>">ICU ambulance for critical patients</a> may be needed to take them to a hospital with intensive care.</p>

<h3>Step 2: Move them somewhere cool</h3>

<p>Get the person out of the sun immediately: into shade, an air-conditioned room, a shop or office lobby, or a car with the AC running. Lay them down. Remove helmets, jackets, uniforms, shoes, socks and any extra layers.</p>

<h3>Step 3: Cool them as fast as you can</h3>

<p>This is the step that saves lives. Don't wait for the ambulance to start it. Use the most effective method you have:</p>

<ul>
  <li><strong>Cold-water immersion (most effective)</strong>: if a bathtub, a large tub or a water drum is available, put the body in cold water up to the neck, keeping the head out and supported. Someone must hold the person the whole time.</li>
  <li><strong>Soak and fan</strong>: if immersion isn't possible, keep pouring cool or cold water over the whole body with buckets, mugs or a hose, and fan hard with a ceiling fan, table fan, hand fan or newspaper. The evaporating water carries heat away. Wet sheets or towels also work if you keep re-wetting them and keep fanning.</li>
  <li><strong>Ice packs</strong>: place ice packs, ice wrapped in cloth, frozen vegetable packets or cold wet cloths on the <strong>neck, armpits and groin</strong>, where large blood vessels run close to the skin.</li>
</ul>

<p>Keep cooling until the ambulance crew takes over, or until the person is fully alert again and starts to shiver. Then stop the ice but keep them in a cool place, because their temperature can rise again.</p>

<h3>Step 4: Give fluids only if they are fully alert</h3>

<p>If the person is awake, thinking clearly and able to swallow, give small sips of cool water or ORS. If they are confused, drowsy, vomiting or unconscious, give <strong>nothing by mouth</strong>, because they may choke or breathe the fluid into their lungs. Sips are enough while you concentrate on cooling.</p>

<h3>Step 5: Watch them closely</h3>

<p>Stay with them and keep checking whether they respond to you and are breathing normally. Note the time they collapsed and what they were doing beforehand, and tell the crew. Don't let them get up and walk, even if they start to feel better.</p>

