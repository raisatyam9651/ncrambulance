<p>It's a May afternoon in Gurgaon and the temperature has crossed 45°C. A delivery rider who has been on the road since morning stumbles off his bike outside an office tower and sits on the pavement, mumbling. The guard sprinkles water on his face and offers him a cold drink, thinking he is just tired. But his skin is burning hot, he can't say where he is, and his body's cooling system has failed.</p>

<p>Heat stroke is a medical emergency that can damage the brain, kidneys and heart within a short time. The most useful thing a bystander can do is <strong>cool the person fast</strong> while help is on the way. This guide explains how to recognise heat stroke, how it differs from heat exhaustion, the quickest ways to cool someone and what to do until the <a href="<?= link_to('emergency') ?>">emergency ambulance</a> arrives.</p>

<h2>What is heat stroke?</h2>

<p>Normally the body keeps its core temperature around 37°C by sweating and sending warm blood to the skin. In extreme heat, especially with humidity, hard physical work or dehydration, this system can be overwhelmed. In heat stroke the core temperature rises <strong>above 40°C</strong> and the brain starts to malfunction. The higher it climbs and the longer it stays there, the more damage it does to the brain, kidneys, liver and muscles.</p>

<p>There are two common patterns. <strong>Classic heat stroke</strong> builds up over a day or more during a heatwave, usually in elderly or ill people, often indoors in a hot room. <strong>Exertional heat stroke</strong> strikes fit, often young people doing hard work or exercise in the heat, such as labourers, riders and athletes, and can develop within hours.</p>

<h2>Signs of heat stroke</h2>

<ul>
  <li><strong>Confusion or strange behaviour</strong>: agitation, irritability, not making sense, not knowing where they are. This is the key sign.</li>
  <li><strong>Slurred speech</strong> or staggering, as if drunk.</li>
  <li><strong>Very hot skin</strong>. It may be dry, but in exertional heat stroke the person is often still sweating, so sweat does not rule it out.</li>
  <li><strong>A fast heartbeat and fast breathing</strong>.</li>
  <li><strong>Headache, nausea or vomiting</strong>.</li>
  <li><strong>Seizures</strong> (fits), collapse or unconsciousness.</li>
</ul>

<p>A home thermometer under the arm or in the mouth often reads lower than the true core temperature, so don't rely on the number. <strong>A very hot person who is confused, slurring or collapsing has heat stroke until proven otherwise.</strong></p>

<h2>Heat stroke vs heat exhaustion: how to tell the difference</h2>

<p>Heat exhaustion usually comes first and is a warning. Heat stroke is the emergency. The main difference is in the brain: in heat exhaustion the person is still thinking clearly.</p>

