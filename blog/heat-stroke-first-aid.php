<h2>Who is most at risk in Delhi NCR summers?</h2>

<p>Delhi NCR's heatwaves usually peak in May and June. They are especially dangerous because the heat often doesn't let up at night, and in the humid weeks around the monsoon, sweat evaporates poorly and cools the body less. The people most at risk are:</p>

<ul>
  <li><strong>Elderly people</strong>, especially those living alone, in top-floor flats or in homes without cooling during power cuts. Older bodies sense heat and thirst less well.</li>
  <li><strong>Babies and young children</strong>. Never leave a child in a parked car, even for a few minutes, because the inside heats up very quickly.</li>
  <li><strong>Outdoor workers</strong>: delivery riders, construction workers, traffic police, security guards, street vendors, rickshaw drivers and farm labourers.</li>
  <li><strong>People exercising outdoors</strong>, such as runners and cricketers, and anyone wearing heavy protective clothing.</li>
  <li><strong>People with long-term illnesses</strong> such as heart disease, diabetes, kidney disease or obesity, and those on certain medicines, including water tablets (diuretics), some blood pressure medicines and some psychiatric medicines.</li>
  <li><strong>Anyone who has been drinking alcohol</strong>, which dehydrates the body.</li>
</ul>

<h2>How to prevent heat stroke</h2>

<p>The National Disaster Management Authority (NDMA) issues heatwave advice every summer. The key points are:</p>

<ul>
  <li>Drink water often, even if you are not thirsty. ORS, lassi, nimbu pani and chhaas (buttermilk) also help.</li>
  <li>Avoid going out in the sun, especially between noon and 3 pm, and do heavy work in the cooler morning or evening hours.</li>
  <li>Wear light-coloured, loose cotton clothes, and cover your head with a cap, gamchha or umbrella.</li>
  <li>Avoid alcohol, and cut down on tea, coffee and fizzy drinks, which can dehydrate the body.</li>
  <li>Keep your home cool with curtains or shades on the sunny side, and open the windows at night.</li>
  <li>Check on elderly neighbours and relatives at least twice a day during a heatwave.</li>
</ul>

<p>Employers can help too, by giving outdoor staff shade, drinking water and regular rest breaks, and by moving the heaviest work away from the afternoon.</p>

