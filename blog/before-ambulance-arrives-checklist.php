<p>The call is done and the ambulance is on its way. Now comes the hardest part: waiting. In a high-rise society, those minutes can slip away in small delays. The guard stops the ambulance at the gate to ask which tower, the lift is stuck on the 20th floor, a parked car blocks the entrance, and nobody can find Papa's medical file.</p>

<p>This checklist shows families how to use the waiting time well, from opening the route and gathering documents to choosing who rides along and briefing the crew. It works whether you have called 112, a state ambulance or our <a href="<?= link_to('emergency') ?>">emergency ambulance service</a>. If you haven't made the call yet, do that first; our guide on <a href="<?= post_url('how-to-call-ambulance-delhi-ncr') ?>">how to call an ambulance and what to say</a> has a ready script.</p>

<h2>First, split the jobs</h2>

<p>If there are two or more adults at home, divide the work straight away so nobody runs around doing the same thing twice.</p>

<ul>
  <li><strong>Person 1 stays with the patient</strong> the whole time. They keep the phone on speaker, follow the dispatcher's instructions, watch the patient's breathing and keep them calm. They don't leave, even to pack a bag.</li>
  <li><strong>Person 2 handles logistics</strong>: the route, the guard, the lift, the documents and the bag.</li>
  <li><strong>A third person, if available,</strong> waits at the society gate or the main road to guide the ambulance in.</li>
</ul>

<p>If you are alone with the patient, the patient comes first. Unlock your front door so the crew can get in, and ask a neighbour or the guard to handle the gate and lift for you.</p>

<h2>Getting your home ready for the crew: step by step</h2>

<h3>Step 1: Unlock the gates and doors</h3>

<p>Open the main gate, the building door, your flat door and any security grille. If you live in a gated society, call the guard room and tell them an ambulance is coming for which tower and flat, so it is waved straight through. Ask them to keep the barrier open and to point the crew to the right tower.</p>

<h3>Step 2: Call the lift and hold it</h3>

<p>Bring the lift to the ground floor shortly before the ambulance is due and have someone hold it there. If your building has a service or stretcher lift, ask the guard to have it ready, because ordinary lifts are often too small for a stretcher. If there is no lift, or it isn't working, tell the dispatcher so the crew can plan how to bring the patient down.</p>

<h3>Step 3: Clear the path for a stretcher</h3>

<ul>
  <li>Move shoes, shoe racks, cycles, plants and boxes out of the corridor and off the landing.</li>
  <li>Clear the staircase in case the crew needs to use it.</li>
  <li>Check that a stretcher can turn from the patient's room into the hallway, and push a sofa or table aside if needed.</li>
  <li>Ask neighbours to move cars blocking the building entrance, and keep a space where the ambulance can stop close to the door.</li>
</ul>

<h3>Step 4: Make your home easy to find</h3>

<p>At night, switch on the porch, gate and staircase lights. Shut pets in a separate room: even a friendly dog can get underfoot when the crew is carrying equipment. Ask someone to stand at the gate or on the main road and wave when they see the ambulance. If the crew calls for directions, answer quickly and give them a landmark.</p>

<h3>Step 5: Gather documents and medicines</h3>

<p>Person 2 should put the patient's ID, health insurance card, medical file and a list of their current medicines into one bag or folder. The full list is in the next section. Two minutes is enough; don't let this delay leaving.</p>

<h3>Step 6: Note what happened</h3>

<p>Write down on your phone what happened, when it started and any medicine you gave, with the time. The crew will ask, and memory fails under stress. For a possible stroke, the time the person was last seen well matters a great deal, as our <a href="<?= post_url('stroke-first-aid-be-fast') ?>">BE FAST guide to stroke first aid</a> explains.</p>

