<h2>Make a plan before you need it</h2>

<p>The calmest families in an emergency are the ones who prepared on an ordinary day. Keep a "hospital folder" with photocopies of ID, insurance details, recent reports and a medicine list for each elderly or ill family member. Save the guard room's number in everyone's phone. If you live in a high-rise, find out today whether your tower has a stretcher lift. Residents can also save the number for our <a href="<?= link_to('noida') ?>">ambulance service in Noida</a> or their own city.</p>

