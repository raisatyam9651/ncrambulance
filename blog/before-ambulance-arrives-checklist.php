<h2>What else to pack in a small bag</h2>

<ul>
  <li>Your phone and charger, plus a power bank if you have one</li>
  <li>Some cash, as well as a card or UPI on your phone</li>
  <li>The patient's spectacles, hearing aid and dentures</li>
  <li>A change of clothes, and a shawl or blanket in winter</li>
  <li>Water and a snack for the family member going along, not for the patient</li>
</ul>

<h2>Who should go with the patient?</h2>

<p>Send one adult who knows the patient's medical history and can make decisions: which medicines they take, past surgeries, allergies and the name of their doctor. That person may need to sign consent forms at the hospital. Space inside an ambulance is limited, so usually only one family member rides along, and others can follow by car or cab.</p>

<p>If you follow in a car, drive normally. Don't try to stay right behind the ambulance or jump red lights; you will help nobody if you crash. If the patient is a child, a parent should travel with them. For an elderly patient who gets confused or frightened, send the family member they trust most.</p>

<h2>What to tell the crew when they arrive</h2>

<p>The crew will take over quickly, and the first minute of the handover matters. Keep it short and factual. Tell them:</p>

<ul>
  <li><strong>What happened</strong> and what you saw</li>
  <li><strong>When it started</strong>, or when the person was last seen well</li>
  <li><strong>What you gave and when</strong>: aspirin, an inhaler, sugar or glucose, or their own tablets</li>
  <li><strong>Any change since the call</strong>: fainting, vomiting, a fit or worse breathing</li>
  <li><strong>Their usual conditions</strong>, medicines and allergies</li>
</ul>

<div class="callout callout-tip">
  <strong>A 30-second handover</strong>
  <p>"This is my mother, she's 72. About 20 minutes ago she said her chest felt heavy and she started sweating. She has diabetes and high BP and takes these medicines. She's allergic to penicillin. We gave her one aspirin to chew at 10:15. She has been awake the whole time."</p>
</div>

<p>Then let the crew decide how to move the patient. They may use a stretcher, a chair or other equipment, and they will tell you when to bring the bag and lock up.</p>

<h2>If the patient gets worse while you wait</h2>

<p>Keep the phone on speaker and tell the dispatcher about any change. If the patient stops responding and isn't breathing normally, or is only gasping, start CPR straight away: push hard and fast in the centre of the chest, 100 to 120 times a minute, and don't stop until the crew takes over. Our guide to <a href="<?= post_url('how-to-do-cpr') ?>">doing hands-only CPR</a> shows how.</p>

<p>If they become unconscious but are still breathing normally, roll them onto their side in the recovery position to keep the airway clear, and keep watching their breathing. If the emergency began with chest pain, keep them sitting still and follow our steps for <a href="<?= post_url('heart-attack-first-aid') ?>">heart attack first aid before the ambulance arrives</a>.</p>

