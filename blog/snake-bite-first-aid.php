<h2>First-aid myths that kill</h2>

<p>Every one of these is still common in India. None of them removes venom, and each one wastes time or causes new injuries:</p>

<ul>
  <li><strong>A tight tourniquet:</strong> a rope, string or cloth tied tightly above the bite cuts off the blood supply. It can cause gangrene and loss of the limb, and it doesn't reliably stop venom. If one has already been tied, don't rip it off; leave it for the hospital, where doctors can release it with treatment ready.</li>
  <li><strong>Cutting or burning the bite:</strong> causes bleeding, infection and damage to nerves and tendons. It is especially dangerous because some venoms stop the blood from clotting.</li>
  <li><strong>Sucking out the venom</strong>, by mouth or with a device: it doesn't work and puts the helper at risk.</li>
  <li><strong>Ice, electric shocks, chemicals and herbal pastes:</strong> no benefit, and they damage the skin and tissue.</li>
  <li><strong>"Snake stones", mantras, jhaad-phoonk, or a visit to an ojha, tantrik or temple:</strong> people who survive after these usually had a dry bite or a bite from a harmless snake. For someone with a real venomous bite, the delay can be fatal.</li>
</ul>

