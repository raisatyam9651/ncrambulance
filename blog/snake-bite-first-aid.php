<p>You can't reliably tell a venomous snake from a harmless one by looking at it, and you don't need to. Treat every snake bite as dangerous until a doctor says otherwise.</p>

<h2>Signs of a venomous snake bite</h2>

<p>Symptoms can start within minutes or be delayed for several hours, so a person who "seems fine" after a bite still needs a hospital. Watch for:</p>

<ul>
  <li>one or two puncture marks, though there may be none at all</li>
  <li>pain, swelling or bruising that spreads up the limb</li>
  <li>bleeding from the bite, gums or nose, or red or dark urine</li>
  <li>vomiting, stomach pain, sweating or feeling faint</li>
  <li>drooping eyelids, blurred or double vision, difficulty swallowing, slurred speech</li>
  <li>weakness, difficulty holding the head up, or difficulty breathing</li>
</ul>

