<h2>Do you need to catch or identify the snake?</h2>

<p>No. Trying to catch or kill the snake leads to more bites and wastes time. Doctors in India decide treatment from the patient's symptoms and simple bedside tests, such as checking whether the blood clots normally, and the anti-snake venom used in India is made to work against all of the Big Four. If someone can take a photo from a safe distance without delay, it may help, but it isn't essential. Never pick up a snake that looks dead: it can still bite by reflex.</p>

<h2>Why the hospital must have anti-snake venom</h2>

<p>ASV is the only treatment that neutralises snake venom. It is given in hospital under close observation, because some people react to it and the number of doses depends on how the patient responds. The hospital also needs to be ready for complications. Bites that affect the nerves can paralyse the breathing muscles, so the patient may need a ventilator for a time. Viper bites can cause severe bleeding and kidney damage that may need blood products or dialysis.</p>

<p>This is why the first hours matter so much, the same idea behind the <a href="<?= post_url('golden-hour-emergency') ?>">golden hour in emergency care</a>. If the patient has any breathing difficulty, tell the dispatcher so they can send a <a href="<?= link_to('ventilator') ?>">ventilator ambulance for breathing support</a> if one is needed.</p>

<h2>If things get worse: breathing problems and CPR</h2>

<p>Cobra and krait bites can weaken the muscles used for breathing. Watch for breathing that becomes shallow, noisy or difficult, a weak voice, or trouble swallowing saliva. Turn the person onto their side so saliva and vomit can drain, and update the dispatcher at once.</p>

<p>If they stop responding and aren't breathing normally, start CPR immediately. Because the problem is often paralysis of the breathing muscles, rescue breaths are especially valuable if you are trained to give them. Our <a href="<?= post_url('how-to-do-cpr') ?>">step-by-step CPR guide</a> explains how. Keep talking to the patient too: someone paralysed by venom may not be able to move or open their eyes but can sometimes still hear you.</p>

<h2>How to prevent snake bites in Delhi NCR</h2>

<ul>
  <li>Wear closed shoes and long trousers in fields, gardens, parks and construction sites, especially after rain.</li>
  <li>Carry a torch when walking outside at night.</li>
  <li>Sleep on a cot or bed rather than the floor, with a mosquito net tucked in under the mattress.</li>
  <li>Keep grass short, and keep rubble, firewood and stacked bricks away from the house.</li>
  <li>Don't put your hands into holes, under stones or into piles of hay or wood.</li>
  <li>If you see a snake, back away slowly and call a trained snake rescuer or the forest department rather than trying to kill it.</li>
</ul>

<p>If you live or work near fields, farmhouses or construction sites on the edges of the city, save the number for an <a href="<?= link_to('greater-noida') ?>">emergency ambulance in Greater Noida</a> and find out which nearby hospital stocks anti-snake venom before the monsoon begins.</p>

