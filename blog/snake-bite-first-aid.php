<h2>Snake bite first aid: Do it R.I.G.H.T., step by step</h2>

<p>The R.I.G.H.T. approach is easy to remember in a panic: <strong>R</strong>eassure, <strong>I</strong>mmobilise, <strong>G</strong>et to <strong>H</strong>ospital, <strong>T</strong>ell the doctor.</p>

<h3>Step 1: Move away from the snake and call for help</h3>

<p>Get the person, and everyone else, a safe distance away from the snake to avoid a second bite. Call 112 or our 24/7 helpline (<a href="<?= BLOG_TEL ?>"><?= BLOG_PHONE ?></a>) straight away. Tell the dispatcher it is a snake bite and ask to be taken to a hospital that has anti-snake venom and can manage snake bites. In rural areas, call the hospital ahead if you can.</p>

<h3>Step 2: Reassure (R)</h3>

<p>Fear makes the heart race and makes people move about, and movement helps venom spread. Speak calmly. Tell them that many bites are dry or from harmless snakes, and that effective treatment is waiting at the hospital. Keep the crowd back and stay with them.</p>

<h3>Step 3: Remove anything tight</h3>

<p>Gently remove rings, bangles, anklets, toe rings, watches, shoes and tight clothing near the bite. The limb may swell quickly, and anything tight can then cut off the blood supply like a tourniquet. If a bangle won't come off easily, don't force it, but tell the doctor.</p>

<h3>Step 4: Immobilise the limb like a fracture (I)</h3>

<p>Moving the bitten limb helps venom travel through the body. Keep it as still as possible:</p>

<ul>
  <li>Splint the limb with a stick, a piece of cardboard, a rolled newspaper or a folded magazine, tied loosely with strips of cloth. You should be able to slide a finger under every tie. Our guide on <a href="<?= post_url('fracture-first-aid') ?>">how to make a splint at home</a> shows the method.</li>
  <li>Keep the bitten limb at about the level of the heart, not raised high or hanging down.</li>
  <li>Keep the person lying down and still. If they vomit or become drowsy, turn them onto their side.</li>
  <li><strong>Don't let them walk</strong>, even to the car or the main road. Carry them on a stretcher, a charpai, a door or a chair.</li>
</ul>

<h3>Step 5: Get to Hospital immediately (G, H)</h3>

<p>Only anti-snake venom can neutralise the venom, and it works best when given early. Go to a hospital that stocks ASV and can watch the patient closely, usually a district hospital, a medical college or a large hospital, rather than a small clinic. Don't stop at a chemist, a local healer or a temple on the way. If an ambulance will take a long time to reach a remote area, follow the dispatcher's advice on the quickest safe way to travel, with the patient lying down and the limb kept still.</p>

<p>Don't give aspirin or painkillers such as ibuprofen, because some venoms cause bleeding and these medicines can make it worse. Paracetamol is the safer choice if pain relief is needed. Don't give alcohol.</p>

<h3>Step 6: Tell the doctor everything (T)</h3>

<p>When you arrive, tell the doctor:</p>

<ul>
  <li>the time of the bite and what the person was doing</li>
  <li>what the snake looked like, if anyone saw it clearly, or show a photo taken safely</li>
  <li>every symptom and when it started, such as vomiting, drooping eyelids or bleeding</li>
  <li>any first aid or traditional treatment already given, including a tourniquet or cuts</li>
</ul>

