<p>Snake bites around Delhi NCR rise sharply in the monsoon, when rain floods snakes out of their burrows. A farm worker walking through wet grass in a village on the edge of Greater Noida, a child playing on a farmhouse lawn, a labourer clearing rubble at a construction site, or a family sleeping on the floor on a hot night: any of them can be bitten. Too often, the family's first response is to tie a rope tightly above the bite and take the person to a local ojha or temple. By the time they reach a hospital, hours have been lost.</p>

<p>Snake bites are treatable. Anti-snake venom (ASV), given in hospital, neutralises the venom, and people who get it in time usually recover. This guide covers what to do from the moment of the bite until an <a href="<?= link_to('als') ?>">ALS ambulance with oxygen and life-support equipment</a> takes over, following the "Do it R.I.G.H.T." approach used in India's snakebite treatment guidelines, along with the myths that waste precious time.</p>

<h2>Which snakes are dangerous in India?</h2>

<p>Most snakes in India are not venomous, and even venomous snakes sometimes bite without injecting venom, which is called a "dry bite". But most serious bites and deaths are caused by four species, known as the Big Four:</p>

