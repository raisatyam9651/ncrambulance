<h2>If things get worse: when to start CPR</h2>

<p>Chest pain from a heart attack can suddenly turn into a cardiac arrest. If the person collapses, doesn't respond when you tap their shoulders and shout, and is <strong>not breathing normally</strong> (no breathing, or only gasping), tell the dispatcher and <strong>start CPR immediately</strong>. Push hard and fast in the centre of the chest, 5 to 6 cm deep and 100 to 120 times a minute, and send someone for an AED. Our <a href="<?= post_url('how-to-do-cpr') ?>">step-by-step guide to adult CPR</a> shows exactly how.</p>

<h2>What if it turns out to be gas?</h2>

<p>Then everyone can go home relieved, and you did exactly the right thing. Chest pain that keeps coming back, especially with effort, should still be checked by a doctor, who may suggest an ECG, a treadmill test or an echo. Panic attacks and acidity are real and treatable too, but they should only be called the cause once the heart has been ruled out.</p>

