<h2>Why you should never "wait and see"</h2>

<p>In a heart attack, a clot blocks an artery and the heart muscle beyond it starts to die. Doctors say "time is muscle": the sooner the artery is opened, the more muscle survives and the lower the risk of heart failure or a sudden cardiac arrest. Treatment works best in the first hours, which is the idea behind the <a href="<?= post_url('golden-hour-emergency') ?>">golden hour in emergencies</a>.</p>

<p>A false alarm costs a few hours in an emergency department. A missed heart attack can cost a life. No ambulance crew or doctor will be annoyed that you called for chest pain that turned out to be acidity.</p>

<h2>What to do while waiting for the ambulance: step by step</h2>

<h3>Step 1: Call 112 or an ambulance</h3>

<p>Call first, before trying any remedy. Say: "Chest pain, suspected heart attack, conscious and breathing," and give the full address with a landmark. Ask for an ambulance with cardiac monitoring, such as an <a href="<?= link_to('als') ?>">ALS ambulance with cardiac monitoring and emergency medicines</a>. Keep the phone on speaker so the dispatcher can guide you.</p>

<h3>Step 2: Stop all activity and sit them down</h3>

<p>Help the person sit on the floor or bed, half-sitting against a wall or pillows with their knees bent. Don't let them walk to the car, climb stairs or go to the bathroom. If they are breathless, don't make them lie flat.</p>

<h3>Step 3: Give aspirin, if it is safe</h3>

<p>If the person is an adult, fully awake, <strong>not allergic</strong> to aspirin, has no bleeding problem and has not been told by a doctor to avoid it, give <strong>one regular-strength aspirin (300 to 350 mg) to chew slowly</strong>. Confirm the dose with the dispatcher. Don't give aspirin if you suspect a stroke, or if the pain is a sudden tearing pain through to the back, unless the dispatcher advises it.</p>

<h3>Step 4: Help with their own heart medicine</h3>

<p>If the person has a known heart condition and their own prescribed medicine, such as Sorbitrate kept under the tongue, help them take it exactly as their doctor prescribed while sitting down. Never give anyone else's tablets. Our guide to <a href="<?= post_url('heart-attack-first-aid') ?>">heart attack first aid before the ambulance arrives</a> explains aspirin and Sorbitrate in more detail.</p>

<h3>Step 5: Keep them calm and note the details</h3>

<ul>
  <li>Loosen tight collars, belts, ties and saris, and open a window or switch on a fan.</li>
  <li>Speak calmly. Fear raises the heart rate.</li>
  <li><strong>Note the time</strong> the pain started and any medicines given.</li>
  <li>Keep old ECGs, prescriptions and a list of medicines ready for the crew.</li>
</ul>

<h3>Step 6: Prepare for the crew</h3>

<p>Send someone to unlock the gate, call the lift to the ground floor and tell the society guard. If your address is hard to find, send a person to the main road. Our guide on <a href="<?= post_url('how-to-call-ambulance-delhi-ncr') ?>">how to call an ambulance in Delhi NCR</a> has a ready script for the call.</p>

