<p>Some other causes of chest pain are just as urgent as a heart attack. <strong>Sudden, severe, tearing pain</strong> that goes through to the back can be a tear in the body's main artery. <strong>Sharp pain that is worse on breathing in</strong>, with sudden breathlessness, can be a clot in the lungs, especially after a long journey, surgery or bed rest, or with a swollen calf. Both need an ambulance immediately. For breathlessness without much pain, see our guide to <a href="<?= post_url('sudden-breathlessness-first-aid') ?>">first aid for sudden breathlessness</a>.</p>

<h2>Red flags: call an ambulance immediately</h2>

<p>Call <strong>112</strong> or an ambulance straight away if chest pain or discomfort:</p>

<ul>
  <li>lasts more than a few minutes, or keeps coming back,</li>
  <li>feels like pressure, squeezing, heaviness or tightness,</li>
  <li>spreads to the arm, jaw, neck, back or upper stomach,</li>
  <li>comes with sweating, breathlessness, nausea, vomiting, dizziness or fainting,</li>
  <li>started during physical effort and doesn't settle with rest,</li>
  <li>is sudden and severe, or tearing through to the back,</li>
  <li>happens in someone with known heart disease, diabetes, high blood pressure, high cholesterol, a smoking habit or a family history of early heart attacks.</li>
</ul>

