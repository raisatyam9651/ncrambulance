<p>It is late after a family wedding. The food was heavy, and your father says there is a burning feeling in his chest. "Just gas," he says, and asks for Eno. Someone suggests lying down, someone else suggests a walk. An hour later he is still uncomfortable, sweating and quiet. This is how many heart attacks in Indian homes are missed: not through carelessness, but because the pain looks so ordinary.</p>

<p>This guide explains how heart-related chest pain usually feels, how it differs from gas, acidity, a panic attack and a pulled muscle, which warning signs mean you should call an ambulance right away, and what to do while you wait. The most important message is simple: you can't rule out the heart at home. When in doubt, call for a <a href="<?= link_to('cardiac') ?>">cardiac ambulance with ECG monitoring and a defibrillator</a>.</p>

<h2>Why you can't tell for sure at home</h2>

<p>The heart, the food pipe and the stomach sit close together and share nerve pathways, so the brain often can't tell exactly where pain is coming from. A heart attack can feel like burning indigestion. Severe acidity can feel like a tight band around the chest. Even doctors don't decide by the description alone: they rely on an <strong>ECG</strong>, blood tests and sometimes repeat tests over several hours.</p>

<p>So the goal of this guide is not to help you diagnose. It is to help you recognise when chest pain is likely to be serious, and to stop the dangerous habit of waiting.</p>

<h2>What does heart-related chest pain feel like?</h2>

<p>Heart pain from a heart attack or angina is caused by the heart muscle not getting enough blood. People describe it in many ways:</p>

<ul>
  <li><strong>Pressure, squeezing, heaviness or tightness</strong>, as if someone is sitting on the chest or a belt is being tightened.</li>
  <li><strong>Burning or a dull ache</strong> in the centre of the chest, behind the breastbone. It is often hard to point to with one finger.</li>
  <li><strong>Pain that spreads</strong> to one or both arms (often the left), the neck, jaw, teeth, back or upper stomach.</li>
  <li><strong>Other symptoms</strong> alongside: cold sweat, breathlessness, nausea or vomiting, dizziness, unusual tiredness or a feeling that something is very wrong.</li>
  <li><strong>Pain that lasts more than a few minutes</strong>, or goes away and comes back, especially if it started with exertion, stress or cold weather.</li>
</ul>

<div class="callout callout-info">
  <strong>Not everyone gets classic chest pain</strong>
  <p>Women, people with diabetes and older people often have milder or unusual symptoms: breathlessness, nausea, indigestion-like discomfort, extreme tiredness, or pain in the jaw, back or upper stomach with little or no chest pain. Diabetes can dull nerve pain, so a heart attack may feel like "just feeling unwell". Take sudden, unexplained symptoms seriously in these groups.</p>
</div>

