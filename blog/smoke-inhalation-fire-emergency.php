<h2>If they become unconscious or stop breathing</h2>

<p>If the person is unresponsive but breathing normally, put them in the recovery position and keep checking their breathing. If they are not breathing normally, start CPR immediately, pushing hard and fast in the centre of the chest, 100 to 120 times a minute. Follow our <a href="<?= post_url('how-to-do-cpr') ?>">CPR guide for bystanders</a> and continue until the crew takes over. If there is heavy soot around the mouth, stick to chest compressions unless you are trained and have a face shield.</p>

<h2>Why even "mild" smoke inhalation must be checked</h2>

<p>Someone may walk out of a fire coughing a little and insist they feel fine. Hours later, their airway can swell shut or their lungs can fill with fluid. Carbon monoxide and cyanide poisoning can't be seen, and a normal-looking face doesn't rule them out.</p>

<div class="callout callout-danger">
  <strong>Feeling fine is not enough</strong>
  <p>Everyone who has been in thick smoke should be checked in hospital, even if they seem well. This matters most for children, elderly people, pregnant women and anyone with asthma, COPD or heart disease. Doctors can check oxygen and carbon monoxide levels, examine the airway and keep the person under observation.</p>
</div>

<p>Severe cases may need intensive care, and an <a href="<?= link_to('icu') ?>">ICU ambulance for critical patients</a> may be needed to move them safely between hospitals. Smoke and heater fumes share some of the same dangers, which our guide to <a href="<?= post_url('carbon-monoxide-poisoning-angithi-heater') ?>">carbon monoxide poisoning from angithis and heaters</a> explains in more detail.</p>

<h2>How to prepare your home and family for a fire</h2>

<p>Most families never think about a fire until they are in one. A few minutes of planning now makes the escape far calmer:</p>

<ul>
  <li>Fit smoke alarms outside bedrooms and near the kitchen, and test them every month.</li>
  <li>Keep a small fire extinguisher or fire blanket in the kitchen, and learn how to use it before you need it.</li>
  <li>Agree on an escape plan: two ways out of every floor where possible, and a meeting point outside the building.</li>
  <li>Keep the keys for window grilles, gates and the terrace door where everyone can find them in the dark.</li>
  <li>Don't overload sockets or run heavy appliances such as ACs, room heaters and geysers on extension boards.</li>
  <li>Switch off and unplug heaters, irons and chargers before you sleep or leave home.</li>
  <li>Teach children to crawl low and get out, and never to hide under beds or inside cupboards during a fire.</li>
</ul>

<p>Practise the plan once or twice a year, so that on the night it matters, nobody has to stop and think.</p>

