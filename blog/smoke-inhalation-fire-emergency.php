<p>It's 2 am in a Faridabad apartment block. A short circuit in the ground-floor meter room has set the wiring alight, and thick black smoke is pouring up the only staircase. Families on the upper floors wake up coughing, unsure whether to run down through the smoke or stay where they are.</p>

<p>In most building fires, it is the smoke, not the flames, that harms people first. This guide explains how to get out of a smoke-filled building safely, how to recognise smoke inhalation injury, how to help a victim after rescue, and why even "mild" cases need a hospital check by <a href="<?= link_to('emergency') ?>">emergency ambulance</a>.</p>

<h2>Why smoke is so dangerous</h2>

<p>Smoke from a house or building fire harms the body in three ways:</p>

<ul>
  <li><strong>Heat</strong>: very hot air and gases burn the mouth, throat and windpipe. The lining swells, and the swelling can block the airway, sometimes hours later.</li>
  <li><strong>Poisonous gases</strong>: burning plastics, foam mattresses, sofas, wiring and synthetic fabrics release carbon monoxide and hydrogen cyanide. Both stop the body from using oxygen and can cause confusion, collapse and death.</li>
  <li><strong>Soot and irritant chemicals</strong>: these coat and inflame the airways and lungs, causing coughing, wheezing and, over the following hours, fluid in the lungs.</li>
</ul>

<p>Thick smoke also makes it impossible to see, and people lose their way in corridors they walk through every day.</p>

<h2>How to escape a smoke-filled building safely</h2>

<ul>
  <li><strong>Raise the alarm.</strong> Shout "Fire!", press the fire alarm if there is one, and bang on neighbours' doors as you leave.</li>
  <li><strong>Get low.</strong> Smoke and hot gases rise, so the cleanest air is near the floor. Crawl on your hands and knees and keep your head down.</li>
  <li><strong>Test doors before opening them.</strong> Touch the door and the handle with the back of your hand. If it's hot, don't open it; use another way out. If it's cool, open it slowly, stay low and be ready to shut it if smoke pushes in.</li>
  <li><strong>Close doors behind you.</strong> A closed door slows the spread of smoke and fire.</li>
  <li><strong>Use the stairs, never the lift.</strong> Lifts can stop between floors or open onto a burning floor, and lift shafts fill with smoke.</li>
  <li><strong>Don't stop for belongings and never go back in.</strong> Tell the firefighters if anyone is still inside.</li>
  <li><strong>Call 101 (fire brigade) or 112</strong> once you are out. Give the address, the floor and how many people may be trapped.</li>
</ul>

<p>A wet cloth over your nose and mouth offers only limited protection. It may filter some soot, but it does not stop carbon monoxide or other toxic gases, so don't waste time looking for one. Getting low and getting out matters far more.</p>

<div class="callout callout-tip">
  <strong>If you are trapped inside</strong>
  <p>Close the door between you and the fire and seal the gaps with wet towels, bedsheets or clothes. Go to a room with a window or balcony, call 101 or 112 and give your exact flat number and floor. Signal from the window with a cloth or a phone torch, stay low and don't jump.</p>
</div>

<p>In Delhi NCR, many building fires start from electrical short circuits, often when wiring is overloaded by air conditioners in summer or heaters in winter. Narrow staircases cluttered with stored items, locked terrace doors, and factories or godowns inside residential areas make escape harder. Keep staircases clear, know two ways out of your building, and make sure the terrace door can be opened from inside.</p>

<h2>Signs of smoke inhalation injury</h2>

<p>After anyone comes out of a fire, look for these danger signs. Any one of them means the airway or lungs may be injured and the person needs urgent hospital care:</p>

<ul>
  <li>Soot around the nose or mouth, or coughing up black or grey sputum</li>
  <li>Singed nostril hair, eyebrows, eyelashes or beard</li>
  <li>Burns on the face, lips or neck</li>
  <li>A hoarse or changed voice, or difficulty swallowing</li>
  <li>Noisy, high-pitched breathing (stridor), wheezing or a cough that won't stop</li>
  <li>Breathlessness, fast breathing or chest pain</li>
  <li>Blue or grey lips</li>
  <li>Headache, confusion, drowsiness or vomiting, which may mean carbon monoxide or cyanide poisoning</li>
</ul>

<h2>How to help a victim after rescue: step by step</h2>

<h3>Step 1: Stay safe and move to fresh air</h3>

<p>Move the person well away from the building, upwind of the smoke and out of the way of fire engines. Don't go back into the building for anyone. Leave that to firefighters, who have breathing equipment.</p>

<h3>Step 2: Call for an ambulance</h3>

<p>If you haven't already, call 112 or an ambulance helpline. Say how many people were in the smoke and whether anyone is unconscious, struggling to breathe, hoarse or burnt. For a victim with breathing difficulty, ask whether a <a href="<?= link_to('ventilator') ?>">ventilator ambulance for breathing support</a> can be sent.</p>

<h3>Step 3: Sit them upright and loosen clothing</h3>

<p>Sitting up makes breathing easier than lying flat. Loosen collars, belts, ties and anything tight around the chest, and keep them calm and still, because moving around increases the body's need for oxygen. If they have asthma or COPD, help them use their own reliever inhaler as prescribed. Our guide to <a href="<?= post_url('severe-asthma-attack-first-aid') ?>">severe asthma attack first aid</a> explains how.</p>

<h3>Step 4: Cool any burns</h3>

<p>Hold burnt skin under cool running water for 20 minutes. Remove rings, watches and clothing near the burn unless it is stuck to the skin, then cover the burn loosely with cling film or a clean, non-fluffy cloth. Don't apply toothpaste, ghee, ice or creams, and keep the rest of the person warm. Our <a href="<?= post_url('burns-first-aid') ?>">burns first aid guide</a> has the details.</p>

<h3>Step 5: Keep watching their breathing</h3>

<p>Stay with the person and watch for any of the danger signs above, especially a voice that grows hoarser, noisier breathing or increasing confusion. Note what you see and when, and tell the ambulance crew. If their eyes sting, rinse them gently with clean water.</p>

