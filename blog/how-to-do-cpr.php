<h2>Do you need to give mouth-to-mouth breaths?</h2>

<p>For an adult who suddenly collapses, <strong>hands-only CPR</strong> is the recommended approach for untrained bystanders. In the first few minutes after the heart stops, the blood still carries oxygen, and continuous chest compressions move it to the brain. If you haven't been trained, or don't feel comfortable giving breaths to a stranger, do hands-only CPR. It is far better than doing nothing.</p>

<p>If you are trained and willing, you can give <strong>30 compressions followed by 2 rescue breaths</strong>:</p>

<ol>
  <li>Tilt the head back with one hand on the forehead and lift the chin with two fingers of the other.</li>
  <li>Pinch the soft part of the nose closed and seal your mouth over theirs.</li>
  <li>Blow steadily for about one second, just enough to see the chest rise.</li>
  <li>Give a second breath, then go straight back to 30 compressions. The two breaths should take less than 10 seconds.</li>
</ol>

<p>If the breaths don't go in, don't keep retrying. Return to compressions. Breaths matter much more when the collapse started with a breathing problem, such as drowning, choking or smoke, and in children and babies. Read our guide to <a href="<?= post_url('cpr-on-child-and-baby') ?>">CPR on a child or baby</a> to see how the technique changes for little ones.</p>

<h2>How long should you continue CPR?</h2>

<p>Don't stop to check whether the person has recovered. Keep going until:</p>

<ul>
  <li>the ambulance crew arrives and takes over,</li>
  <li>the person shows clear signs of life: they open their eyes, move on purpose, cough or start breathing normally,</li>
  <li>the AED tells you to pause while it analyses or delivers a shock,</li>
  <li>you are too exhausted to continue and nobody can take over, or</li>
  <li>the place becomes unsafe for you.</li>
</ul>

<p>In Delhi NCR, traffic, narrow lanes and high-rise buildings can all add minutes before the crew reaches the patient. Your CPR buys the brain that time.</p>

<h2>What if you break a rib?</h2>

<p>You may feel or hear a crack under your hands, especially in older people. This is a known side effect of effective CPR and <strong>not a reason to stop</strong>. Quickly check that your hands are still in the centre of the breastbone and not drifting onto the ribs, then carry on at the same depth. A broken rib heals. A brain left without blood flow for several minutes may never recover.</p>

<h2>Can you be blamed if CPR doesn't work?</h2>

<p>The fear of police cases or blame stops many people in India from helping. Remember the reality: a person in cardiac arrest will die without help, and CPR can only improve their chances.</p>

<p>Indian law protects people who act in good faith to help someone in an emergency, and nobody expects a bystander to perform like a doctor. Trying, and following the dispatcher's instructions, is exactly what is asked of you. Our guide to the <a href="<?= post_url('good-samaritan-law-india') ?>">Good Samaritan law in India</a> explains your rights as a helper.</p>

<h2>CPR in real situations: women, cars, lifts and crowds</h2>

<ul>
  <li><strong>If the person is a woman:</strong> don't hesitate. The technique is exactly the same, and you can push through her clothes. The chest only needs to be bare for AED pads, so ask others to hold up a dupatta, shawl or bedsheet around her for privacy.</li>
  <li><strong>In a car or auto:</strong> CPR doesn't work in a seat. Stop safely, get the person out and flat on the ground, then start.</li>
  <li><strong>In a lift, staircase or narrow corridor:</strong> drag them onto the nearest flat floor where you can kneel beside the chest.</li>
  <li><strong>In a crowd:</strong> point at people and give clear tasks: "You, call 112. You, ask security for the AED. You, keep people back."</li>
</ul>

<h2>If they start breathing again</h2>

<p>If the person starts breathing normally but stays unconscious, roll them into the <strong>recovery position</strong>: on their side, top leg bent at the knee, head tilted back slightly so the airway stays open and any vomit can drain out. Our guide to <a href="<?= post_url('unconscious-person-first-aid') ?>">first aid for an unconscious person</a> shows how to do it safely.</p>

<p>Keep watching their breathing, and leave any AED pads on with the machine switched on. If they stop breathing normally again, roll them onto their back and restart CPR immediately. Tell the ambulance crew when the person collapsed, how long CPR was given and whether the AED gave any shocks.</p>

<h2>Adult CPR: quick do's and don'ts</h2>

<div class="do-dont">
  <div class="do">
    <h3>Do</h3>
    <ul>
      <li>Call 112 or an ambulance and put the phone on speaker</li>
      <li>Start CPR if they are unresponsive and only gasping</li>
      <li>Push hard and fast in the centre of the chest</li>
      <li>Send someone for an AED and use it as soon as it arrives</li>
      <li>Swap helpers every two minutes and keep going</li>
    </ul>
  </div>
  <div class="dont">
    <h3>Don't</h3>
    <ul>
      <li>Wait to see if they "come round" on their own</li>
      <li>Splash water, rub their hands and feet or make them sit up</li>
      <li>Pour water, juice or glucose water into their mouth</li>
      <li>Do CPR on a soft bed if you can move them to the floor</li>
      <li>Stop because of a cracked rib or the fear of blame</li>
    </ul>
  </div>
</div>

<h2>Why every second of CPR counts</h2>

<p>When the heart stops, brain cells begin to be damaged within minutes, and every minute without CPR lowers the chance of survival. Bystander CPR keeps some blood flowing until the defibrillator and the ambulance crew arrive. Most cardiac arrests happen at home, so the person who starts CPR is usually a family member.</p>

