<p>It happens in seconds. A man slumps over his desk in an office tower, an uncle collapses while dancing at a wedding, or a father falls in the living room after dinner. He doesn't answer when you call his name, and his breathing has turned into strange, noisy gasps. His heart has most likely stopped, and the people around him are his lifeline until help arrives.</p>

<p>CPR (cardiopulmonary resuscitation) is the skill that bridges that gap. It keeps blood moving to the brain until a defibrillator and an <a href="<?= link_to('als') ?>">ALS ambulance with cardiac monitoring</a> reach the patient. This guide walks you through adult CPR step by step: when to start, where to put your hands, how hard and fast to push, whether you need to give breaths, and when you can stop. You don't need a certificate. You need to start.</p>

<h2>When should you start CPR?</h2>

<p>Start CPR on an adult who is <strong>unresponsive</strong> and <strong>not breathing normally</strong>. That is all you need to check.</p>

<ul>
  <li><strong>Unresponsive:</strong> tap both shoulders firmly and shout, "Can you hear me?" There is no eye opening, no words and no movement.</li>
  <li><strong>Not breathing normally:</strong> look at the chest and face for no more than 10 seconds. There is no breathing at all, or only slow gasps, snorts, gurgles or snoring sounds.</li>
</ul>

<p>Don't try to feel for a pulse. It is easy to get wrong when you are frightened, and it wastes time the brain doesn't have. If you are unsure, start CPR. Chest compressions rarely cause serious harm to someone whose heart is still beating, but waiting when the heart has stopped is often fatal.</p>

<div class="callout callout-danger">
  <strong>Gasping is not breathing</strong>
  <p>In the first minutes after the heart stops, many people make slow, deep gasps or gurgling sounds. Families often take this as a sign of life and wait. It is not normal breathing. It is a sign of cardiac arrest, and it means you should start CPR now. A few seconds of jerking of the arms and legs at the moment of collapse can also look like a fit. If the person then stays unresponsive and isn't breathing normally, start CPR.</p>
</div>

<p>A cardiac arrest is not a heart attack. In a heart attack the person is usually awake, with chest pain. In a cardiac arrest the heart stops pumping and they collapse. One can lead to the other, so if someone is awake with chest pain, follow our guide to <a href="<?= post_url('heart-attack-first-aid') ?>">heart attack first aid before the ambulance arrives</a>.</p>

<h2>How to do CPR on an adult: step by step</h2>

<h3>Step 1: Make sure it's safe to help</h3>

<p>Take two seconds to look around before you rush in. On a road, watch for traffic. If the person may have had an electric shock, switch off the mains before you touch them. You can't help anyone if you become a second patient.</p>

<h3>Step 2: Check for a response and shout for help</h3>

<p>Kneel beside them, tap both shoulders firmly and shout their name or "Are you all right?" If there is no response, shout loudly for help: family members, neighbours, the society guard, anyone nearby. One extra pair of hands can make the call, fetch a defibrillator and take over CPR when you tire.</p>

<h3>Step 3: Call 112 or an ambulance on speaker</h3>

<p>Dial <strong>112</strong> or a 24/7 ambulance helpline and put the phone on speaker next to you, so both hands stay free. Say clearly: "Adult collapsed, not breathing normally, I'm starting CPR," then give the full address with a landmark. Ask for an ambulance with a defibrillator. The dispatcher can count with you and coach you through each step.</p>

<p>If others are present, one person calls while you start. Another fetches an <strong>AED</strong> (automated external defibrillator): offices, malls, airports, gyms and some housing societies keep one near reception or the security desk. A third waits at the gate to guide the ambulance in.</p>

<h3>Step 4: Lay them flat on a firm surface</h3>

<p>Roll the person onto their back on the floor. A bed or sofa sinks under your hands and absorbs much of each push, so if they collapsed on a bed, two people should slide them onto the floor. Kneel beside their chest. You can push through a thin shirt or kurta, so don't waste time undressing them, but pull aside a thick sweater or jacket if it gets in the way.</p>

<h3>Step 5: Put your hands in the centre of the chest</h3>

<p>Place the <strong>heel of one hand in the centre of the chest</strong>, on the lower half of the breastbone (roughly in line with the nipples). Put your other hand on top and interlock your fingers, keeping them lifted off the ribs. Straighten and lock your elbows, and bring your shoulders directly above your hands. This lets you push with your body weight rather than your arm muscles, which tire quickly.</p>

<h3>Step 6: Push hard and fast</h3>

<ul>
  <li><strong>Depth:</strong> push down <strong>5 to 6 cm</strong> (about two inches) with each compression. It feels harder than you expect. That is normal.</li>
  <li><strong>Speed:</strong> <strong>100 to 120 pushes a minute</strong>, a little faster than two pushes every second.</li>
  <li><strong>Recoil:</strong> let the chest rise all the way back up after each push. Don't lean your weight on it between pushes, because the heart refills during the recoil.</li>
  <li><strong>No pauses:</strong> keep any breaks shorter than 10 seconds. Blood flow drops the moment you stop.</li>
</ul>

<div class="callout callout-tip">
  <strong>Find the rhythm</strong>
  <p>Count out loud, "one, two, three..." up to 30, then start again. Some people push to the beat of the song "Stayin' Alive", or set a free metronome app to about 110 beats a minute. Most people get tired within two minutes and their pushes get shallower without them noticing, which is why swapping helps.</p>
</div>

<h3>Step 7: Use the AED the moment it arrives</h3>

<p>Switch it on and follow its voice prompts. Keep pushing while another person bares the chest and sticks on the pads. Stop only when the machine says it is analysing or tells everyone to stand clear. After a shock, or if no shock is advised, go straight back to compressions. Our guide on <a href="<?= post_url('how-to-use-aed-defibrillator') ?>">how to use an AED defibrillator</a> explains every prompt in plain language.</p>

<h3>Step 8: Keep going and swap every 2 minutes</h3>

<p>If there is anyone else around, take turns about every two minutes, or whenever the AED pauses to check the heart. Switch over in a few seconds: the new person kneels on the other side, ready to start the moment you lift your hands. Even someone who has never done CPR can take over after watching you for a minute.</p>

