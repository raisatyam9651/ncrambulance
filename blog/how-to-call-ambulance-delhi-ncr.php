<h2>If the patient gets worse while you wait</h2>

<p>If the person stops responding and isn't breathing normally (no breathing, or only occasional gasps), tell the dispatcher immediately and start CPR. Push hard and fast in the centre of the chest, 100 to 120 times a minute, and don't stop until the crew takes over. Our guide to <a href="<?= post_url('how-to-do-cpr') ?>">hands-only CPR for adults</a> shows exactly how.</p>

<p>If they are unconscious but breathing normally, turn them onto their side in the recovery position so their airway stays clear, and keep checking their breathing. If anything else changes, such as fresh bleeding, a fit, or the person waking up confused, tell the dispatcher or call back straight away.</p>

