<h2>How to call an ambulance: step by step</h2>

<h3>Step 1: Make sure you are safe, then check the patient</h3>

<p>Take two seconds to look around. At a road accident, watch for traffic, leaking fuel or fire. At home, switch off the mains before touching someone who has had an electric shock. Then check whether the person responds when you tap their shoulders and speak loudly, and whether they are breathing normally. The dispatcher will ask you both questions. If you are calling for a stranger, remember that <a href="<?= post_url('good-samaritan-law-india') ?>">India's Good Samaritan law protects people who help</a>.</p>

<h3>Step 2: Dial and say what you need first</h3>

<p>Call 112 or your ambulance helpline. Start with the most important facts: "I need an ambulance. My father has collapsed and is not breathing properly." The dispatcher will ask for more, but leading with the emergency helps them understand how urgent your call is.</p>

<h3>Step 3: Give the exact location</h3>

<p>This is the information most often given badly. The dispatcher needs:</p>

<ul>
  <li>The house or flat number, the floor, and the tower or block</li>
  <li>The society, colony or sector name, the city and the pin code</li>
  <li>A well-known landmark nearby: a temple, school, metro station, petrol pump or mall</li>
  <li>Which gate to use, if your society or campus has several</li>
</ul>

<h3>Step 4: Describe the patient in a few words</h3>

<ul>
  <li><strong>Age and sex</strong>: "a 68-year-old man"</li>
  <li><strong>The main problem</strong>: chest pain, a fall, a fit, breathing trouble, bleeding or burns</li>
  <li><strong>Conscious and breathing?</strong> Say clearly whether they respond to you and are breathing normally</li>
  <li><strong>How many patients</strong>, and any hazards such as fire, gas or traffic</li>
  <li><strong>Known conditions</strong>, if you know them: heart disease, diabetes, pregnancy</li>
</ul>

<p>Answer the questions in the order you're asked. They are designed to help the dispatcher send the right help quickly.</p>

<h3>Step 5: Share a live location</h3>

<p>If the helpline uses WhatsApp, send your live location as well as saying the address (the next section explains how). A map pin removes the guesswork, especially at night or in a large township where many towers look the same.</p>

<h3>Step 6: Stay on the line and follow instructions</h3>

<p>Don't hang up until the dispatcher tells you to. Put the phone on speaker so your hands are free. You may be asked to unlock the door, turn the patient on their side or start CPR. Do exactly what you are told, and say at once if anything changes.</p>

<h3>Step 7: Keep the phone free and guide the crew in</h3>

<p>After the call, don't use that phone for anything else, because the ambulance crew may ring you for directions. Send someone to the gate or the main road to wave the ambulance in, and tell the society guard it is coming. Our <a href="<?= post_url('before-ambulance-arrives-checklist') ?>">checklist for families waiting for an ambulance</a> covers the gate, the lift and the documents to keep ready.</p>

