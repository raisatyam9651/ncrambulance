<h2>How to share your exact location</h2>

<p>Addresses in Delhi NCR can be confusing: new sectors, repeated block letters, societies with five gates. A map pin is the surest way to be found.</p>

<ul>
  <li><strong>WhatsApp live location:</strong> open the chat, tap the attachment icon (a paperclip or plus sign), choose Location, then Share live location. Pick a duration of an hour or more so the crew can still see you if you move.</li>
  <li><strong>Google Maps pin:</strong> open Google Maps and tap the blue dot that shows where you are, then use the share option. You can also press and hold on your building to drop a pin and share that.</li>
  <li><strong>Say the landmark anyway:</strong> GPS can be off by a building or two in crowded colonies, and phones lose signal in basements and lifts.</li>
  <li><strong>On a highway or expressway:</strong> say which direction you were travelling, and the nearest exit, toll plaza, flyover or kilometre stone.</li>
  <li><strong>Near the metro:</strong> elevated metro pillars carry numbers. Reading out the pillar number gives the crew a precise point to head for.</li>
</ul>

