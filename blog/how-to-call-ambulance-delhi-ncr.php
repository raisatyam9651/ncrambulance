<h2>Why should you stay on the line?</h2>

<p>It can feel as if the call is wasting time. It isn't. Help may already be on its way while you talk, and staying connected means the dispatcher can:</p>

<ul>
  <li><strong>Talk you through CPR</strong> if the person stops breathing normally, often counting the rhythm with you.</li>
  <li><strong>Tell you what to do and what to avoid</strong>, such as keeping a heart patient still or turning a vomiting person on their side.</li>
  <li><strong>Update the crew</strong> if the patient gets worse, so they arrive ready.</li>
  <li><strong>Call you back</strong> if the line drops or the crew can't find the address.</li>
</ul>

