<h2>Preventing the next fall</h2>

<p>One fall makes another more likely, so treat it as a warning. Simple changes at home help:</p>

<ul>
  <li>Night lights along the route from the bed to the bathroom.</li>
  <li>Grab bars next to the toilet and in the shower, and anti-slip mats on wet floors.</li>
  <li>Well-fitting footwear with grip, rather than loose chappals, socks or bare feet on marble or tiles.</li>
  <li>No loose rugs, doormats, trailing wires or clutter on the floor.</li>
  <li>Getting up slowly from the bed or a chair, sitting for a moment first.</li>
  <li>A doctor's review of medicines that cause dizziness or drowsiness, and regular eye checks.</li>
  <li>Gentle exercise for strength and balance, as advised by their doctor or physiotherapist.</li>
</ul>

