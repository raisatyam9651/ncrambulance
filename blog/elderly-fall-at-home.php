<p>It often happens at night. You hear a thud from the bathroom and find your 78-year-old mother on the floor, embarrassed, saying "I'm fine, just help me up." Or your father has slipped on a wet marble floor, or tripped over a doormat on the way to the kitchen. Every instinct tells you to pull them to their feet as fast as possible. In many cases, that is the wrong first move.</p>

<p>This guide explains what to do in the first few minutes after an older person falls at home: how to check for a hip fracture or head injury, when to keep them still and call a <a href="<?= link_to('bls') ?>">BLS ambulance with a stretcher and a trained attendant</a>, how to help them up safely if they aren't hurt, and why the reason they fell matters as much as the fall itself.</p>

<h2>Should you lift an elderly person straight after a fall?</h2>

<p>No. Wait a minute or two before anyone moves. Older bones break easily, and a fracture of the hip, wrist, spine or ribs isn't always obvious at first. Pulling someone up by the arms can make an injury worse, tear thin skin or strain a shoulder, and lifting a fallen adult on your own can injure your back too.</p>

<p>Instead, kneel beside them, speak calmly and let them catch their breath. Ask what happened, where it hurts and whether they hit their head. Their answers, and how clearly they give them, tell you what to do next. If they don't respond, or aren't breathing normally, go straight to the section on what to do if things get worse, below.</p>

<h2>How to check for injuries after a fall</h2>

<p>Before you help them move, check from head to toe. Ask them to stay where they are while you do it.</p>

<ul>
  <li><strong>Head:</strong> did they hit it? Look for a bump, cut or bleeding, and watch for confusion, drowsiness, vomiting, a severe headache or slurred speech. Our guide to <a href="<?= post_url('head-injury-first-aid') ?>">head injury first aid</a> lists the warning signs.</li>
  <li><strong>Hip:</strong> pain in the hip or groin, especially on moving the leg, being unable to put weight on it, or a leg that looks shorter or turned outwards compared with the other. These are classic signs of a broken hip.</li>
  <li><strong>Arms and wrists:</strong> people often put out a hand as they fall. Swelling, an odd shape or severe pain in the wrist or shoulder suggests a fracture. See how to support it in our <a href="<?= post_url('fracture-first-aid') ?>">fracture first-aid guide</a>.</li>
  <li><strong>Back and neck:</strong> new pain in the neck or back, or tingling, numbness or weakness in the arms or legs. If you notice any of these, don't move them at all.</li>
  <li><strong>Skin:</strong> older skin tears easily. Press gently on any bleeding with a clean cloth.</li>
  <li><strong>Breathing and chest:</strong> breathlessness, chest pain, or rib pain when breathing in.</li>
</ul>

<div class="callout callout-danger">
  <strong>Head knock on blood thinners? Go to hospital</strong>
  <p>If the person takes blood-thinning medicine (often prescribed after a stroke, a heart attack, valve surgery, an irregular heartbeat or a clot) and has hit their head at all, they need to be checked in hospital, even if they seem perfectly fine. Blood thinners can let bleeding inside the skull build up slowly over hours before any symptoms appear.</p>
</div>

<h2>Why did they fall? It matters</h2>

<p>A fall is sometimes the first sign of an illness. Ask them, or anyone who saw it, what happened just before:</p>

<ul>
  <li><strong>Dizziness on standing up</strong>, often from low blood pressure, dehydration in summer, or a new or changed medicine.</li>
  <li><strong>Low blood sugar</strong> in someone with diabetes, especially after a missed meal: sweating, shaking, confusion. Read about <a href="<?= post_url('low-blood-sugar-hypoglycemia-emergency') ?>">what to do for low blood sugar</a>.</li>
  <li><strong>Stroke signs:</strong> a drooping face, weakness of an arm or leg on one side, or slurred speech. Call an ambulance immediately and follow our <a href="<?= post_url('stroke-first-aid-be-fast') ?>">BE FAST stroke first-aid guide</a>.</li>
  <li><strong>A blackout</strong> without tripping, chest pain, or a racing or very slow heartbeat, which can point to a heart problem.</li>
  <li><strong>Fever or new confusion</strong>, which in older people can be the first sign of an infection such as a urine or chest infection.</li>
</ul>

<p>If the fall seems to have been caused by any of these, call an ambulance even if there is no injury.</p>

<h2>What to do after an elderly person falls: step by step</h2>

<h3>Step 1: Stay calm and reassure them</h3>

<p>Many older people feel embarrassed or frightened after a fall and want to get up quickly to prove they're fine. Tell them there's no hurry. Make the area safe: switch on the lights, mop up water on a bathroom floor, and move anything they might knock into.</p>

<h3>Step 2: Check for injuries before anyone moves them</h3>

<p>Go through the head-to-toe check above. Don't let them try to stand while you are still checking, and don't let well-meaning relatives haul them up.</p>

<h3>Step 3: If they are hurt, keep them still and call an ambulance</h3>

<p>If you suspect a broken hip or other fracture, a head, neck or back injury, or if they are confused, can't move or are in severe pain, call 112 or an ambulance and leave them where they are. Then:</p>

<ul>
  <li>Make them comfortable without moving the injured part. A folded towel under the head is fine if you don't suspect a neck injury.</li>
  <li>Keep them warm with a blanket or shawl. Floors get cold quickly, especially in a Delhi winter.</li>
  <li>Don't give food or drink if you suspect a fracture, in case they need an anaesthetic. You can moisten their lips.</li>
  <li>Gather their medicine list, recent prescriptions and ID for the crew.</li>
</ul>

<p>Tell the dispatcher which floor you are on and whether there is a lift. In older houses with narrow staircases, the crew can bring a stretcher or carry chair to bring the patient down safely. Don't try to carry an injured person down the stairs yourselves.</p>

<h3>Step 4: If they aren't hurt, help them get up the safe way</h3>

<p>If they feel well, didn't hit their head, have nothing worse than a bruise and want to get up, guide them through this method. You steady and encourage; they do the work. Don't take their full weight.</p>

<ol>
  <li><strong>Roll onto the side.</strong> Bend the knees and roll gently onto one side.</li>
  <li><strong>Get onto hands and knees.</strong> Push up with the arms. Pause here if they feel dizzy.</li>
  <li><strong>Crawl to a sturdy chair</strong> or the edge of a bed. Use a heavy chair without wheels, ideally pushed against a wall.</li>
  <li><strong>Put both hands on the seat</strong>, then bring the stronger leg forward with the foot flat on the floor, in a half-kneeling position.</li>
  <li><strong>Push up and turn to sit</strong> on the chair, using the arms and the front leg.</li>
  <li><strong>Rest for several minutes</strong> before trying to stand or walk, and check again for any pain or dizziness.</li>
</ol>

<p>If they can't manage any stage, or it causes pain, stop. Help them back down, keep them warm and comfortable on the floor, and call for help. An ambulance crew can lift them safely with the right equipment.</p>

<h3>Step 5: Keep watching them in the days after</h3>

<p>Even after a fall that seemed minor, watch for new pain, swelling, limping, headache, vomiting, drowsiness or confusion in the following days. Arrange a visit to their doctor to review the fall, their medicines and their eyesight.</p>

