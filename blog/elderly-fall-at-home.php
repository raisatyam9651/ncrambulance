<h2>If things get worse: unresponsive or not breathing</h2>

<p>If the person doesn't respond when you tap their shoulders and speak loudly, check whether they are breathing normally, taking no more than 10 seconds.</p>

<ul>
  <li><strong>Breathing normally:</strong> call 112. If you don't suspect a neck or back injury, put them in the recovery position on their side. If you do, leave them as they are unless they vomit or their breathing becomes noisy; then roll them onto their side, keeping the head, neck and body in line.</li>
  <li><strong>Not breathing normally:</strong> call 112, put the phone on speaker and start CPR straight away. Older ribs may crack during compressions; keep going anyway. Our guide on <a href="<?= post_url('how-to-do-cpr') ?>">how to do CPR on an adult</a> walks you through it.</li>
</ul>

<p>If someone who seemed fine after a fall later becomes drowsy, confused, starts vomiting or develops a severe headache, call an ambulance at once. These can be signs of bleeding inside the skull.</p>

<h2>The hidden danger: a "long lie" on the floor</h2>

<p>Older people who live alone, or who are alone during the day while the family is at work, can lie on the floor for hours before anyone finds them. This is called a "long lie", and it can be more harmful than the fall itself:</p>

<ul>
  <li><strong>Dehydration</strong>, especially in the Delhi summer.</li>
  <li><strong>Hypothermia</strong> on a cold floor in winter.</li>
  <li><strong>Pressure sores</strong> on the hips, heels and back.</li>
  <li><strong>Muscle breakdown</strong>, which releases substances into the blood that can damage the kidneys.</li>
  <li><strong>Chest infections</strong>, and a lasting fear of falling again.</li>
</ul>

<p>If you find someone who has been on the floor for a long time, or you don't know how long they were there, call an ambulance even if they say they feel fine. Keep a mobile phone within reach of an older person at all times, consider a fall-alert device, and arrange daily check-in calls.</p>

