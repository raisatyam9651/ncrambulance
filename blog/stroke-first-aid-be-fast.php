<p>It often starts with something small. Your father is reading the newspaper over his morning chai when the cup slips from his hand, or your mother's words come out jumbled during a phone call. Someone says it's tiredness or high BP and suggests they lie down for a while. That pause, while everyone waits for it to pass, is the most costly mistake families make with a stroke.</p>

<p>A stroke is a brain attack, and the treatments that limit the damage only work within a few hours of it starting. This guide shows you how to recognise a stroke using BE FAST, what to do (and not do) in the minutes before help arrives, and why the hospital you choose matters. Save the number of a <a href="<?= link_to('home') ?>">24/7 emergency ambulance service in Delhi NCR</a> before you ever need it.</p>

<h2>What is a stroke?</h2>

<p>A stroke happens when the blood supply to part of the brain is suddenly cut off. In most strokes, a clot blocks an artery in the brain (an ischaemic stroke). In others, a blood vessel bursts and bleeds into the brain (a haemorrhagic stroke). Without a steady flow of blood and oxygen, brain cells begin to die within minutes.</p>

<p>From the outside, a clot and a bleed look exactly the same. Only a CT or MRI scan at a hospital can tell them apart, and that single fact shapes almost everything about stroke first aid.</p>

<h2>The BE FAST signs of a stroke</h2>

<p>BE FAST is a simple way to remember the most common warning signs. They usually come on <strong>suddenly</strong>, and often affect one side of the body.</p>

<ul>
  <li><strong>B for Balance</strong>: sudden dizziness, loss of balance or coordination, or trouble walking.</li>
  <li><strong>E for Eyes</strong>: sudden blurred or double vision, or loss of sight in one or both eyes.</li>
  <li><strong>F for Face</strong>: ask them to smile. Does one side of the face droop or look uneven?</li>
  <li><strong>A for Arm</strong>: ask them to raise both arms. Does one arm drift down, or feel weak or numb? The leg on the same side may be weak too.</li>
  <li><strong>S for Speech</strong>: is their speech slurred or strange? Can they repeat a simple sentence and understand what you say?</li>
  <li><strong>T for Time</strong>: if you see even one of these signs, it's time to call an ambulance. Note the time the symptoms started.</li>
</ul>

<p>Other sudden signs include a very severe headache unlike any before, confusion, vomiting, and numbness or tingling down one side. A person does not need to have all the signs. <strong>One sudden sign is enough to call.</strong></p>

<div class="callout callout-info">
  <strong>Signs that go away still count</strong>
  <p>Sometimes the face droop or weak arm lasts only a few minutes and then disappears. This may be a transient ischaemic attack (TIA), often called a mini-stroke. It is a warning that a major stroke may follow, often within days. Treat it as an emergency and get the person to hospital, even if they now say they feel fine.</p>
</div>

<h2>Why every minute matters: the treatment window</h2>

<p>Doctors say "time is brain". During a major stroke, vast numbers of brain cells are lost for every minute the blood supply stays blocked. The earlier treatment starts, the more of the person's speech, movement and independence can be saved.</p>

<p>For a stroke caused by a clot, there are two main hospital treatments:</p>

<ul>
  <li><strong>Clot-busting medicine (thrombolysis)</strong>, given through a drip. It works only within a few hours of the stroke starting, commonly up to 4.5 hours, and works best the earlier it's given.</li>
  <li><strong>Clot removal (thrombectomy)</strong>, where a specialist pulls the clot out through a thin tube passed up from an artery. This can help selected patients with large blockages, sometimes even later than the clot-busting window, depending on their scans.</li>
</ul>

<p>Both need a brain scan first to rule out bleeding, and that takes time at the hospital too. So the window is not "4.5 hours to reach hospital": it's 4.5 hours for everything, including the journey, the scan and the tests. This is why the <a href="<?= post_url('golden-hour-emergency') ?>">golden hour in emergency care</a> applies so strongly to strokes.</p>

<p>The most useful thing you can tell the doctors is the <strong>"last known well" time</strong>: the last time the person was seen behaving normally. If they woke up with symptoms, it's the time they went to sleep or were last seen normal, not the time they woke up. Write it down or note it on your phone.</p>

<h2>What to do if you suspect a stroke: step by step</h2>

<h3>Step 1: Call an ambulance immediately</h3>

<p>Don't wait to see if the symptoms improve, and don't call the family doctor first. Dial <strong>112</strong> or a 24/7 ambulance helpline such as ours (<a href="<?= BLOG_TEL ?>"><?= BLOG_PHONE ?></a>). Say clearly: "Suspected stroke. Face drooping and slurred speech, started at 9:40 this morning." Give the full address with a landmark and ask for an <a href="<?= link_to('als') ?>">ALS ambulance with oxygen and monitoring</a>. Our guide on <a href="<?= post_url('how-to-call-ambulance-delhi-ncr') ?>">what to tell the ambulance dispatcher</a> has a short script you can follow.</p>

<h3>Step 2: Note the time and the symptoms</h3>

<p>Write down the last known well time, which signs you noticed and when each one began. If the symptoms change, note that too. Under stress, family members often remember the timeline differently, and a written note avoids confusion at the hospital.</p>

<h3>Step 3: Position them safely</h3>

<ul>
  <li>If the person is <strong>awake</strong>, help them lie down with their <strong>head and shoulders slightly raised</strong> on a pillow or folded blanket.</li>
  <li>If they're in a chair and leaning or slipping to one side, ease them down to the floor or onto a bed so they can't fall.</li>
  <li>Rest a weak arm on a pillow so it doesn't hang down or get trapped under the body.</li>
  <li>If they become <strong>drowsy or unresponsive but are breathing normally</strong>, or they are drooling or vomiting, turn them onto their side in the recovery position so the airway stays clear.</li>
  <li>Don't let them walk to the car, the lift or the bathroom. A weak leg can give way without warning.</li>
</ul>

<h3>Step 4: Give nothing by mouth</h3>

<p>No aspirin, no water, no tea, no food and no regular tablets until doctors at the hospital say it's safe. The reasons are explained further down. If their mouth feels dry, you can moisten their lips with a damp cloth.</p>

<h3>Step 5: Keep them calm, warm and watched</h3>

<ul>
  <li>Loosen tight collars, belts and saris, and cover them with a light blanket if the room is cold.</li>
  <li>Talk to them calmly, even if they can't reply. Many stroke patients understand far more than they can say.</li>
  <li>Keep checking their breathing and whether they respond to you.</li>
  <li>If they have diabetes and you have a glucometer, a quick sugar reading helps the crew, because very low sugar can look like a stroke. Don't put sugar in their mouth unless they are fully alert, can swallow normally and the dispatcher advises it.</li>
</ul>

<h3>Step 6: Get ready for the ambulance crew</h3>

<p>While one person stays with the patient, another should unlock the gate, call the lift to the ground floor and tell the society guard. Gather a list of current medicines (especially blood thinners), recent reports and an ID card. Most importantly, the person who <strong>saw the symptoms begin</strong> should travel with the patient, so they can give the timeline to the doctors.</p>

