<h2>Should you give aspirin, water or food? No, and here's why</h2>

<p>Families want to do <em>something</em>, so they reach for a tablet or a glass of water. In a stroke, both can cause harm.</p>

<ul>
  <li><strong>Aspirin can make a bleed worse.</strong> Aspirin thins the blood. That helps in a <a href="<?= post_url('heart-attack-first-aid') ?>">heart attack</a>, but in a stroke you can't know whether the cause is a clot or a bleed. If it's a bleed, aspirin may make it bigger. Doctors give it only after a scan.</li>
  <li><strong>Swallowing may not be safe.</strong> A stroke often weakens the throat muscles. Water, food or a tablet can slip into the windpipe instead of the food pipe, causing choking or a serious chest infection (aspiration pneumonia).</li>
  <li><strong>An extra BP tablet can backfire.</strong> Blood pressure is often high during a stroke, and bringing it down suddenly at home can reduce blood flow to the struggling brain. Doctors control it carefully in hospital.</li>
</ul>

<div class="callout callout-danger">
  <strong>Myths that waste precious time</strong>
  <p>A viral message claims that pricking the fingertips or earlobes with a needle can "release pressure" and reverse a stroke. It cannot. Neither can putting oil or ghee in the nose, massaging the limbs, or making the person walk "to check". These remedies delay treatment and can cause infection or choking. What helps is reaching a stroke-ready hospital quickly.</p>
</div>

<h2>Which hospital is "stroke-ready"?</h2>

<p>The nearest hospital is not always the right one for a stroke. A small nursing home without a scanner may have to refer the patient onwards, and time is lost on the way. A stroke-ready hospital should have:</p>

<ul>
  <li>a <strong>CT or MRI scanner available 24×7</strong>, so the brain can be scanned soon after arrival,</li>
  <li>a <strong>neurologist or stroke team</strong> on call round the clock,</li>
  <li>the ability to give <strong>clot-busting treatment</strong> in the emergency department, and</li>
  <li>ideally, facilities for <strong>clot removal (thrombectomy)</strong> and an <strong>ICU or stroke unit</strong>.</li>
</ul>

