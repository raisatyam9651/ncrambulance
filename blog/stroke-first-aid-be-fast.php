<p>If the patient first reaches a hospital that can scan but can't remove clots, they may need a quick transfer. A monitored <a href="<?= link_to('icu') ?>">ICU ambulance for critical patients</a> or a planned <a href="<?= link_to('hospital-transfer') ?>">hospital-to-hospital transfer</a> keeps them safe on the way.</p>

<h2>If things get worse: unresponsive, vomiting or not breathing</h2>

<p>A stroke can worsen while you wait. Keep watching and act on what you see:</p>

<ol>
  <li><strong>Vomiting or drooling</strong>: turn them onto their side straight away so the airway stays clear.</li>
  <li><strong>Unresponsive but breathing normally</strong>: place them in the recovery position and keep checking their breathing. Our guide to <a href="<?= post_url('unconscious-person-first-aid') ?>">first aid for an unconscious person</a> shows how, step by step.</li>
  <li><strong>A fit (seizure)</strong>: this can happen with a stroke. Clear the space around them, cushion the head and don't hold them down. Turn them on their side once the jerking stops.</li>
  <li><strong>Not breathing normally</strong> (no breathing, or only occasional gasps): tell the dispatcher, start <a href="<?= post_url('how-to-do-cpr') ?>">hands-only CPR</a> and send someone for an AED.</li>
</ol>

