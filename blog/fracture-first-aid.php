<h2>Open fracture: what to do if the bone is visible</h2>

<p>When a broken bone pierces the skin, there is a high risk of bleeding and serious infection. It always needs an ambulance and surgery.</p>

<ol>
  <li><strong>Don't touch the bone</strong> or try to push it back in.</li>
  <li><strong>Control bleeding</strong> by pressing firmly around the wound, not on the bone end. A ring of rolled cloth around the bone lets you bandage without pressing on it.</li>
  <li><strong>Cover the wound</strong> with a clean, non-fluffy cloth or a sterile dressing.</li>
  <li><strong>Keep the limb still</strong> and support it as you would any fracture.</li>
</ol>

<p>Our guide on <a href="<?= post_url('how-to-stop-severe-bleeding') ?>">how to stop severe bleeding</a> explains pressure and padding in more detail.</p>

<h2>Should you try to straighten a broken limb?</h2>

<p><strong>No.</strong> Pulling a limb straight is extremely painful. It can tear the nerves and blood vessels that run beside the bone, and it can push a sharp bone end through the skin, turning a closed fracture into an open one. Doctors realign bones only after an X-ray, with proper pain relief.</p>

<p>The one warning sign to act on quickly is a hand or foot beyond the injury that turns <strong>cold, pale or blue</strong>, or loses feeling. It can mean the blood supply is being cut off. Don't try to fix it yourself: call the dispatcher immediately and tell them.</p>

