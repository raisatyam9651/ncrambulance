<h2>Hip, thigh, pelvis and spine fractures: don't move them</h2>

<p>These are the fractures where moving the person can do the most harm. A broken thigh bone or pelvis can bleed heavily inside the body, and a broken spine can damage the spinal cord. Older people who fall at home often break a hip: they usually can't stand, they have pain in the groin or hip, and the leg may look shorter and turned outwards.</p>

<p>Don't try to lift them, help them stand or carry them down the stairs. Make them comfortable where they are with pillows or rolled blankets around (not under) the injured area, keep them warm and call an ambulance. Our guides on <a href="<?= post_url('elderly-fall-at-home') ?>">what to do when an elderly person falls</a> and <a href="<?= post_url('spinal-injury-first-aid') ?>">spinal injury first aid</a> cover these situations in detail.</p>

<h2>If things get worse: shock or unconsciousness</h2>

<p>Large fractures, especially of the thigh or pelvis, can cause shock from blood loss. Watch for pale, cold, clammy skin, a fast weak pulse, fast breathing, confusion or drowsiness. Lay the person flat, keep them warm, give nothing by mouth and call the dispatcher again to say they are getting worse.</p>

<p>If they become unresponsive but are breathing normally, turn them onto their side in the recovery position, unless you suspect a neck or back injury. In that case, keep the head still and only log-roll them if they vomit. If they stop breathing normally, start CPR straight away using our <a href="<?= post_url('how-to-do-cpr') ?>">hands-only CPR guide</a>, and continue until help arrives.</p>

