<p>A child falls off the slide in the society park and won't let anyone touch her wrist. An elderly mother slips in the bathroom and can't get up. A delivery rider skids on a wet road, and his leg looks bent in the wrong place. In moments like these, families often reach for warm mustard oil, try to pull the limb straight, or call the local pehlwan to "set" the bone.</p>

<p>This guide explains how to give first aid for a suspected broken bone until you reach hospital or a <a href="<?= link_to('bls') ?>">BLS ambulance with a stretcher</a> arrives. It covers how to tell a fracture from a sprain, how to make a splint from things you have at home, what to do if the bone is poking through the skin, and why you should never try to straighten it.</p>

<h2>Is it a fracture or a sprain?</h2>

<p>A fracture is a broken or cracked bone. A sprain is a stretched or torn ligament around a joint, such as the ankle or wrist. They can look alike and only an X-ray can tell for sure, but these signs point towards a fracture:</p>

<ul>
  <li>A limb that looks <strong>bent, twisted or shorter</strong> than the other side</li>
  <li><strong>Severe pain</strong> at one spot that gets much worse with movement or pressure</li>
  <li><strong>Swelling and bruising</strong> that come up quickly</li>
  <li><strong>Being unable to bear weight</strong> on it or use it</li>
  <li>A <strong>snap or crack</strong> heard at the time of injury, or a <strong>grating</strong> feeling when it moves</li>
  <li><strong>Bone visible</strong> through a wound in the skin (an open fracture)</li>
</ul>

