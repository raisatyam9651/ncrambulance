<p>If you aren't sure, <strong>treat it as a fracture</strong>. Splinting a sprain does no harm, but walking on a broken bone can.</p>

<h2>Fracture first aid: step by step</h2>

<h3>Step 1: Decide whether you need an ambulance</h3>

<p>Don't move the person, and call <strong>112</strong> or an ambulance helpline such as ours (<a href="<?= BLOG_TEL ?>"><?= BLOG_PHONE ?></a>), if:</p>

<ul>
  <li>you suspect a broken <strong>hip, thigh, pelvis, neck or back</strong></li>
  <li>the bone is <strong>through the skin</strong>, or there is heavy bleeding</li>
  <li>the hand or foot beyond the injury is <strong>cold, pale, blue or numb</strong></li>
  <li>the person has <strong>other serious injuries</strong>, such as a head injury, or shows signs of shock</li>
  <li>the pain is too severe to move them</li>
</ul>

<p>For a suspected broken finger, wrist or forearm in someone who is otherwise well, you can usually splint it and take them to hospital by car or taxi, with someone else driving. For anything more serious, ask for an <a href="<?= link_to('emergency') ?>">emergency ambulance for injuries and falls</a>.</p>

<h3>Step 2: Keep it still in the position you found it</h3>

<p>Movement causes pain, and the broken ends can damage nearby nerves, muscles and blood vessels. Ask the person to stay still, and support the injured part with your hands, a pillow or rolled clothes in the position you found it. Don't try to straighten it.</p>

<h3>Step 3: Make a splint from things at home</h3>

<p>A splint is anything stiff that stops the broken bone moving. The key rule: it must be long enough to <strong>include the joint above and the joint below</strong> the break. For a broken forearm, that means from the elbow to the wrist and hand.</p>

<ul>
  <li><strong>Stiff support:</strong> a tightly rolled newspaper or magazine, a flattened cardboard box, a wooden scale, a plank or a strong stick.</li>
  <li><strong>Padding:</strong> a folded towel, sari, dupatta or clothes between the splint and the skin, especially around the bony parts.</li>
  <li><strong>Ties:</strong> strips of cloth, a dupatta, a belt or a crepe bandage, tied above and below the break, never directly over it.</li>
</ul>

<p>Tie it firmly but not tightly. Check the fingers or toes every few minutes, and loosen the ties if they become cold, pale, blue, tingly or numb. For a suspected broken leg, if an ambulance is on its way and the person is lying still, you don't need to splint it: just support it on both sides with rolled blankets and wait.</p>

<h3>Step 4: Support an arm with a sling</h3>

<p>For a broken arm, wrist or collarbone, a sling takes the weight off the injury. Fold a dupatta or a large square of cloth into a triangle and place it under the arm with the elbow bent at a right angle. Tie the ends at the side of the neck so the hand rests slightly higher than the elbow. If the elbow can't bend without pain, don't force it: support the arm in the position you found it.</p>

<h3>Step 5: Ease swelling with ice wrapped in cloth</h3>

<p>Wrap ice or a cold pack (a packet of frozen peas works well) in a thin cloth and hold it gently on the injury for up to <strong>20 minutes</strong>. Never put ice directly on the skin, and don't use it over an open wound. Don't apply heat.</p>

<h3>Step 6: Keep them warm, calm and fasting</h3>

<p>Keep the person lying or sitting comfortably, and cover them to keep them warm. Give nothing to eat or drink, because a broken bone may need setting under anaesthesia or surgery. Ask the doctor or dispatcher before giving any painkiller.</p>

