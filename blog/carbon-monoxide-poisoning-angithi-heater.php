<h2>If they are unconscious or not breathing</h2>

<p>If the person does not respond and is not breathing normally (no breathing, or only occasional gasps), start CPR immediately in the fresh air. Push hard and fast in the centre of the chest, 100 to 120 times a minute, and keep going until the crew takes over. Our <a href="<?= post_url('how-to-do-cpr') ?>">hands-only CPR guide</a> explains the technique.</p>

<p>In hospital, doctors give high-concentration oxygen and monitor the heart and brain. A few severe cases are treated with high-pressure (hyperbaric) oxygen, which only some centres offer, and the doctors will decide whether it is needed. Even after recovery, some people have memory or concentration problems in the weeks that follow, so follow-up matters.</p>

