<p>On a cold December night in Ghaziabad, a family carries a glowing angithi into the bedroom, shuts the door and windows tight and goes to sleep. In the morning everyone wakes with a pounding headache and nausea, and the grandmother can't be woken at all. Stories like this appear in the news from North India almost every winter.</p>

<p>The cause is carbon monoxide (CO), a poisonous gas you can't see or smell. This guide explains why it is so dangerous, the early warning signs, how to rescue someone without becoming a victim yourself, what to do until a <a href="<?= link_to('ventilator') ?>">ventilator ambulance with oxygen and breathing support</a> arrives, and how to keep your family safe every winter.</p>

<h2>Why carbon monoxide is called a silent killer</h2>

<p>Carbon monoxide forms whenever coal, wood, charcoal, kerosene, LPG, petrol or diesel burns without enough fresh air. It has <strong>no colour, no smell and no taste</strong>, and it doesn't sting the eyes the way smoke does. Glowing coals that look almost smokeless can still give off a lot of it.</p>

<p>When you breathe it in, CO locks onto the red blood cells far more tightly than oxygen does, so the blood can no longer carry enough oxygen to the brain and heart. One of the first effects is drowsiness, so sleeping people simply sink deeper into sleep. That is why so many victims are found in their beds.</p>

<h2>Where carbon monoxide comes from in Delhi NCR homes</h2>

<ul>
  <li>An <strong>angithi or sigri</strong> burning coal or wood in a closed room</li>
  <li><strong>Coal, kerosene or gas room heaters</strong> used without ventilation</li>
  <li>A <strong>gas geyser fitted inside a closed bathroom</strong></li>
  <li>A <strong>generator</strong> running indoors, in a closed shop or godown, or next to a window</li>
  <li>A <strong>car engine running</strong> in a closed garage or basement, or while someone sleeps inside the car</li>
  <li>Charcoal tandoors or barbecues used indoors, and blocked chimneys</li>
</ul>

<p>Security guards in small cabins, workers sleeping in shops or site huts and elderly people living alone are especially at risk, because they often use an angithi to stay warm through the night.</p>

<h2>Early warning signs of carbon monoxide poisoning</h2>

<p>Early symptoms are easy to mistake for flu, food poisoning or "just the cold":</p>

<ul>
  <li>Headache, often the first and most common sign</li>
  <li>Dizziness, weakness and tiredness</li>
  <li>Nausea or vomiting</li>
  <li>Confusion, difficulty thinking and unusual sleepiness</li>
  <li>Breathlessness, chest pain or a fast heartbeat</li>
  <li>Blurred vision and loss of balance</li>
</ul>

<p>With higher levels, the person may collapse, have a seizure or become unconscious. Cherry-red skin is sometimes described, but it appears late and often not at all, so don't wait for it.</p>

<div class="callout callout-info">
  <strong>Clues that point to carbon monoxide</strong>
  <p>Several people in the same room or house feel unwell at the same time. Pets are sick or unusually sleepy too. Symptoms are worse at home or in one particular room, get better after going outside, and appear when the heater, angithi, geyser or generator is on. If you notice any of these, get everyone into fresh air first and work out the cause later.</p>
</div>

<h2>How to rescue someone safely: step by step</h2>

<h3>Step 1: Protect yourself first</h3>

<p>Carbon monoxide can knock out a rescuer too, so take a deep breath of fresh air before you go in, <strong>hold your breath</strong> and move quickly. Throw open the doors and windows as you go. If the room is heavy with fumes or smoke, or you start to feel dizzy, get out. Never go in alone if it feels overwhelming: shout for neighbours or the society guard, so someone can pull you out if needed.</p>

<h3>Step 2: Get everyone out into fresh air</h3>

<p>Move the person, and everyone else in the house, outside or to a well-ventilated place such as a balcony, an open corridor or the ground floor. If you can't lift them, drag them on a sheet or blanket. Check every room for children, elderly relatives and pets.</p>

<h3>Step 3: Call 112 or an ambulance</h3>

<p>Say clearly: "Suspected carbon monoxide poisoning from an angithi (or heater)," then tell the dispatcher how many people are affected, whether anyone is unconscious and the address with a landmark. Ask for an ambulance with oxygen. If someone is unconscious or breathing poorly, an <a href="<?= link_to('icu') ?>">ICU ambulance with a critical care team</a> may be needed.</p>

<h3>Step 4: Turn off the source if it's safe</h3>

<p>Switch off the geyser or room heater, close the gas cylinder regulator or shut down the generator, but only if you can do it in seconds without breathing the fumes. Carry an angithi outside with tongs, or leave it where it is and keep the room open. Don't go back in for belongings.</p>

<h3>Step 5: Care for them in the fresh air</h3>

<ul>
  <li><strong>If they are awake</strong>: sit them up, loosen tight clothing and keep them calm and still. Don't let them walk around or go back inside to sleep.</li>
  <li><strong>Keep them warm</strong> with blankets or shawls. On a winter night, getting chilled outside is a real risk, especially for babies and elderly people.</li>
  <li><strong>If they are unconscious but breathing</strong>: put them in the recovery position. See our guide to <a href="<?= post_url('unconscious-person-first-aid') ?>">first aid for an unconscious person</a>.</li>
  <li><strong>If they are not breathing normally</strong>: start CPR straight away (see below).</li>
</ul>

<h3>Step 6: Get everyone checked in hospital</h3>

<p>Feeling better in fresh air does <strong>not</strong> mean the carbon monoxide has left the blood. The treatment is oxygen given in hospital, which clears CO from the body much faster than ordinary air. Everyone who was exposed should be checked, especially pregnant women (CO can harm the unborn baby), babies, elderly people and anyone with heart or lung disease.</p>

