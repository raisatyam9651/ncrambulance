<h2>How to prevent carbon monoxide poisoning in winter</h2>

<ul>
  <li><strong>Never sleep with an angithi, sigri, coal heater or gas heater burning in a closed room.</strong> Put it out completely and take it outside before anyone goes to sleep.</li>
  <li>Keep a window or door open whenever any fuel is burning indoors, and don't stuff cloth into air gaps and vents to keep the cold out.</li>
  <li>Prefer electric heaters, such as oil-filled radiators or fan heaters. They don't produce CO, though they should be kept away from curtains and bedding.</li>
  <li>Fit gas geysers <strong>outside the bathroom</strong>, or make sure the bathroom has a working exhaust fan or an open window. Avoid long hot baths with the door and window shut.</li>
  <li>Run generators outdoors, well away from doors and windows.</li>
  <li>Never run a car engine in a closed garage, or sleep in a parked car with the engine on.</li>
  <li>Install a battery-operated <strong>carbon monoxide alarm</strong> near bedrooms and test it regularly.</li>
  <li>Check on guards, domestic workers and elderly neighbours who use angithis to stay warm.</li>
</ul>

