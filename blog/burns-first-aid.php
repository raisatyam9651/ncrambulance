<h2>Why toothpaste, ghee, ice and butter make burns worse</h2>

<div class="callout callout-danger">
  <strong>Never put these on a burn</strong>
  <p>Toothpaste, ghee, butter, oil, haldi and ink don't cool a burn. Fats and oils hold the heat in the skin so it keeps burning. Pastes and powders contaminate the wound, can cause infection and hide how deep the burn is, so doctors have to scrub them off, which is painful for the patient. Ice and ice-cold water can damage burnt skin further and chill the body.</p>
</div>

<p>Blisters are the body's own sterile dressing. <strong>Don't burst them</strong>, and don't peel away loose skin, because breaking them opens the wound to infection. For more remedies like these that do more harm than good, see our guide to <a href="<?= post_url('first-aid-myths-india') ?>">first-aid myths in India</a>.</p>

<h2>How to know if a burn is serious</h2>

<p>Call an ambulance or go to hospital urgently if the burn:</p>

<ul>
  <li>is <strong>larger than the person's palm</strong></li>
  <li>is on the <strong>face, hands, feet or genitals</strong>, or over a <strong>joint</strong> such as the knee or elbow</li>
  <li>goes <strong>all the way round</strong> an arm, a leg or the chest</li>
  <li>looks <strong>deep</strong>: white, waxy, leathery, brown or charred, sometimes with little pain because the nerves are damaged</li>
  <li>was caused by <strong>electricity or chemicals</strong></li>
  <li>is on a <strong>child or an older person</strong>, a pregnant woman, or someone with diabetes or another long-term illness</li>
</ul>

<p>Also call for help straight away if the person was in a fire in a closed space and has a <strong>hoarse voice, a cough, noisy breathing, soot around the nose or mouth, or singed nostril hair</strong>. These are signs that hot smoke may have burnt the airway, which can swell and close over the next few hours. Read our guide to <a href="<?= post_url('smoke-inhalation-fire-emergency') ?>">smoke inhalation in a fire</a>.</p>

