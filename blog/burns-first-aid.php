<h2>Chemical, electrical and firecracker burns</h2>

<h3>Chemical burns</h3>

<p>Acids, toilet cleaners, drain cleaners, lime (chuna) and wet cement can all burn the skin. Protect your own hands with gloves. <strong>Brush off any dry powder</strong> first, remove contaminated clothing and jewellery, then <strong>flush the area with plenty of running water for at least 20 minutes</strong>. Don't try to neutralise the chemical with another substance.</p>

<p>If a chemical gets into an eye, rinse it under gently running water for at least 20 minutes. Hold the eyelids open and tilt the head so the water runs away from the other eye, then go to hospital.</p>

<h3>Electrical burns</h3>

<p>Never touch someone who is still in contact with electricity: switch off the power at the main switch or MCB first. Electrical burns may look small on the skin but can cause deep damage inside the body and upset the heartbeat, so every electrical burn needs a hospital check. See our full guide to <a href="<?= post_url('electric-shock-first-aid') ?>">electric shock first aid</a>.</p>

<h3>Firecracker burns on Diwali</h3>

<p>Cool the burn as above, and take rings off burnt fingers quickly before they swell. Check the hands and fingers carefully, and <strong>check the eyes</strong>.</p>

<p>If powder or smoke has gone into an eye, rinse it gently with clean running water. If something may be stuck in the eye or the eye is cut, don't rub, press or rinse it: cover it loosely with a clean paper cup and go to hospital. Our <a href="<?= post_url('eye-injury-first-aid') ?>">eye injury first aid guide</a> has more detail.</p>

<h2>If things get worse: breathing trouble, shock or collapse</h2>

<p>People with large burns can go into shock as fluid leaks from the damaged skin. Watch for pale, cold, clammy skin away from the burn, a fast weak pulse, fast breathing, confusion or drowsiness. Lay them down, keep them warm and call the dispatcher again.</p>

<p>If breathing becomes noisy or difficult after smoke exposure, help them sit upright in fresh air and tell the dispatcher at once. If they become unresponsive and stop breathing normally, start CPR straight away and continue until the ambulance crew takes over. Our <a href="<?= post_url('how-to-do-cpr') ?>">hands-only CPR guide</a> shows how.</p>

