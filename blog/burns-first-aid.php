<p>Hot oil splashes from the kadhai, a pressure cooker lid bursts open, a toddler pulls a cup of tea off the table, or an anaar flares up in a child's hand on Diwali night. Within seconds someone runs for toothpaste, ghee or a bottle of ink, because that is what their grandmother did. These remedies trap heat in the skin and can make the burn deeper.</p>

<p>This guide explains what actually works: cooling the burn the right way and for long enough, covering it safely, and knowing when a burn is serious enough to call an <a href="<?= link_to('emergency') ?>">emergency ambulance for burn injuries</a>. It also covers chemical, electrical and firecracker burns, and kitchen fires.</p>

<h2>Burns first aid: step by step</h2>

<h3>Step 1: Stop the burning</h3>

<p>Get the person away from the heat. If their clothes catch fire, they must <strong>stop, drop and roll</strong>: stop moving, drop to the ground, cover the face with the hands and roll over and over to smother the flames. You can also smother flames with a heavy cotton or woollen blanket, or put them out with water. Running fans the flames.</p>

<p>In a kitchen fire, switch off the gas at the stove and at the cylinder regulator only if you can reach them safely. Never throw water on a burning kadhai of oil: cover it with a well-fitting lid and turn off the gas. If you smell gas, don't switch any lights or appliances on or off; open the doors and windows, turn off the regulator and get out. If a fire is spreading, get everyone out and call 112.</p>

<h3>Step 2: Call for help if the burn is serious</h3>

<p>Call <strong>112</strong> or our helpline (<a href="<?= BLOG_TEL ?>"><?= BLOG_PHONE ?></a>) for any serious burn (see the list below) and for anyone who was caught in a fire or a smoke-filled room. For a large burn or any breathing trouble, ask for an <a href="<?= link_to('als') ?>">ALS ambulance with oxygen support</a>. Start cooling the burn while you wait.</p>

<h3>Step 3: Cool the burn with running water for 20 minutes</h3>

<p>Hold the burnt area under <strong>cool running tap water for 20 minutes</strong>. Watch the clock, because 20 minutes feels very long. Cooling stops the heat damaging deeper layers, eases pain and swelling, and can help the burn heal better. It is still worth doing up to three hours after the burn.</p>

<p>If there is no tap nearby, use a shower, pour water continuously from a bucket and mug, or use bottled drinking water. The water should be cool, not ice-cold. Cool the burn, not the whole person.</p>

<h3>Step 4: Remove rings, watches and loose clothing</h3>

<p>Burnt skin swells quickly. While you cool the burn, gently take off rings, bangles, watches, belts, shoes and any clothing near the burn. If clothing is stuck to the skin, leave it and cut around it, because pulling it off tears the skin.</p>

<h3>Step 5: Cover the burn loosely</h3>

<p>After cooling, cover the burn to protect it from germs and air, which also eases the pain. <strong>Cling film</strong> (kitchen food wrap) is ideal: lay it over the burn in strips rather than wrapping it tightly around a limb, because the area will swell. A clean plastic bag works well for a burnt hand.</p>

<p>If you have neither, use a clean, non-fluffy cotton cloth or pillowcase. Don't use cotton wool or fluffy towels, which stick to the wound. Don't use adhesive plasters on burnt skin.</p>

<h3>Step 6: Keep the person warm</h3>

<p>Cool the burn, but keep the person warm. Large burns and long cooling can lower body temperature quickly, especially in children, older people and in winter. Cover the rest of their body with a blanket and watch their breathing until help arrives.</p>

