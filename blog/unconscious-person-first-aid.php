<h2>Fainting or unconsciousness: what's the difference?</h2>

<p>Fainting is a brief loss of consciousness caused by a sudden, short drop in blood flow to the brain. It is common in the heat, after standing for a long time, during a fast, at the sight of blood, or with sudden fear or pain. People usually feel it coming: dizziness, nausea, sweating, blurred vision or ringing in the ears.</p>

<p>Unconsciousness that lasts longer is a different matter. It can be caused by a head injury, a stroke, a seizure, very low blood sugar, a heart rhythm problem, poisoning, alcohol, heat stroke or a lack of oxygen. You don't need to know the cause to help, because the first steps are the same. If the person is stiff or jerking, follow our <a href="<?= post_url('seizure-first-aid') ?>">seizure first aid steps</a> first.</p>

