<h2>If they are not breathing normally: start CPR</h2>

<p>If the person is unresponsive and <strong>not breathing normally</strong>, their heart has probably stopped. This is a cardiac arrest, and every minute without CPR lowers the chance of survival. Don't wait for the ambulance to begin.</p>

<ol>
  <li>Make sure the dispatcher knows the person is not breathing. They can coach you through CPR on the phone.</li>
  <li>Place the heel of one hand in the centre of the chest, the other hand on top, arms straight.</li>
  <li>Push hard (about 5 to 6 cm deep) and fast (100 to 120 pushes a minute), letting the chest rise fully between pushes.</li>
  <li>Send someone to fetch an AED (defibrillator) if there's one in the building, switch it on and follow its voice prompts.</li>
  <li>Keep going until the ambulance crew takes over, the person starts breathing normally, or you're too exhausted to continue.</li>
</ol>

