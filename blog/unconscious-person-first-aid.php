<h2>First aid for fainting</h2>

<p>If someone feels faint, or has just fainted and is breathing normally:</p>

<ul>
  <li><strong>Lay them flat on their back</strong> on the floor. Don't try to sit them up or hold them upright.</li>
  <li><strong>Raise their legs</strong> on a chair, stool or a pile of cushions to help blood flow back to the brain, unless you think the legs, hips or back are injured.</li>
  <li>Loosen tight clothing and ask the crowd to step back so they get fresh air.</li>
  <li>Most people come round within a minute or two. Help them sit up slowly, and let them stand only once they feel steady.</li>
  <li>Once they're fully awake and can swallow normally, a few sips of water are fine, especially in Delhi's summer heat.</li>
</ul>

<p>If they don't come round within a minute or two, treat them as unconscious: call an ambulance and follow the checks above. Also call if they were hurt in the fall, have chest pain, palpitations or breathlessness, fainted during exercise or while lying down, or are pregnant. Anyone who faints for the first time without an obvious reason should see a doctor the same day. For a patient who has recovered and is stable, a <a href="<?= link_to('bls') ?>">BLS ambulance with oxygen and a stretcher</a> can take them to hospital safely.</p>

<h2>Should you splash water or give them something to drink?</h2>

<p>It's the first thing many people do, but it doesn't help. Water splashed on the face won't treat the cause, and a semi-conscious person may breathe it in. Pouring water, juice, tea or sugar into the mouth of someone who can't swallow properly can choke them or cause a serious chest infection.</p>

<div class="callout callout-danger">
  <strong>Don't do these</strong>
  <p>Don't slap or shake the person, rub their palms and soles, make them smell an onion or a shoe, or prop them up in a chair. Sitting an unconscious person upright lets the head flop forward and block the airway, and keeps blood away from the brain in a faint. Keep the space clear: a crowd blocks fresh air and makes it harder to help.</p>
</div>

<p>If the person has diabetes, think of <strong>low blood sugar</strong>. Don't put sugar or glucose in the mouth of anyone who isn't fully awake. Call an ambulance and tell the dispatcher they're diabetic, so the crew can check their sugar and give glucose safely. Once they're awake and able to swallow, follow our guide on <a href="<?= post_url('low-blood-sugar-hypoglycemia-emergency') ?>">treating low blood sugar in an emergency</a>.</p>

<h2>What to tell the ambulance crew</h2>

<p>The crew will want to piece together what happened. Try to note:</p>

<ul>
  <li>what the person was doing just before they collapsed, and whether they complained of anything,</li>
  <li>how long they were unconscious, and whether there was any jerking or a fall,</li>
  <li>any medical conditions, such as diabetes, epilepsy or heart disease, and a list of their medicines,</li>
  <li>whether they might have taken alcohol, drugs or anything poisonous, and</li>
  <li>a sugar reading, if someone has a glucometer and has checked it.</li>
</ul>

