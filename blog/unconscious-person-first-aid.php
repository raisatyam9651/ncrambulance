<h2>How to check an unconscious person: step by step</h2>

<p>First aiders remember the order as <strong>Danger, Response, Airway, Breathing</strong>. Work through it calmly.</p>

<h3>Step 1: Check for danger</h3>

<p>Before you go near, look around. Is there traffic, a live electric wire, a smell of gas, fire or smoke? Don't become a second patient. If the area is unsafe and you can't make it safe, keep your distance and call for help. Only move the person if staying where they are would put their life at risk.</p>

<h3>Step 2: Check for a response</h3>

<p>Kneel beside them, tap their shoulders firmly and shout, "Can you hear me? Open your eyes!" Use their name if you know it. A person who opens their eyes, speaks or moves in response is responsive. A person who doesn't react at all is unresponsive and needs your help now.</p>

<h3>Step 3: Shout for help and call an ambulance</h3>

<p>Shout for anyone nearby to come. Ask one person to call <strong>112</strong> or a 24/7 ambulance helpline such as ours (<a href="<?= BLOG_TEL ?>"><?= BLOG_PHONE ?></a>) and put the phone on speaker beside you. If you're alone, make the call yourself on speaker so your hands stay free. Say clearly: "Adult unconscious, not responding," and give the full address with a landmark. For someone who has collapsed suddenly, ask for an <a href="<?= link_to('als') ?>">Advanced Life Support ambulance with cardiac monitoring</a>.</p>

<h3>Step 4: Open the airway</h3>

<p>When an unconscious person lies on their back, the tongue can fall back and block the throat. To open the airway, use the <strong>head-tilt, chin-lift</strong>: place one hand on their forehead and gently tilt the head back, then put two fingertips under the bony tip of the chin and lift it. If you can see something in the mouth, such as vomit or food, remove it only if you can pick it out easily. Don't sweep your fingers around blindly.</p>

<h3>Step 5: Check breathing for up to 10 seconds</h3>

<p>Keep the airway open and put your cheek close to their mouth while you watch the chest. <strong>Look</strong> for the chest rising, <strong>listen</strong> for breath sounds and <strong>feel</strong> for breath on your cheek, for no more than 10 seconds. Occasional gasps, snorts or gurgles are <strong>not normal breathing</strong>. They often happen in the first minutes after the heart stops.</p>

<h3>Step 6: Choose the recovery position or CPR</h3>

<ul>
  <li><strong>Breathing normally</strong>: put them in the recovery position (below) and keep checking their breathing.</li>
  <li><strong>Not breathing normally, or you're not sure</strong>: start CPR straight away.</li>
</ul>

<h2>How to put someone in the recovery position</h2>

<p>The recovery position keeps the airway open and lets vomit or saliva drain out of the mouth instead of into the lungs. For an adult lying on their back:</p>

<ol>
  <li>Kneel beside them. Remove their spectacles and anything bulky from their pockets.</li>
  <li>Place the arm nearest you at a right angle to the body, elbow bent and palm facing up.</li>
  <li>Bring the far arm across the chest and hold the back of that hand against the cheek nearest you.</li>
  <li>With your other hand, pull the far knee up so that foot is flat on the floor.</li>
  <li>Keeping their hand pressed to the cheek, pull on the bent knee to roll them towards you onto their side.</li>
  <li>Adjust the top leg so the hip and knee are bent at right angles. This stops them rolling onto their face.</li>
  <li>Tilt the head back slightly and lift the chin so the airway stays open.</li>
  <li>Keep checking that they are breathing normally until the ambulance arrives.</li>
</ol>

<p>If an unconscious woman is pregnant, place her on her <strong>left side</strong>. If you have a long wait, turn the person onto their other side after about 30 minutes to protect the arm underneath. If at any point their breathing becomes abnormal or stops, roll them onto their back and start CPR.</p>

<p>If they might have hurt their neck or back, for example in a fall from a height or a road accident, keep them still as long as they are breathing and the airway is clear. Turn them only if they vomit or you have to leave them, keeping the head, neck and body in a straight line as you roll. Our guide to <a href="<?= post_url('spinal-injury-first-aid') ?>">spinal injury first aid</a> explains how.</p>

